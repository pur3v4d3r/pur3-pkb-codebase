# Wiki-link pattern. Captures the inner reference. Excludes [[ and ]] inside.
# Optional leading "!" is captured separately via lookbehind handling in code.
WIKILINK_RE = re.compile(r"(!?)\[\[([^\[\]\n]+?)\]\]")

# Strip fenced code blocks (```...```) and inline code (`...`) before parsing.
FENCED_CODE_RE = re.compile(r"```.*?```", re.DOTALL)
INLINE_CODE_RE = re.compile(r"`[^`\n]+`")

# Folders to skip when building the vault index (large/auto-generated).
DEFAULT_INDEX_EXCLUDES: tuple[str, ...] = (
    ".git", ".obsidian", ".trash", ".venv", "node_modules",
    "__pycache__", ".cache", ".vscode",
)

DEFAULT_SCAN_EXCLUDES: tuple[str, ...] = DEFAULT_INDEX_EXCLUDES


