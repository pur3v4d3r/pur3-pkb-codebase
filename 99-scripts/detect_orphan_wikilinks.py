def to_kebab_case(text: str) -> str:
    """Normalize a string to kebab-case.

    Lowercases, replaces underscores/spaces with hyphens, strips characters
    outside ``[a-z0-9-]``, and collapses repeated hyphens.

    Args:
        text: Arbitrary string (typically a note basename without extension).

    Returns:
        The kebab-cased form.

    Example:
        >>> to_kebab_case("My Note Title_v2")
        'my-note-title-v2'
    """
    s = text.strip().lower()
    s = re.sub(r"[\s_]+", "-", s)
    s = re.sub(r"[^a-z0-9\-]+", "", s)
    s = re.sub(r"-{2,}", "-", s).strip("-")
    return s


def strip_code(text: str) -> str:
    """Remove fenced and inline code regions from Markdown text.

    Wiki-links inside code should not be treated as real links.
    """
    text = FENCED_CODE_RE.sub("", text)
    text = INLINE_CODE_RE.sub("", text)
    return text


def parse_wikilink_inner(inner: str) -> tuple[str, str | None, str | None, str | None, bool]:
    """Parse the inner content of a wiki-link.

    Args:
        inner: Text between ``[[`` and ``]]``, e.g. ``"folder/Note#H|Alias"``.

    Returns:
        Tuple of ``(target, alias, heading, block, is_path)``.
    """
    alias: str | None = None
    heading: str | None = None
    block: str | None = None

    if "|" in inner:
        inner, alias = inner.split("|", 1)
        alias = alias.strip()

    if "^" in inner:
        inner, block = inner.split("^", 1)
        block = block.strip()
    elif "#" in inner:
        inner, heading = inner.split("#", 1)
        heading = heading.strip()

    target = inner.strip()
    is_path = "/" in target
    return target, alias, heading, block, is_path


def extract_wikilinks(file_path: Path, vault_root: Path) -> list[WikiLink]:
    """Extract all wiki-links from a single Markdown file.

    Args:
        file_path: Absolute path to the Markdown file.
        vault_root: Absolute path to the vault root (for relative paths in output).

    Returns:
        List of ``WikiLink`` records (one per occurrence).
    """
    try:
        text = file_path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        logger.warning("Skipping non-UTF-8 file: %s", file_path)
        return []

    cleaned = strip_code(text)
    rel = file_path.relative_to(vault_root)

    # Build a map of cleaned-text offset → original line number.
    # Simpler approach: re-scan original line-by-line (code-strip on whole-file
    # could shift line numbers; per-line stripping preserves them).
    links: list[WikiLink] = []
    in_fence = False
    for lineno, raw_line in enumerate(text.splitlines(), start=1):
        stripped = raw_line.lstrip()
        if stripped.startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        line_no_inline = INLINE_CODE_RE.sub("", raw_line)

        for match in WIKILINK_RE.finditer(line_no_inline):
            bang, inner = match.group(1), match.group(2)
            target, alias, heading, block, is_path = parse_wikilink_inner(inner)
            if not target:
                continue
            links.append(WikiLink(
                source_file=rel,
                line_number=lineno,
                raw=inner,
                target=target,
                alias=alias,
                heading=heading,
                block=block,
                is_embed=(bang == "!"),
                is_path=is_path,
            ))
    _ = cleaned  # cleaned retained for potential future whole-file analysis
    return links


def build_vault_index(
    vault_root: Path,
    excludes: Iterable[str] = DEFAULT_INDEX_EXCLUDES,
) -> tuple[dict[str, list[Path]], set[str]]:
    """Build an index of all Markdown notes in the vault.

    Args:
        vault_root: Absolute path to the vault root.
        excludes: Folder names to skip (matched anywhere in path).

    Returns:
        Tuple of:
          - ``{lowercased_basename: [relative_paths]}`` — for basename matching.
          - Set of lowercased relative paths (POSIX, no extension) — for path matching.
    """
    excludes_set = set(excludes)
    by_basename: dict[str, list[Path]] = defaultdict(list)
    by_path: set[str] = set()

    for md in vault_root.rglob("*.md"):
        if any(part in excludes_set for part in md.parts):
            continue
        rel = md.relative_to(vault_root)
        by_basename[md.stem.lower()].append(rel)
        by_path.add(rel.with_suffix("").as_posix().lower())

    logger.info("Indexed %d notes (%d unique basenames)",
                sum(len(v) for v in by_basename.values()), len(by_basename))
    return dict(by_basename), by_path


def is_orphan(link: WikiLink, by_basename: dict[str, list[Path]], by_path: set[str]) -> bool:
    """Return True if the link's target does not exist in the vault index.

    Resolution order (Obsidian-like):
      1. If the target contains a path separator, match against full path index.
      2. Otherwise, match by basename (case-insensitive).
    """
    if link.is_path:
        return link.target.lower() not in by_path
    return link.target.lower() not in by_basename


def scan_folder(
    scan_folder_path: Path,
    vault_root: Path,
    by_basename: dict[str, list[Path]],
    by_path: set[str],
    include_embeds: bool,
    excludes: Iterable[str] = DEFAULT_SCAN_EXCLUDES,
) -> ScanResult:
    """Scan a folder for orphan wiki-links.

    Args:
        scan_folder_path: Absolute path to the folder to scan.
        vault_root: Absolute path to the vault root.
        by_basename: Vault basename index.
        by_path: Vault path index.
        include_embeds: If False, ``![[...]]`` embeds are skipped.
        excludes: Folder names to skip during the scan.

    Returns:
        ``ScanResult`` aggregating files scanned, links found, and orphans.
    """
    excludes_set = set(excludes)
    result = ScanResult()

    for md in scan_folder_path.rglob("*.md"):
        if any(part in excludes_set for part in md.parts):
            continue
        result.files_scanned += 1
        for link in extract_wikilinks(md, vault_root):
            if link.is_embed and not include_embeds:
                continue
            result.links_found += 1
            if is_orphan(link, by_basename, by_path):
                result.orphans.append(link)

    logger.info("Scanned %d files, found %d links, %d orphans",
                result.files_scanned, result.links_found, len(result.orphans))
    return result


