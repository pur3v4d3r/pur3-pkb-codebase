def render_markdown_report(
    result: ScanResult,
    scan_folder_rel: Path,
    vault_root: Path,
    suggest_kebab: bool,
) -> str:
    """Render a Markdown report of orphan wiki-links.

    Args:
        result: Scan result to render.
        scan_folder_rel: Folder that was scanned (relative to vault root).
        vault_root: Vault root (used for context only).
        suggest_kebab: If True, include suggested kebab-case rewrites.

    Returns:
        Markdown string ready to be written to a file or stdout.
    """
    from datetime import datetime

    lines: list[str] = []
    lines.append("# Orphan Wiki-Links Report")
    lines.append("")
    lines.append(f"- **Scanned folder:** `{scan_folder_rel.as_posix()}`")
    lines.append(f"- **Vault root:** `{vault_root.name}`")
    lines.append(f"- **Generated:** {datetime.now().isoformat(timespec='seconds')}")
    lines.append(f"- **Files scanned:** {result.files_scanned}")
    lines.append(f"- **Wiki-links found:** {result.links_found}")
    lines.append(f"- **Orphan links:** {len(result.orphans)}")
    lines.append("")

    if not result.orphans:
        lines.append("> [!success] No orphan wiki-links detected.")
        lines.append("")
        return "\n".join(lines)

    # Group by source file.
    by_file: dict[Path, list[WikiLink]] = defaultdict(list)
    for link in result.orphans:
        by_file[link.source_file].append(link)

    lines.append("## Summary by File")
    lines.append("")
    lines.append("| File | Orphan Count |")
    lines.append("|------|--------------|")
    for src in sorted(by_file.keys(), key=lambda p: p.as_posix()):
        lines.append(f"| `{src.as_posix()}` | {len(by_file[src])} |")
    lines.append("")

    lines.append("## Detailed Findings")
    lines.append("")
    for src in sorted(by_file.keys(), key=lambda p: p.as_posix()):
        lines.append(f"### `{src.as_posix()}`")
        lines.append("")
        header = "| Line | Wiki-Link | Target | Alias | Heading | Embed |"
        sep = "|------|-----------|--------|-------|---------|-------|"
        if suggest_kebab:
            header = header[:-1] + " Suggested (kebab-case) |"
            sep = sep[:-1] + "-------------------------|"
        lines.append(header)
        lines.append(sep)
        for link in sorted(by_file[src], key=lambda L: L.line_number):
            row = (
                f"| {link.line_number} "
                f"| `[[{link.raw}]]` "
                f"| `{link.target}` "
                f"| {link.alias or ''} "
                f"| {link.heading or ''} "
                f"| {'yes' if link.is_embed else ''} |"
            )
            if suggest_kebab:
                row = row[:-1] + f" `{to_kebab_case(link.target)}` |"
            lines.append(row)
        lines.append("")

    if suggest_kebab:
        lines.append("> [!note] Suggestions are **not applied**. "
                     "Per vault policy, any link normalization must use kebab-case. "
                     "Review each suggestion before adopting it.")
        lines.append("")

    return "\n".join(lines)


