def write_manifest(
    batch: TermListBatch,
    *,
    accepted: list[tuple[ParsedTerm, Path, DedupDecision]],
    skipped: list[DedupDecision],
    warnings: list[str],
    briefs_dir: Path,
    seeds_dir: Path,
) -> Path:
    """Write the manifest.json describing this batch."""
    briefs_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = briefs_dir / "manifest.json"
    batch_date_obj = _date.fromisoformat(batch.batch_date)

    def _rel(p: Path) -> str:
        try:
            return str(p.resolve().relative_to(_HERE)).replace("\\", "/")
        except ValueError:
            return str(p.resolve()).replace("\\", "/")

    entries = [
        ManifestEntry(
            term=t.term,
            kebab=ssb.to_kebab(t.term),
            brief_path=_rel(brief),
            expected_seed_filename=ssb.filename_for(
                {"concept": t.term}, batch_date=batch_date_obj,
            ),
        )
        for (t, brief, _decision) in accepted
    ]
    payload: dict[str, Any] = {
        "manifest_version": "1.0.0",
        "expand_term_list_version": __version__,
        "batch": {
            "name": batch.batch_name,
            "date": batch.batch_date,
            "source_term_list": str(batch.source_path).replace("\\", "/"),
            "notes": batch.notes,
        },
        "paths": {
            "briefs_dir": str(briefs_dir.resolve()).replace("\\", "/"),
            "seeds_dir": str(seeds_dir.resolve()).replace("\\", "/"),
        },
        "counts": {
            "parsed": len(accepted) + len(skipped),
            "accepted": len(accepted),
            "skipped": len(skipped),
            "warnings": len(warnings),
        },
        "entries": [dataclasses.asdict(e) for e in entries],
        "skipped": [dataclasses.asdict(d) for d in skipped],
        "warnings": warnings,
    }
    # Path objects need to be stringified for json.dumps.
    for d in payload["skipped"]:
        d["note_path"] = str(d["note_path"]).replace("\\", "/")
    tmp = manifest_path.with_suffix(manifest_path.suffix + ".tmp")
    tmp.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    tmp.replace(manifest_path)
    return manifest_path


def load_manifest(path: Path) -> dict[str, Any]:
    """Load and minimally validate a manifest.json file."""
    if not path.exists():
        raise ManifestError(f"manifest not found: {path}")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ManifestError(f"manifest is not valid JSON: {exc}") from exc
    for required in ("manifest_version", "batch", "paths", "entries"):
        if required not in data:
            raise ManifestError(f"manifest missing required key: {required!r}")
    return data


