def build_parser() -> argparse.ArgumentParser:
    """Construct the argparse parser."""
    parser = argparse.ArgumentParser(
        prog="expand_term_list",
        description=(
            "Convert a Markdown term list into a batch of YAML briefs and "
            "synthetic *_extracted.json seeds for the V6 permanent-note "
            "pipeline."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "Examples:\n"
            "  expand_term_list.py -v expand term-lists/2026-04-24-cluster.md\n"
            "  expand_term_list.py -v expand --dry-run term-lists/foo.md\n"
            "  expand_term_list.py -v build-batch briefs/2026-04-24-cluster/manifest.json\n"
            "  expand_term_list.py -v run term-lists/2026-04-24-cluster.md\n"
        ),
    )
    parser.add_argument("--version", action="version",
                        version=f"%(prog)s {__version__}")
    parser.add_argument("-v", "--verbose", action="count", default=0,
                        help="increase logging verbosity (repeatable)")
    parser.add_argument("-q", "--quiet", action="store_true",
                        help="suppress non-error output")

    sub = parser.add_subparsers(dest="command", metavar="COMMAND", required=True)

    # ---- expand ----
    p_exp = sub.add_parser("expand", help="parse a term list -> briefs + manifest")
    p_exp.add_argument("list_path", help="path to a term-list Markdown file")
    p_exp.add_argument(
        "--briefs-dir",
        default=str(DEFAULT_BRIEFS_ROOT),
        help=f"root directory for generated briefs "
             f"(default: {DEFAULT_BRIEFS_ROOT})",
    )
    p_exp.add_argument(
        "--seeds-dir",
        default=str(DEFAULT_SEEDS_ROOT),
        help=f"root directory for generated seeds "
             f"(default: {DEFAULT_SEEDS_ROOT})",
    )
    p_exp.add_argument(
        "--permanent-notes-dir",
        default=str(DEFAULT_PERMANENT_NOTES_DIR),
        help=f"directory holding finished permanent notes (used for the "
             f"dedup gate; default: {DEFAULT_PERMANENT_NOTES_DIR})",
    )
    p_exp.add_argument(
        "--overwrite-existing", action="store_true",
        help="accept terms even if a permanent note already exists",
    )
    p_exp.add_argument(
        "--overwrite-briefs", action="store_true",
        help="overwrite existing brief files in the briefs dir",
    )
    p_exp.add_argument(
        "-n", "--dry-run", action="store_true",
        help="parse and dedup; print what would be written; produce no files",
    )
    p_exp.set_defaults(func=cmd_expand)

    # ---- build-batch ----
    p_build = sub.add_parser(
        "build-batch", help="materialize seeds from a manifest.json",
    )
    p_build.add_argument("manifest_path", help="path to a manifest.json")
    p_build.add_argument(
        "--overwrite-seeds", action="store_true",
        help="pass --overwrite to synth_seed_builder for each brief",
    )
    p_build.add_argument(
        "-n", "--dry-run", action="store_true",
        help="invoke seed builder in dry-run mode (no files written)",
    )
    p_build.set_defaults(func=cmd_build_batch)

    # ---- run ----
    p_run = sub.add_parser(
        "run", help="convenience: expand + build-batch in one invocation",
    )
    p_run.add_argument("list_path", help="path to a term-list Markdown file")
    p_run.add_argument(
        "--briefs-dir",
        default=str(DEFAULT_BRIEFS_ROOT),
        help=f"root directory for generated briefs "
             f"(default: {DEFAULT_BRIEFS_ROOT})",
    )
    p_run.add_argument(
        "--seeds-dir",
        default=str(DEFAULT_SEEDS_ROOT),
        help=f"root directory for generated seeds "
             f"(default: {DEFAULT_SEEDS_ROOT})",
    )
    p_run.add_argument(
        "--permanent-notes-dir",
        default=str(DEFAULT_PERMANENT_NOTES_DIR),
        help=f"dedup-gate target dir (default: {DEFAULT_PERMANENT_NOTES_DIR})",
    )
    p_run.add_argument(
        "--overwrite-existing", action="store_true",
        help="accept terms even if a permanent note already exists",
    )
    p_run.add_argument(
        "--overwrite-briefs", action="store_true",
        help="overwrite existing brief files",
    )
    p_run.add_argument(
        "--overwrite-seeds", action="store_true",
        help="overwrite existing seed files",
    )
    p_run.add_argument(
        "-n", "--dry-run", action="store_true",
        help="run expand in dry-run mode and skip build-batch",
    )
    p_run.set_defaults(func=cmd_run)

    return parser


def configure_logging(verbosity: int, quiet: bool) -> None:
    """Configure root logger from CLI verbosity flags."""
    if quiet:
        level = logging.ERROR
    elif verbosity >= 2:
        level = logging.DEBUG
    elif verbosity == 1:
        level = logging.INFO
    else:
        level = logging.WARNING
    logging.basicConfig(
        level=level,
        format="%(asctime)s [%(levelname)s] %(message)s",
        datefmt="%H:%M:%S",
    )


def main(argv: Sequence[str] | None = None) -> int:
    """Main entry point.

    Args:
        argv: Argument vector (defaults to ``sys.argv[1:]``).

    Returns:
        Exit code (0 = success; 2 = file-not-found; 4 = parse/validation
        failure; 5 = manifest error; 130 = interrupted; 1 = unhandled).
    """
    parser = build_parser()
    args = parser.parse_args(argv)
    configure_logging(args.verbose, args.quiet)

    try:
        return args.func(args)
    except FileNotFoundError as exc:
        logger.error("File not found: %s", exc)
        return 2
    except TermListParseError as exc:
        logger.error("Term-list parse error: %s", exc)
        return 4
    except ManifestError as exc:
        logger.error("Manifest error: %s", exc)
        return 5
    except DedupGateError as exc:
        logger.error("Dedup gate error: %s", exc)
        return 4
    except KeyboardInterrupt:
        logger.warning("Interrupted by user")
        return 130
    except Exception:
        logger.exception("Unexpected error")
        return 1


