def _term_to_brief_dict(term: ParsedTerm) -> dict[str, Any]:
    """Build the YAML-brief dict for one term.

    Each callout is constructed so that the term name appears in the title,
    satisfying V4's substring-discipline rule by construction.
    """
    name = term.term
    callouts: list[dict[str, str]] = [
        {
            "type": "definition",
            "title": name,
            "body": term.definition,
        }
    ]
    if term.key_claim:
        callouts.append({
            "type": "key-claim",
            "title": f"Key claim about {name}",
            "body": term.key_claim,
        })
    if term.warning:
        callouts.append({
            "type": "warning",
            "title": f"Common pitfall regarding {name}",
            "body": term.warning,
        })

    brief: dict[str, Any] = {
        "concept": name,
        "domain": term.domain,
        "secondary_domains": term.secondary_domains,
        "aliases": term.aliases,
        "broader": term.broader,
        "narrower": term.narrower,
        "related": term.related,
        "prerequisites": term.prerequisites,
        "confidence": term.confidence,
        "callouts": callouts,
    }
    # Strip empty optional collections to keep the brief tidy.
    for k in (
        "secondary_domains",
        "aliases",
        "broader",
        "narrower",
        "related",
        "prerequisites",
    ):
        if not brief[k]:
            brief.pop(k)
    return brief


def write_brief(
    term: ParsedTerm,
    *,
    briefs_dir: Path,
    overwrite: bool,
) -> Path:
    """Serialize a term's brief to YAML in ``briefs_dir``."""
    briefs_dir.mkdir(parents=True, exist_ok=True)
    brief_path = briefs_dir / f"{ssb.to_kebab(term.term)}.yaml"
    if brief_path.exists() and not overwrite:
        raise FileExistsError(brief_path)
    payload = _term_to_brief_dict(term)
    text = yaml.safe_dump(payload, sort_keys=False, allow_unicode=True)
    tmp = brief_path.with_suffix(brief_path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(brief_path)
    return brief_path


