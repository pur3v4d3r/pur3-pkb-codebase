def cmd_expand(args: argparse.Namespace) -> int:
    """Parse a term list, run dedup, write briefs + manifest."""
    list_path = Path(args.list_path).resolve()
    batch = parse_term_list(list_path)
    logger.info(
        "Parsed %d term(s) from %s (batch=%s, date=%s)",
        len(batch.terms), list_path.name, batch.batch_name, batch.batch_date,
    )

    permanent_dir = Path(args.permanent_notes_dir).resolve()
    decisions = evaluate_dedup(
        batch.terms,
        permanent_notes_dir=permanent_dir,
        overwrite_existing=args.overwrite_existing,
    )
    accepted_decisions = [d for d in decisions if d.decision == "accept"]
    skipped_decisions = [d for d in decisions if d.decision == "skip"]
    accepted_terms = [
        t for t, d in zip(batch.terms, decisions) if d.decision == "accept"
    ]
    logger.info(
        "Dedup: %d accepted, %d skipped (existing notes)",
        len(accepted_decisions), len(skipped_decisions),
    )
    for d in skipped_decisions:
        logger.info("  SKIP %s -> %s", d.term, d.reason)

    briefs_dir = Path(args.briefs_dir).resolve() / batch.batch_name
    seeds_dir = (
        Path(args.seeds_dir).resolve() / f"{batch.batch_date}-{batch.batch_name}"
    )

    if args.dry_run:
        logger.info("[dry-run] Would write %d brief(s) to %s",
                    len(accepted_terms), briefs_dir)
        logger.info("[dry-run] Would target seeds dir %s", seeds_dir)
        for t in accepted_terms:
            logger.info("[dry-run]   brief: %s.yaml", ssb.to_kebab(t.term))
        return 0

    warnings: list[str] = []
    accepted_with_paths: list[tuple[ParsedTerm, Path, DedupDecision]] = []
    for term, decision in zip(batch.terms, decisions):
        if decision.decision != "accept":
            continue
        if not term.key_claim:
            warnings.append(
                f"{term.term}: no 'key_claim' supplied — seed will have only "
                "definition + warning callouts"
            )
        if not term.warning:
            warnings.append(
                f"{term.term}: no 'warning' supplied — seed will have only "
                "definition + key_claim callouts"
            )
        try:
            brief_path = write_brief(
                term, briefs_dir=briefs_dir, overwrite=args.overwrite_briefs,
            )
        except FileExistsError as exc:
            logger.error(
                "Brief already exists: %s (use --overwrite-briefs to replace)",
                exc,
            )
            return 4
        logger.info("Wrote brief: %s", brief_path)
        accepted_with_paths.append((term, brief_path, decision))

    manifest_path = write_manifest(
        batch,
        accepted=accepted_with_paths,
        skipped=skipped_decisions,
        warnings=warnings,
        briefs_dir=briefs_dir,
        seeds_dir=seeds_dir,
    )
    logger.info("Manifest written: %s", manifest_path)

    if warnings:
        for w in warnings:
            logger.warning("MANIFEST WARNING: %s", w)
    print(
        f"=== expand summary: parsed={len(batch.terms)} "
        f"accepted={len(accepted_with_paths)} skipped={len(skipped_decisions)} "
        f"warnings={len(warnings)} ==="
    )
    print(f"Manifest: {manifest_path}")
    return 0


