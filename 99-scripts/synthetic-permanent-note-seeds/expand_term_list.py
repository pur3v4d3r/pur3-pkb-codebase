def _run_seed_builder(
    brief_path: Path,
    *,
    out_dir: Path,
    overwrite: bool,
    dry_run: bool,
) -> tuple[int, str]:
    """Invoke synth_seed_builder.py build for one brief. Returns (rc, output)."""
    cmd: list[str] = [
        sys.executable,
        str(SEED_BUILDER_SCRIPT),
        "build",
        str(brief_path),
        "--out-dir", str(out_dir),
    ]
    if overwrite:
        cmd.append("--overwrite")
    if dry_run:
        cmd.append("--dry-run")
    proc = subprocess.run(
        cmd, capture_output=True, text=True,
        encoding="utf-8", errors="replace",
    )
    return proc.returncode, (proc.stdout or "") + (proc.stderr or "")


def cmd_build_batch(args: argparse.Namespace) -> int:
    """Read a manifest and materialize each brief as a synthetic seed."""
    manifest_path = Path(args.manifest_path).resolve()
    manifest = load_manifest(manifest_path)
    seeds_dir = Path(manifest["paths"]["seeds_dir"])
    seeds_dir.mkdir(parents=True, exist_ok=True)
    briefs_dir_root = manifest_path.parent  # briefs/<batch_name>/

    entries = manifest["entries"]
    logger.info(
        "Materializing %d seed(s) into %s", len(entries), seeds_dir,
    )

    rc_total = 0
    built = 0
    failed: list[str] = []
    for entry in entries:
        # brief_path in manifest is relative to _HERE (the script dir).
        brief_path = (_HERE / entry["brief_path"]).resolve()
        if not brief_path.exists():
            # Fall back to looking inside briefs_dir_root.
            alt = briefs_dir_root / Path(entry["brief_path"]).name
            if alt.exists():
                brief_path = alt
            else:
                logger.error("Brief missing for %s: %s", entry["term"], brief_path)
                failed.append(entry["term"])
                rc_total = 4
                continue
        rc, output = _run_seed_builder(
            brief_path,
            out_dir=seeds_dir,
            overwrite=args.overwrite_seeds,
            dry_run=args.dry_run,
        )
        if rc != 0:
            logger.error("Seed build failed for %s (rc=%d):\n%s",
                         entry["term"], rc, output.strip())
            failed.append(entry["term"])
            rc_total = max(rc_total, rc)
        else:
            built += 1
            logger.info("Built seed for %s -> %s", entry["term"],
                        entry["expected_seed_filename"])
            if args.verbose >= 1 and output.strip():
                logger.debug("seed-builder output:\n%s", output.strip())

    print(
        f"=== build-batch summary: built={built} failed={len(failed)} "
        f"target_dir={seeds_dir} ==="
    )
    if failed:
        print("Failed terms: " + ", ".join(failed))
    return rc_total


# ========================================================================
# Subcommand: run (expand + build-batch)
# ========================================================================


def cmd_run(args: argparse.Namespace) -> int:
    """Convenience wrapper: expand then build-batch."""
    rc = cmd_expand(args)
    if rc != 0:
        return rc
    if args.dry_run:
        # Expand was a dry-run; nothing to build.
        return 0
    # Locate the manifest the expand step just wrote.
    list_path = Path(args.list_path).resolve()
    batch = parse_term_list(list_path)
    briefs_dir = Path(args.briefs_dir).resolve() / batch.batch_name
    manifest_path = briefs_dir / "manifest.json"
    build_args = argparse.Namespace(
        manifest_path=str(manifest_path),
        overwrite_seeds=args.overwrite_seeds,
        dry_run=False,
        verbose=args.verbose,
        quiet=args.quiet,
    )
    return cmd_build_batch(build_args)


