def evaluate_dedup(
    terms: Iterable[ParsedTerm],
    *,
    permanent_notes_dir: Path,
    overwrite_existing: bool = False,
) -> list[DedupDecision]:
    """Decide for each term whether to accept or skip based on existing notes.

    Mirrors V6's collision check: the kebab-cased term is compared against
    files matching ``<kebab>.md`` in ``permanent_notes_dir``.

    Args:
        terms: Iterable of parsed terms.
        permanent_notes_dir: Directory holding finished permanent notes.
        overwrite_existing: When True, accept even if a note already exists.

    Returns:
        One DedupDecision per term, in input order.

    Raises:
        DedupGateError: if ``permanent_notes_dir`` does not exist.
    """
    if not permanent_notes_dir.exists():
        raise DedupGateError(
            f"permanent-notes directory not found: {permanent_notes_dir}"
        )
    decisions: list[DedupDecision] = []
    for t in terms:
        kebab = ssb.to_kebab(t.term)
        note_path = permanent_notes_dir / f"{kebab}.md"
        exists = note_path.exists()
        if exists and not overwrite_existing:
            decisions.append(
                DedupDecision(
                    term=t.term,
                    kebab=kebab,
                    note_path=note_path,
                    exists=True,
                    decision="skip",
                    reason=f"permanent note already exists at {note_path.name}",
                )
            )
        elif exists and overwrite_existing:
            decisions.append(
                DedupDecision(
                    term=t.term,
                    kebab=kebab,
                    note_path=note_path,
                    exists=True,
                    decision="accept",
                    reason="overwrite-existing flag set",
                )
            )
        else:
            decisions.append(
                DedupDecision(
                    term=t.term,
                    kebab=kebab,
                    note_path=note_path,
                    exists=False,
                    decision="accept",
                    reason="no existing permanent note",
                )
            )
    return decisions


