def _parse_inline_list(raw: str) -> list[str]:
    """Parse a YAML-style or comma-separated inline list.

    ``"[a, b]"`` -> ``["a", "b"]``
    ``"a, b"``   -> ``["a", "b"]``
    ``""``       -> ``[]``
    """
    raw = raw.strip()
    if not raw:
        return []
    m = _INLINE_LIST_RE.match(raw)
    inner = m.group(1) if m else raw
    parts = [p.strip().strip("'\"") for p in inner.split(",")]
    # Strip wiki-link brackets if present.
    cleaned = []
    for p in parts:
        if not p:
            continue
        p = ssb.strip_brackets(p)
        cleaned.append(p)
    return cleaned


def _parse_frontmatter(text: str) -> tuple[dict[str, Any], str]:
    """Split YAML frontmatter from the body. Returns (fm_dict, body)."""
    m = _FRONTMATTER_RE.match(text)
    if not m:
        raise TermListParseError(
            "term list missing required YAML frontmatter "
            "(must start with '---' on line 1)"
        )
    try:
        fm = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError as exc:
        raise TermListParseError(f"frontmatter is not valid YAML: {exc}") from exc
    if not isinstance(fm, dict):
        raise TermListParseError("frontmatter must be a YAML mapping")
    body = text[m.end():]
    return fm, body


def _split_term_sections(body: str) -> list[tuple[str, int, str]]:
    """Split the body into ``(title, line_no, section_text)`` per H2."""
    sections: list[tuple[str, int, str]] = []
    matches = list(_H2_HEADING_RE.finditer(body))
    for i, m in enumerate(matches):
        title = m.group("title").strip()
        # Compute 1-based line number of the heading.
        line_no = body[: m.start()].count("\n") + 1
        start = m.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(body)
        sections.append((title, line_no, body[start:end]))
    return sections


def _parse_term_section(title: str, line_no: int, section: str) -> dict[str, Any]:
    """Parse a single H2 section into a raw dict of fields."""
    out: dict[str, Any] = {"term": title.strip(), "line_no": line_no}

    # Bullet fields (kebab/scalar settings).
    for m in _BULLET_FIELD_RE.finditer(section):
        key = m.group("key")
        val = m.group("value").strip()
        if key in LIST_SLOT_FIELDS:
            out[key] = _parse_inline_list(val)
        elif key == "domain":
            out["domain"] = ssb.to_kebab(val)
        elif key == "confidence":
            out["confidence"] = val.lower()
        else:
            # Unknown bullet keys are preserved but ignored downstream.
            out.setdefault("_extra", {})[key] = val

    # Bold fields (multi-line prose).
    for m in _BOLD_FIELD_RE.finditer(section):
        key = m.group("key")
        # Take only the first paragraph (collapse internal whitespace).
        val = m.group("value").strip()
        # Stop at the first blank line within the captured value.
        first_para = val.split("\n\n", 1)[0]
        out[key] = re.sub(r"\s+", " ", first_para).strip()

    return out


def parse_term_list(path: Path) -> TermListBatch:
    """Parse a term-list Markdown file into a TermListBatch.

    Raises:
        TermListParseError: on malformed input.
        FileNotFoundError: if the file does not exist.
    """
    if not path.exists():
        raise FileNotFoundError(path)
    text = path.read_text(encoding="utf-8")
    fm, body = _parse_frontmatter(text)

    batch_name = fm.get("batch_name")
    if not isinstance(batch_name, str) or not batch_name:
        raise TermListParseError("frontmatter missing 'batch_name'")
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", batch_name):
        raise TermListParseError(
            f"'batch_name' must be kebab-case, got: {batch_name!r}"
        )

    raw_date = fm.get("batch_date")
    if isinstance(raw_date, _date):
        batch_date = raw_date.isoformat()
    elif isinstance(raw_date, str) and re.fullmatch(r"\d{4}-\d{2}-\d{2}", raw_date):
        batch_date = raw_date
    else:
        raise TermListParseError(
            "frontmatter 'batch_date' must be an ISO date (YYYY-MM-DD)"
        )

    default_domain = fm.get("default_domain")
    if default_domain is not None and not isinstance(default_domain, str):
        raise TermListParseError("'default_domain' must be a string if set")
    if default_domain:
        default_domain = ssb.to_kebab(default_domain)

    default_confidence = (fm.get("default_confidence") or DEFAULT_CONFIDENCE).lower()
    if default_confidence not in ALLOWED_CONFIDENCE:
        raise TermListParseError(
            f"'default_confidence' must be one of {sorted(ALLOWED_CONFIDENCE)}"
        )

    notes = str(fm.get("notes") or "").strip()

    sections = _split_term_sections(body)
    if not sections:
        raise TermListParseError("term list contains no H2 term sections")

    parsed_terms: list[ParsedTerm] = []
    seen_kebabs: set[str] = set()
    for title, line_no, section_text in sections:
        raw = _parse_term_section(title, line_no, section_text)
        domain = raw.get("domain") or default_domain
        if not domain:
            raise TermListParseError(
                f"term '{title}' (line {line_no}) has no 'domain' and no "
                "'default_domain' was set in frontmatter"
            )
        confidence = raw.get("confidence", default_confidence)
        if confidence not in ALLOWED_CONFIDENCE:
            raise TermListParseError(
                f"term '{title}' (line {line_no}) has invalid confidence "
                f"{confidence!r}; expected one of {sorted(ALLOWED_CONFIDENCE)}"
            )
        if not raw.get("definition"):
            raise TermListParseError(
                f"term '{title}' (line {line_no}) missing required "
                "'**definition**:' field"
            )
        kebab = ssb.to_kebab(title)
        if kebab in seen_kebabs:
            raise TermListParseError(
                f"duplicate term '{title}' (line {line_no}) — kebab '{kebab}' "
                "already declared earlier in the list"
            )
        seen_kebabs.add(kebab)

        parsed_terms.append(
            ParsedTerm(
                term=ssb.clean_title(title),
                domain=domain,
                secondary_domains=raw.get("secondary_domains", []),
                aliases=raw.get("aliases", []),
                broader=raw.get("broader", []),
                narrower=raw.get("narrower", []),
                related=raw.get("related", []),
                prerequisites=raw.get("prerequisites", []),
                confidence=confidence,
                definition=raw.get("definition", ""),
                key_claim=raw.get("key_claim", ""),
                warning=raw.get("warning", ""),
                line_no=line_no,
            )
        )

    return TermListBatch(
        batch_name=batch_name,
        batch_date=batch_date,
        default_domain=default_domain,
        default_confidence=default_confidence,
        notes=notes,
        terms=parsed_terms,
        source_path=path.resolve(),
    )


