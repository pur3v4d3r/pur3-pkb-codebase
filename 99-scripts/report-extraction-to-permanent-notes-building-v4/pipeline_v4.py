def _clean_title(raw: str) -> str:
    """Normalize a callout title into a concept name.

    Strips trailing parentheticals (``"X (Author, Year)"``) and ``"X — extra"``
    qualifiers. Collapses whitespace. Removes wiki-link brackets if present.
    """
    if not raw:
        return ""
    t = raw.replace("[[", "").replace("]]", "").strip()
    t = _TITLE_PAREN_RE.sub("", t)
    t = _TITLE_DASH_RE.sub("", t)
    t = re.sub(r"\s+", " ", t).strip(" .:;,")
    return t


def _is_usable_title(title: str) -> bool:
    """Return True if a title looks like a real concept name (not prose)."""
    if not (MIN_TITLE_LEN <= len(title) <= MAX_TITLE_LEN):
        return False
    # Reject titles that look like full sentences (multiple spaces + ends w/ period)
    if title.count(" ") > 8:
        return False
    return True


def mine_concepts(
    payload: dict[str, Any],
    *,
    include_key_claims: bool,
) -> list[tuple[str, dict[str, Any]]]:
    """Yield ``(callout_type, callout_dict)`` pairs that qualify as concepts.

    Deduplicates by cleaned title (case-insensitive); keeps the first occurrence,
    preferring ``definition`` callouts over ``key-claim`` callouts on collision.
    """
    callouts = (payload.get("extracted_items") or {}).get("callouts") or []
    accepted: dict[str, tuple[str, dict[str, Any]]] = {}

    def _consider(co: dict[str, Any], allowed: frozenset[str]) -> None:
        ctype = (co.get("type") or "").lower()
        if ctype not in allowed:
            return
        cleaned = _clean_title(co.get("title") or "")
        if not _is_usable_title(cleaned):
            return
        key = cleaned.lower()
        # Definition wins over key-claim on collision
        if key in accepted and accepted[key][0] == "definition":
            return
        accepted[key] = (ctype, co)

    # First pass: definitions (preferred)
    for co in callouts:
        _consider(co, PRIMARY_CONCEPT_CALLOUTS)
    # Second pass: key-claims (only if requested and no definition exists)
    if include_key_claims:
        for co in callouts:
            _consider(co, SECONDARY_CONCEPT_CALLOUTS)

    return list(accepted.values())


