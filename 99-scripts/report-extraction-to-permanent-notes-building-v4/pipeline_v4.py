def _truncate(text: str, limit: int) -> str:
    text = (text or "").strip()
    if len(text) <= limit:
        return text
    return text[: limit - 1].rstrip() + "…"


def _gather_support(
    payload: dict[str, Any],
    *,
    title: str,
    skip_raw_title: str,
) -> tuple[SourceCallout, ...]:
    """Collect callouts from the same report that mention the target title.

    A callout supports a concept if either (a) its title contains the cleaned
    concept name or (b) its body mentions it as substring (case-insensitive).
    The originating callout is excluded by raw-title equality.
    """
    callouts = (payload.get("extracted_items") or {}).get("callouts") or []
    needle = title.lower()
    out: list[SourceCallout] = []
    for co in callouts:
        ctype = (co.get("type") or "").lower()
        if ctype not in SUPPORT_CALLOUT_TYPES:
            continue
        ctitle = co.get("title") or ""
        if ctitle == skip_raw_title and ctype == "definition":
            continue
        cbody = co.get("body") or ""
        haystack = (ctitle + " " + cbody).lower()
        if needle not in haystack:
            continue
        out.append(SourceCallout(
            type=ctype,
            title=ctitle.strip(),
            body=_truncate(cbody, MAX_SUPPORT_BODY_CHARS),
        ))
        if len(out) >= MAX_SUPPORT_CALLOUTS:
            break
    return tuple(out)


def _normalize_domain(raw: str | None) -> str:
    if not raw:
        return "other"
    return to_kebab(raw) or "other"


def _related_links_from_payload(payload: dict[str, Any]) -> tuple[str, ...]:
    """Pull a curated list of related wiki-link targets from the report."""
    fm = (payload.get("document_metadata") or {}).get("frontmatter") or {}
    out: list[str] = []
    for key in ("related", "see-also", "broader", "narrower", "prerequisites"):
        for v in fm.get(key) or []:
            target = str(v).strip().strip("[]").split("|", 1)[0].strip()
            if target and target not in out:
                out.append(target)
    # Add unique extracted wiki-link targets, capped
    kg = payload.get("knowledge_graph") or {}
    for t in (kg.get("unique_wiki_link_targets") or [])[:30]:
        target = str(t).strip().strip("[]").split("|", 1)[0].strip()
        if target and target not in out:
            out.append(target)
    return tuple(out[:40])


def build_bundles(
    payload: dict[str, Any],
    *,
    report_stem: str,
    include_key_claims: bool,
) -> list[ConceptBundle]:
    """Build all ConceptBundles for a single report payload."""
    fm = (payload.get("document_metadata") or {}).get("frontmatter") or {}
    domain = _normalize_domain(fm.get("primary_domain") or fm.get("domain"))
    subdomains = tuple(
        to_kebab(s) for s in (fm.get("secondary_domains") or fm.get("subdomains") or [])
        if s
    )
    aliases = tuple(str(a) for a in (fm.get("aliases") or []) if a)
    related = _related_links_from_payload(payload)
    report_title = str(fm.get("title") or report_stem)
    confidence = str(fm.get("confidence") or fm.get("evidence-quality") or "medium")

    bundles: list[ConceptBundle] = []
    for ctype, co in mine_concepts(payload, include_key_claims=include_key_claims):
        raw_title = co.get("title") or ""
        cleaned = _clean_title(raw_title)
        body = (co.get("body") or "").strip()
        support = _gather_support(payload, title=cleaned, skip_raw_title=raw_title)
        bundles.append(ConceptBundle(
            title=cleaned,
            raw_title=raw_title,
            callout_type=ctype,
            definition_body=_truncate(body, 1800),
            support=support,
            domain=domain,
            subdomains=subdomains,
            aliases=aliases,
            related_links=related,
            report_title=report_title,
            report_stem=report_stem,
            confidence=confidence,
        ))
    return bundles


