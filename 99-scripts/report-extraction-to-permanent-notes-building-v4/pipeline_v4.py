def _make_progress():  # noqa: ANN202
    """Return a Rich ``Progress`` context manager, or a no-op fallback."""
    if _RICH_AVAILABLE:
        return Progress(
            SpinnerColumn(),
            TextColumn("[progress.description]{task.description}"),
            BarColumn(),
            MofNCompleteColumn(),
            TimeElapsedColumn(),
            transient=False,
        )
    # Fallback: minimal no-op Progress
    class _NoopTask:
        def update(self, *a, **kw):  # noqa: ANN001,ANN002,ANN003
            pass

    class _NoopProgress:
        def __enter__(self):
            return self

        def __exit__(self, *a, **kw):  # noqa: ANN001,ANN002,ANN003
            return False

        def add_task(self, description, total=None):  # noqa: ANN001
            return 0

        def update(self, *a, **kw):  # noqa: ANN001,ANN002,ANN003
            pass

    return _NoopProgress()


