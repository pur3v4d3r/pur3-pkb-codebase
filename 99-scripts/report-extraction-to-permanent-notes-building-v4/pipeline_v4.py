def load_payload(path: Path) -> dict[str, Any]:
    """Load and minimally validate a single _extracted.json file."""
    with path.open("r", encoding="utf-8") as f:
        data = json.load(f)
    if not isinstance(data, dict):
        raise ValueError(f"{path.name}: top-level JSON is not an object")
    if "extracted_items" not in data:
        raise ValueError(f"{path.name}: missing extracted_items key")
    return data


def discover_jsons(
    input_dir: Path,
    *,
    report_filter: str | None,
) -> list[Path]:
    """Recursively discover ``*_extracted.json`` files under input_dir."""
    if not input_dir.exists():
        raise FileNotFoundError(f"Input dir does not exist: {input_dir}")
    paths = sorted(input_dir.rglob("*_extracted.json"))
    if report_filter:
        needle = report_filter.lower()
        paths = [p for p in paths if needle in p.stem.lower()]
    return paths


def write_atomic(path: Path, content: str) -> None:
    """Atomically write ``content`` to ``path`` via .tmp → replace."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(content, encoding="utf-8")
    tmp.replace(path)


def existing_status(path: Path) -> str | None:
    """Return the ``status:`` field of an existing note, or None if absent."""
    if not path.exists():
        return None
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return None
    m = _FM_RE.match(text)
    if not m:
        return None
    fm_block = m.group(1)
    for line in fm_block.splitlines():
        if line.lower().startswith("status:"):
            return line.split(":", 1)[1].strip().strip("\"'").lower()
    return None


def resolve_destination(
    bundle: ConceptBundle,
    output_dir: Path,
    *,
    mode: str,
) -> tuple[Path, str | None]:
    """Resolve the output path and return (path, skip_reason_or_None).

    Modes:
        skip      — if file exists, return skip reason
        overwrite — write regardless (atomic replace)
        merge     — write only if existing status is not in ENRICHED_STATUSES
    """
    dest = output_dir / f"{bundle.filename_stem}.md"
    if not dest.exists():
        return dest, None
    if mode == "overwrite":
        return dest, None
    status = existing_status(dest) or ""
    if mode == "merge":
        if status in ENRICHED_STATUSES:
            return dest, f"existing status '{status}' is enriched"
        return dest, None
    # mode == 'skip'
    return dest, f"file exists (status='{status}')"


