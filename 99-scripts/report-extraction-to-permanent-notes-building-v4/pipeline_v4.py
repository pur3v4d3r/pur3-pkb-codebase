# Orchestration
# ════════════════════════════════════════════════════════════════════════════

def convert_one(
    bundle: ConceptBundle,
    client: OllamaClient,
    output_dir: Path,
    *,
    model: str,
    mode: str,
    dry_run: bool,
    bypass_cache: bool,
    today: dt.date,
    no_gate: bool = False,
) -> ConvertResult:
    """End-to-end conversion of one ConceptBundle into a written note."""
    dest, skip_reason = resolve_destination(bundle, output_dir, mode=mode)
    if skip_reason and not dry_run:
        return ConvertResult(
            bundle=bundle, ok=True, cached=False, written_path=None,
            skipped_reason=skip_reason,
        )
    try:
        response, cached = condense_concept(
            bundle, client, model=model, bypass_cache=bypass_cache,
        )
    except (StructuredOutputError, LLMError) as e:
        return ConvertResult(
            bundle=bundle, ok=False, cached=False, written_path=None,
            error=f"{type(e).__name__}: {e}",
        )

    # ── LLM worthiness gate ──────────────────────────────────────────────
    worthy = bool(getattr(response, "worthy", True))
    worthy_reason = str(getattr(response, "worthy_reason", "") or "").strip()
    if not worthy and not no_gate:
        return ConvertResult(
            bundle=bundle, ok=True, cached=cached, written_path=None,
            skipped_reason=f"unworthy: {worthy_reason or '(no reason given)'}",
            unworthy_reason=worthy_reason,
        )

    content = render_note(bundle, response, today=today)
    if dry_run:
        return ConvertResult(
            bundle=bundle, ok=True, cached=cached, written_path=dest,
            skipped_reason="dry-run",
        )
    try:
        write_atomic(dest, content)
    except OSError as e:
        return ConvertResult(
            bundle=bundle, ok=False, cached=cached, written_path=None,
            error=f"OSError: {e}",
        )
    return ConvertResult(
        bundle=bundle, ok=True, cached=cached, written_path=dest,
    )


def process_jsons(
    json_paths: list[Path],
    output_dir: Path,
    client: OllamaClient,
    *,
    model: str,
    mode: str,
    dry_run: bool,
    bypass_cache: bool,
    include_key_claims: bool,
    limit: int | None,
    today: dt.date,
    no_gate: bool = False,
) -> tuple[list[ConvertResult], dict[str, int]]:
    """Process a list of JSON paths sequentially, returning results + stats."""
    all_results: list[ConvertResult] = []
    stats = {
        "jsons": 0, "concepts": 0, "written": 0, "skipped": 0,
        "cached": 0, "failed": 0, "unworthy": 0,
    }

    # Mine all bundles up front so progress bar has accurate totals
    all_bundles: list[ConceptBundle] = []
    for jp in json_paths:
        stats["jsons"] += 1
        try:
            payload = load_payload(jp)
        except (OSError, json.JSONDecodeError, ValueError) as e:
            logger.warning("Skipping %s: %s", jp.name, e)
            continue
        report_stem = jp.stem.removesuffix("_extracted")
        bundles = build_bundles(
            payload, report_stem=report_stem,
            include_key_claims=include_key_claims,
        )
        all_bundles.extend(bundles)
        if limit and len(all_bundles) >= limit:
            all_bundles = all_bundles[:limit]
            break
    stats["concepts"] = len(all_bundles)

    if not all_bundles:
        return all_results, stats

    progress_ctx = _make_progress()
    with progress_ctx as progress:
        task = progress.add_task("Condensing", total=len(all_bundles))
        for bundle in all_bundles:
            try:
                result = convert_one(
                    bundle, client, output_dir,
                    model=model, mode=mode, dry_run=dry_run,
                    bypass_cache=bypass_cache, today=today,
                    no_gate=no_gate,
                )
            except KeyboardInterrupt:
                raise
            all_results.append(result)
            if result.ok:
                if result.unworthy_reason and not no_gate:
                    stats["unworthy"] += 1
                elif result.skipped_reason and result.skipped_reason != "dry-run":
                    stats["skipped"] += 1
                elif result.written_path is not None:
                    stats["written"] += 1
                if result.cached:
                    stats["cached"] += 1
            else:
                stats["failed"] += 1
                logger.warning(
                    "Failed: %s — %s", bundle.title, result.error,
                )
            progress.update(task, advance=1, description=f"Condensing — {bundle.title[:40]}")
    return all_results, stats


