def _yaml_list(items: Iterable[str], *, quote: bool = True, wikilink: bool = False) -> str:
    """Render a list-of-strings as a YAML block sequence."""
    items = [s for s in (str(x).strip() for x in items) if s]
    if not items:
        return "  - \"\""
    out: list[str] = []
    for s in items:
        if wikilink:
            out.append(f"  - \"[[{s}]]\"")
        elif quote:
            out.append(f"  - \"{s}\"")
        else:
            out.append(f"  - {s}")
    return "\n".join(out)


def _yaml_inline_list(items: Iterable[str]) -> str:
    items = [str(x).strip() for x in items if str(x).strip()]
    if not items:
        return "[]"
    return "[" + ", ".join(items) + "]"


def _quote(s: str) -> str:
    return s.replace("\\", "\\\\").replace("\"", "\\\"")


