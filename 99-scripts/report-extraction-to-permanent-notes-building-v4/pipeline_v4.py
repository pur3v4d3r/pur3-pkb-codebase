def configure_logging(verbosity: int, quiet: bool) -> None:
    """Configure root logger based on verbosity flags."""
    if quiet:
        level = logging.ERROR
    elif verbosity >= 2:
        level = logging.DEBUG
    elif verbosity == 1:
        level = logging.INFO
    else:
        level = logging.WARNING
    logging.basicConfig(
        level=level,
        format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
        datefmt="%H:%M:%S",
    )


def _print_summary(results: list[ConvertResult], stats: dict[str, int]) -> None:
    """Emit a human-readable summary of the run."""
    if _RICH_AVAILABLE:
        c = Console()
        c.rule("[bold cyan]V4 Condenser — Summary")
        c.print(
            f"JSONs scanned : [bold]{stats['jsons']}[/]   "
            f"Concepts mined: [bold]{stats['concepts']}[/]"
        )
        c.print(
            f"Written       : [green]{stats['written']}[/]   "
            f"Skipped       : [yellow]{stats['skipped']}[/]   "
            f"Unworthy      : [magenta]{stats.get('unworthy', 0)}[/]   "
            f"Cached hits   : [cyan]{stats['cached']}[/]   "
            f"Failed        : [red]{stats['failed']}[/]"
        )
        if stats.get("unworthy", 0):
            c.print("\n[magenta]Rejected as unworthy (no note written):[/]")
            for r in results:
                if r.unworthy_reason:
                    c.print(f"  • {r.bundle.title}: {r.unworthy_reason}")
        if stats["failed"]:
            c.print("\n[red]Failures:[/]")
            for r in results:
                if not r.ok:
                    c.print(f"  • {r.bundle.title}: {r.error}")
    else:  # pragma: no cover
        print("=" * 64)
        print(
            f"JSONs={stats['jsons']} concepts={stats['concepts']} "
            f"written={stats['written']} skipped={stats['skipped']} "
            f"unworthy={stats.get('unworthy', 0)} "
            f"cached={stats['cached']} failed={stats['failed']}"
        )
        for r in results:
            if not r.ok:
                print(f"  FAIL  {r.bundle.title}: {r.error}")


def main(argv: list[str] | None = None) -> int:
    """Main entry point."""
    parser = build_parser()
    args = parser.parse_args(argv)
    configure_logging(args.verbose, args.quiet)

    if not _PYDANTIC_AVAILABLE:
        logger.warning(
            "pydantic not installed — schema validation disabled. "
            "Install with: pip install pydantic"
        )

    try:
        json_paths = discover_jsons(args.input_dir, report_filter=args.report)
    except FileNotFoundError as e:
        logger.error("%s", e)
        return 2
    if not json_paths:
        logger.error("No *_extracted.json files matched under %s", args.input_dir)
        return 4
    logger.info("Discovered %d JSON file(s)", len(json_paths))

    config_v3.LLM_CACHE_DIR.mkdir(parents=True, exist_ok=True)
    today = dt.date.today()

    try:
        with OllamaClient(
            model=args.model,
            url=config_v3.OLLAMA_URL,
            cache_dir=config_v3.LLM_CACHE_DIR,
            timeout_s=config_v3.LLM_REQUEST_TIMEOUT_S,
            max_retries=config_v3.LLM_MAX_RETRIES,
        ) as client:
            try:
                results, stats = process_jsons(
                    json_paths,
                    args.output_dir,
                    client,
                    model=args.model,
                    mode=args.mode,
                    dry_run=args.dry_run,
                    bypass_cache=args.bypass_cache,
                    include_key_claims=args.include_key_claims,
                    limit=args.limit,
                    today=today,
                    no_gate=args.no_gate,
                )
            except OllamaUnavailableError as e:
                logger.error("Ollama unreachable: %s", e)
                return 6
    except OllamaUnavailableError as e:
        logger.error("Ollama unreachable on startup: %s", e)
        return 6
    except KeyboardInterrupt:
        logger.warning("Interrupted by user")
        return 130

    if stats["concepts"] == 0:
        logger.error(
            "No concept candidates mined. Try --include-key-claims, or check "
            "that the JSON files contain [!definition] callouts."
        )
        return 4

    _print_summary(results, stats)

    if args.strict and stats["failed"] > 0:
        return 5
    return 0


