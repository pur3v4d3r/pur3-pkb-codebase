def parse_frontmatter(text: str) -> tuple[dict[str, object], str, bool]:
    """Extract and parse YAML frontmatter from a markdown document.

    Args:
        text: Full file contents.

    Returns:
        Tuple of (parsed_dict, body_without_frontmatter, has_frontmatter).
        If parsing fails, returns ({}, original_text, True) so the caller
        knows a frontmatter block existed but was malformed.
    """
    match = RE_FRONTMATTER.match(text)
    if not match:
        return {}, text, False
    body = text[match.end():]
    raw = match.group(1)
    if _HAS_YAML:
        try:
            parsed = yaml.safe_load(raw) or {}
            if not isinstance(parsed, dict):
                parsed = {}
            return parsed, body, True
        except yaml.YAMLError as exc:  # type: ignore[attr-defined]
            logger.debug("YAML parse failed: %s", exc)
            return {}, body, True
    # Fallback: extract simple key: value pairs via regex
    fallback: dict[str, object] = {}
    for line in raw.splitlines():
        if ":" in line and not line.strip().startswith("#"):
            k, _, v = line.partition(":")
            fallback[k.strip()] = v.strip()
    return fallback, body, True


def strip_code_blocks(text: str) -> str:
    """Remove fenced code blocks and inline code for word/link analysis."""
    text = RE_CODEBLOCK.sub("", text)
    text = RE_INLINE_CODE.sub("", text)
    return text


def analyze_text(path: Path, text: str, stat: os.stat_result) -> FileAnalysis:
    """Run the full analyser pipeline on a single file's contents.

    Args:
        path: Source file path (used for the record).
        text: Full file contents.
        stat: ``os.stat`` result for size and mtime.

    Returns:
        Fully-populated :class:`FileAnalysis`.
    """
    fm, body, has_fm = parse_frontmatter(text)
    body_no_code = strip_code_blocks(body)

    wikilinks = [m.group(1).strip() for m in RE_WIKILINK.finditer(body_no_code)]
    embeds = [m.group(1).strip() for m in RE_EMBED.finditer(body_no_code)]
    tags_inline = [m.group(1) for m in RE_TAG.finditer(body_no_code)]
    tags_fm = _extract_fm_tags(fm)
    tags = tags_inline + tags_fm
    callouts = [m.group(1).lower() for m in RE_CALLOUT.finditer(body_no_code)]
    urls = RE_URL.findall(body_no_code)
    headings = RE_HEADING.findall(body_no_code)
    heading_depths = [len(h[0]) for h in headings]

    words = RE_WORD.findall(body_no_code)

    content_hash = hashlib.sha256(body_no_code.encode("utf-8", errors="ignore")).hexdigest()

    try:
        created = datetime.fromtimestamp(stat.st_ctime, tz=timezone.utc)
    except (OSError, OverflowError):
        created = None
    try:
        modified = datetime.fromtimestamp(stat.st_mtime, tz=timezone.utc)
    except (OSError, OverflowError):
        modified = None

    return FileAnalysis(
        path=path,
        size_bytes=stat.st_size,
        line_count=text.count("\n") + (0 if text.endswith("\n") else 1),
        word_count=len(words),
        char_count=len(body),
        heading_count=len(headings),
        max_heading_depth=max(heading_depths) if heading_depths else 0,
        wikilinks=wikilinks,
        embeds=embeds,
        tags=tags,
        callouts=callouts,
        urls=urls,
        frontmatter=fm,
        has_frontmatter=has_fm,
        created=created,
        modified=modified,
        content_hash=content_hash,
    )


def _extract_fm_tags(fm: dict[str, object]) -> list[str]:
    """Pull tags from frontmatter regardless of list/string/space-separated form."""
    raw = fm.get("tags") or fm.get("tag")
    if raw is None:
        return []
    if isinstance(raw, list):
        return [str(t).lstrip("#").strip() for t in raw if str(t).strip()]
    if isinstance(raw, str):
        # Could be "tag1 tag2" or "#tag1 #tag2" or "tag1, tag2"
        parts = re.split(r"[,\s]+", raw)
        return [p.lstrip("#").strip() for p in parts if p.strip()]
    return []


def top_words(files: Sequence[FileAnalysis], n: int = 25) -> list[tuple[str, int]]:
    """Aggregate word frequencies across all files, excluding stopwords.

    Args:
        files: All analysed files.
        n: How many top entries to return.

    Returns:
        List of (word, count) sorted descending.
    """
    counter: Counter[str] = Counter()
    for f in files:
        if f.error:
            continue
        # Re-tokenise from cached body would require holding text; for top-words
        # we only have what's in the analysis object. Workaround: we already
        # scrubbed body to wikilinks/tags/etc but didn't keep raw words. For
        # cost/value tradeoff at moderate scale, re-read each file once.
        try:
            text = f.path.read_text(encoding="utf-8", errors="ignore")
            _, body, _ = parse_frontmatter(text)
            body = strip_code_blocks(body)
            for word in RE_WORD.findall(body.lower()):
                if word in STOPWORDS or len(word) < 3:
                    continue
                counter[word] += 1
        except OSError:
            continue
    return counter.most_common(n)


def link_graph(files: Sequence[FileAnalysis]) -> dict[str, dict[str, object]]:
    """Build a wiki-link graph: most-linked targets, hubs, orphans, broken links.

    Args:
        files: All analysed files.

    Returns:
        Dict with keys: 'incoming', 'outgoing', 'orphans', 'hubs',
        'most_linked', 'broken'.
    """
    # File stems available as link targets (in-folder).
    stems = {f.path.stem for f in files if not f.error}
    incoming: Counter[str] = Counter()
    outgoing: Counter[str] = Counter()
    broken: list[tuple[str, str]] = []  # (source_file, missing_target)

    for f in files:
        if f.error:
            continue
        outgoing[f.path.stem] = len(f.wikilinks)
        for target in f.wikilinks:
            target_stem = target.split("/")[-1]  # handle "folder/note" links
            incoming[target_stem] += 1
            if target_stem not in stems:
                broken.append((f.path.name, target))

    most_linked = incoming.most_common(20)
    hubs = outgoing.most_common(20)
    orphans = [
        f.path.name for f in files
        if not f.error
        and incoming.get(f.path.stem, 0) == 0
        and outgoing.get(f.path.stem, 0) == 0
    ]
    return {
        "incoming": incoming,
        "outgoing": outgoing,
        "most_linked": most_linked,
        "hubs": hubs,
        "orphans": orphans,
        "broken": broken,
    }


def detect_duplicates(files: Sequence[FileAnalysis]) -> list[list[Path]]:
    """Group files with identical content hashes.

    Returns:
        List of duplicate-groups (each group = list of paths). Singletons excluded.
    """
    groups: dict[str, list[Path]] = defaultdict(list)
    for f in files:
        if f.error or not f.content_hash:
            continue
        groups[f.content_hash].append(f.path)
    return [g for g in groups.values() if len(g) > 1]


def activity_timeline(files: Sequence[FileAnalysis]) -> Counter[str]:
    """Bucket modification times by month.

    Returns:
        Counter mapping 'YYYY-MM' → count.
    """
    counter: Counter[str] = Counter()
    for f in files:
        if f.modified:
            counter[f.modified.strftime("%Y-%m")] += 1
    return counter


def frontmatter_audit(files: Sequence[FileAnalysis]) -> dict[str, object]:
    """Audit frontmatter coverage and field consistency.

    Returns:
        Dict with: 'with_fm', 'without_fm', 'field_coverage' (Counter of fields),
        'status_distribution' (Counter), 'missing_tags' (list of files).
    """
    with_fm = 0
    without_fm: list[str] = []
    field_counter: Counter[str] = Counter()
    status_counter: Counter[str] = Counter()
    missing_tags: list[str] = []
    for f in files:
        if f.error:
            continue
        if f.has_frontmatter:
            with_fm += 1
            for key in f.frontmatter:
                field_counter[key] += 1
            status = f.frontmatter.get("status")
            if status:
                status_counter[str(status)] += 1
            if not f.frontmatter.get("tags") and not f.frontmatter.get("tag"):
                missing_tags.append(f.path.name)
        else:
            without_fm.append(f.path.name)
    return {
        "with_fm": with_fm,
        "without_fm": without_fm,
        "field_coverage": field_counter,
        "status_distribution": status_counter,
        "missing_tags": missing_tags,
    }


