def configure_logging(verbosity: int, quiet: bool) -> None:
    """Configure root logger based on CLI flags."""
    if quiet:
        level = logging.ERROR
    elif verbosity >= 2:
        level = logging.DEBUG
    elif verbosity == 1:
        level = logging.INFO
    else:
        level = logging.WARNING
    logging.basicConfig(
        level=level,
        format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
        datefmt="%H:%M:%S",
    )


def main(argv: list[str] | None = None) -> int:
    """Main entry point.

    Args:
        argv: Argument vector (defaults to ``sys.argv[1:]``).

    Returns:
        Exit code.
    """
    parser = build_parser()
    args = parser.parse_args(argv)
    configure_logging(args.verbose, args.quiet)

    # Force UTF-8 stdout/stderr on Windows so emoji and box-drawing print cleanly.
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[union-attr]
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[union-attr]
    except (AttributeError, ValueError):
        pass

    try:
        input_path: Path = args.input.resolve()

        # Resolve vault root
        if args.vault:
            vault_root = args.vault.resolve()
        elif input_path.is_dir():
            vault_root = input_path
            # Walk up to find a folder that looks like a vault root
            for candidate in [input_path, *input_path.parents]:
                if (candidate / ".obsidian").is_dir() or (candidate / "00-meta").is_dir():
                    vault_root = candidate
                    break
        else:
            vault_root = input_path.parent

        excludes = DEFAULT_EXCLUDES | frozenset(
            x.strip() for x in args.exclude.split(",") if x.strip()
        )

        logger.info("Discovering files in %s (recursive=%s)", input_path, args.recursive)
        files_to_analyze = discover_files(input_path, args.recursive, excludes)
        logger.info("Found %d file(s) to analyse", len(files_to_analyze))

        analyses = analyze_files_parallel(
            files_to_analyze,
            workers=max(1, args.workers),
            show_progress=not args.no_progress and not args.quiet,
        )

        # Resolve output path
        if args.output:
            output_path = args.output.resolve()
        else:
            today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
            target_dir = input_path if input_path.is_dir() else input_path.parent
            output_path = target_dir / f"_REPORT-{today}.md"

        # Charts
        chart_paths: list[Path] = []
        if args.charts and not args.dry_run:
            if not _HAS_MPL:
                logger.warning("matplotlib not installed — skipping PNG charts")
            else:
                chart_dir = output_path.parent / f"{output_path.stem}_charts"
                tag_counter: Counter[str] = Counter()
                for f in analyses:
                    if not f.error:
                        tag_counter.update(f.tags)
                chart_paths = render_png_charts(
                    chart_dir,
                    [f for f in analyses if not f.error],
                    tag_counter,
                    activity_timeline([f for f in analyses if not f.error]),
                    link_graph([f for f in analyses if not f.error]),
                )
                logger.info("Generated %d chart PNG(s) in %s", len(chart_paths), chart_dir)

        report = render_report(
            files=analyses,
            input_path=input_path,
            vault_root=vault_root,
            chart_paths=chart_paths,
            recursive=args.recursive,
            top_n=args.top,
        )

        successful = sum(1 for f in analyses if not f.error)
        failed = len(analyses) - successful

        if args.dry_run:
            sep = "-" * 60
            print(f"[DRY-RUN] Would write {len(report):,} chars to {output_path}")
            print(f"[DRY-RUN] {successful} file(s) analysed successfully, {failed} error(s)")
            print(f"[DRY-RUN] First 1000 chars of report:\n{sep}")
            print(report[:1000])
            print(f"{sep}\n[DRY-RUN] (truncated)")
            return 0

        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(report, encoding="utf-8")

        if not args.quiet:
            print(f"✓ Report written: {output_path}")
            print(f"  Files analysed: {successful} (errors: {failed})")
            if chart_paths:
                print(f"  Charts written: {len(chart_paths)}")

        return 0

    except InvalidInputError as exc:
        logger.error("Invalid input: %s", exc)
        return 2
    except NoFilesFoundError as exc:
        logger.error("%s", exc)
        return 3
    except KeyboardInterrupt:
        logger.warning("Interrupted by user")
        return 130
    except Exception:
        logger.exception("Unexpected error")
        return 1


