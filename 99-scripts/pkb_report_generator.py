def _derive_insights(
    files: Sequence[FileAnalysis],
    graph: dict[str, dict[str, object]],
    fm_audit: dict[str, object],
    tag_counter: Counter[str],
    timeline: Counter[str],
) -> list[str]:
    """Generate narrative insight bullets from aggregated data."""
    insights: list[str] = []
    if not files:
        return ["No analysable files."]

    # Most active month
    if timeline:
        peak = max(timeline.items(), key=lambda kv: kv[1])
        insights.append(f"📅 **Peak activity month:** {peak[0]} with {peak[1]} files modified.")

    # Tag concentration
    if tag_counter:
        total = sum(tag_counter.values())
        top5 = sum(c for _, c in tag_counter.most_common(5))
        pct = top5 / total * 100
        insights.append(f"🏷️  **Tag concentration:** top 5 tags account for {pct:.0f}% of all tag usage.")

    # Link density
    total_links = sum(len(f.wikilinks) for f in files)
    avg_links = total_links / len(files)
    insights.append(f"🔗 **Link density:** average {avg_links:.1f} wiki-links per file.")

    # Frontmatter coverage
    coverage = fm_audit["with_fm"] / len(files) * 100  # type: ignore[operator]
    insights.append(f"📋 **Frontmatter coverage:** {coverage:.0f}% of files have YAML frontmatter.")

    # Orphan ratio
    orphans = graph["orphans"]
    if isinstance(orphans, list):
        orphan_pct = len(orphans) / len(files) * 100
        insights.append(f"🏝️  **Orphan ratio:** {orphan_pct:.0f}% of notes lack any wiki-link connection.")

    # Long-form vs stub
    long_notes = sum(1 for f in files if f.word_count > 1000)
    stubs = sum(1 for f in files if f.word_count < 50)
    insights.append(
        f"📝 **Content distribution:** {long_notes} long-form notes (>1000 words), "
        f"{stubs} stubs (<50 words)."
    )

    return insights


def textwrap_dedent(s: str) -> str:
    """Trivial dedent wrapper to avoid importing textwrap module-wide."""
    import textwrap
    return textwrap.dedent(s)


