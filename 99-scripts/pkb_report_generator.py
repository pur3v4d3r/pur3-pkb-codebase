def _slugify(text: str) -> str:
    """Convert a heading to a GitHub-style anchor slug."""
    s = text.lower().strip()
    s = re.sub(r"[^\w\s-]", "", s)
    s = re.sub(r"[\s]+", "-", s)
    return s


def _resolve_permanent_note_links(vault_root: Path) -> list[str]:
    """Discover permanent-note files for the Related Resources section.

    Args:
        vault_root: Vault root path used to resolve PERMANENT_NOTE_FOLDERS.

    Returns:
        Sorted list of bare wiki-link names (file stems).
    """
    links: set[str] = set()
    for rel in PERMANENT_NOTE_FOLDERS:
        folder = vault_root / rel
        if folder.is_dir():
            for p in folder.rglob("*.md"):
                links.add(p.stem)
    return sorted(links)


def _format_size(n: int) -> str:
    """Human-readable byte size."""
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024:
            return f"{n:.1f} {unit}" if unit != "B" else f"{n} {unit}"
        n /= 1024  # type: ignore[assignment]
    return f"{n:.1f} TB"


