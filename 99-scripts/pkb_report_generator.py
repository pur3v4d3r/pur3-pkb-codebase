def generate_recommendations(
    files: Sequence[FileAnalysis],
    graph: dict[str, dict[str, object]],
    fm_audit: dict[str, object],
    duplicates: list[list[Path]],
) -> list[Recommendation]:
    """Apply heuristic rules to produce actionable recommendations.

    Args:
        files: All analysed files.
        graph: Output of :func:`link_graph`.
        fm_audit: Output of :func:`frontmatter_audit`.
        duplicates: Output of :func:`detect_duplicates`.

    Returns:
        List of recommendations sorted by severity then affected count.
    """
    recs: list[Recommendation] = []
    total = sum(1 for f in files if not f.error)
    if total == 0:
        return recs

    # Rule 1 — Frontmatter coverage
    without_fm = fm_audit["without_fm"]  # type: ignore[index]
    n_without = len(without_fm) if isinstance(without_fm, list) else 0
    if n_without:
        pct = n_without / total * 100
        sev = "critical" if pct > 50 else "warning" if pct > 20 else "info"
        recs.append(Recommendation(
            severity=sev,
            category="metadata",
            message=(
                f"{n_without} of {total} files ({pct:.0f}%) lack YAML "
                "frontmatter. Consider running `generate_frontmatter.py`."
            ),
            affected_count=n_without,
        ))

    # Rule 2 — Missing tags
    missing_tags = fm_audit["missing_tags"]  # type: ignore[index]
    n_missing = len(missing_tags) if isinstance(missing_tags, list) else 0
    if n_missing:
        recs.append(Recommendation(
            severity="warning" if n_missing > total * 0.3 else "info",
            category="metadata",
            message=(
                f"{n_missing} files have frontmatter but no `tags` field. "
                "Consider batch-tagging via the reference-guide-batch-tagging-script."
            ),
            affected_count=n_missing,
        ))

    # Rule 3 — Orphan notes
    orphans = graph["orphans"]
    n_orphans = len(orphans) if isinstance(orphans, list) else 0
    if n_orphans:
        pct = n_orphans / total * 100
        sev = "critical" if pct > 30 else "warning" if pct > 10 else "info"
        recs.append(Recommendation(
            severity=sev,
            category="links",
            message=(
                f"{n_orphans} orphan notes (no incoming or outgoing links) "
                f"— ~{pct:.0f}% of corpus. Connect them to the knowledge graph "
                "or archive."
            ),
            affected_count=n_orphans,
        ))

    # Rule 4 — Broken links
    broken = graph["broken"]
    n_broken = len(broken) if isinstance(broken, list) else 0
    if n_broken:
        recs.append(Recommendation(
            severity="warning",
            category="links",
            message=(
                f"{n_broken} broken wiki-links detected. Run `link_check.py` "
                "or `broken_link_fixer.py` to triage."
            ),
            affected_count=n_broken,
        ))

    # Rule 5 — Duplicate content
    if duplicates:
        n_dup = sum(len(g) - 1 for g in duplicates)
        recs.append(Recommendation(
            severity="warning",
            category="hygiene",
            message=(
                f"{len(duplicates)} duplicate groups containing {n_dup} "
                "redundant files. Review the Duplicates section and consolidate."
            ),
            affected_count=n_dup,
        ))

    # Rule 6 — Stub notes (very short)
    stubs = [f for f in files if not f.error and f.word_count < 50]
    if stubs:
        recs.append(Recommendation(
            severity="info",
            category="content",
            message=(
                f"{len(stubs)} stub notes (<50 words). Consider expanding "
                "or marking with `status: seedling`."
            ),
            affected_count=len(stubs),
        ))

    # Rule 7 — Heading-less long notes
    heading_less = [
        f for f in files
        if not f.error and f.word_count > 500 and f.heading_count == 0
    ]
    if heading_less:
        recs.append(Recommendation(
            severity="info",
            category="structure",
            message=(
                f"{len(heading_less)} long notes (>500 words) have no headings. "
                "Add structure for navigability."
            ),
            affected_count=len(heading_less),
        ))

    severity_order = {"critical": 0, "warning": 1, "info": 2}
    recs.sort(key=lambda r: (severity_order[r.severity], -r.affected_count))
    return recs


