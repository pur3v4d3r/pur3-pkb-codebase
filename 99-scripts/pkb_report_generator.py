def discover_files(
    input_path: Path,
    recursive: bool,
    excludes: frozenset[str],
    extensions: tuple[str, ...] = DEFAULT_EXTENSIONS,
) -> list[Path]:
    """Enumerate files to analyse.

    Args:
        input_path: File or directory to scan.
        recursive: If directory, recurse into subdirectories.
        excludes: Directory names to skip during recursion.
        extensions: File suffixes to include (case-insensitive).

    Returns:
        Sorted list of file paths.

    Raises:
        InvalidInputError: If ``input_path`` does not exist.
        NoFilesFoundError: If no matching files are found.
    """
    if not input_path.exists():
        raise InvalidInputError(f"Path does not exist: {input_path}")
    suffixes = {e.lower() for e in extensions}
    files: list[Path] = []
    if input_path.is_file():
        if input_path.suffix.lower() in suffixes:
            files = [input_path]
    elif input_path.is_dir():
        if recursive:
            for root, dirs, names in os.walk(input_path):
                dirs[:] = [d for d in dirs if d not in excludes]
                for name in names:
                    p = Path(root) / name
                    if p.suffix.lower() in suffixes:
                        files.append(p)
        else:
            for p in input_path.iterdir():
                if p.is_file() and p.suffix.lower() in suffixes:
                    files.append(p)
    else:
        raise InvalidInputError(f"Not a file or directory: {input_path}")
    if not files:
        raise NoFilesFoundError(
            f"No files matching {extensions} found in {input_path}"
            + (" (recursive)" if recursive else "")
        )
    return sorted(files)


def analyze_file(path: Path) -> FileAnalysis:
    """Read and analyse a single file. Never raises for per-file errors.

    Args:
        path: File path.

    Returns:
        :class:`FileAnalysis`. On error, ``.error`` is populated and other
        fields are zero/empty.
    """
    try:
        text = path.read_text(encoding="utf-8", errors="ignore")
        stat = path.stat()
        return analyze_text(path, text, stat)
    except (OSError, ValueError) as exc:
        logger.warning("Failed to analyse %s: %s", path, exc)
        return FileAnalysis(path=path, error=str(exc))


def analyze_files_parallel(
    paths: list[Path],
    workers: int,
    show_progress: bool,
) -> list[FileAnalysis]:
    """Analyse files in parallel with optional progress reporting.

    Args:
        paths: Files to analyse.
        workers: Thread-pool size.
        show_progress: If True and rich is available, render a progress bar.

    Returns:
        Analyses in the same order as ``paths``.
    """
    results: dict[Path, FileAnalysis] = {}
    use_rich = show_progress and _HAS_RICH

    if use_rich:
        progress = Progress(
            SpinnerColumn(),
            TextColumn("[progress.description]{task.description}"),
            BarColumn(),
            MofNCompleteColumn(),
            TimeElapsedColumn(),
            transient=True,
        )
        progress.start()
        task_id = progress.add_task("Analysing files…", total=len(paths))
    else:
        progress = None
        task_id = None

    try:
        with ThreadPoolExecutor(max_workers=workers) as pool:
            future_to_path = {pool.submit(analyze_file, p): p for p in paths}
            for future in as_completed(future_to_path):
                p = future_to_path[future]
                results[p] = future.result()
                if progress and task_id is not None:
                    progress.update(task_id, advance=1)
    finally:
        if progress:
            progress.stop()

    return [results[p] for p in paths]


