@dataclass
class FileAnalysis:
    """Per-file analysis record.

    Attributes:
        path: Absolute path to the file.
        size_bytes: File size on disk.
        line_count: Total lines (including blank).
        word_count: Word count (code blocks excluded).
        char_count: Character count (after frontmatter stripped).
        heading_count: Count of ATX headings.
        max_heading_depth: Deepest heading level (1-6, 0 if none).
        wikilinks: All [[wiki-link]] targets, in order.
        embeds: All ![[embed]] targets.
        tags: All #tag occurrences (without leading #).
        callouts: All > [!type] callout types.
        urls: External URLs found.
        frontmatter: Parsed YAML frontmatter (empty if absent or unparseable).
        has_frontmatter: True if a frontmatter block is present.
        created: File creation time (best-effort, OS-dependent).
        modified: File modification time.
        content_hash: SHA-256 of normalised content (used for duplicate detection).
        error: Non-None if analysis failed; analysis fields will be empty.
    """
    path: Path
    size_bytes: int = 0
    line_count: int = 0
    word_count: int = 0
    char_count: int = 0
    heading_count: int = 0
    max_heading_depth: int = 0
    wikilinks: list[str] = field(default_factory=list)
    embeds: list[str] = field(default_factory=list)
    tags: list[str] = field(default_factory=list)
    callouts: list[str] = field(default_factory=list)
    urls: list[str] = field(default_factory=list)
    frontmatter: dict[str, object] = field(default_factory=dict)
    has_frontmatter: bool = False
    created: datetime | None = None
    modified: datetime | None = None
    content_hash: str = ""
    error: str | None = None

