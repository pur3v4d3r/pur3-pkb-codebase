# Pre-compiled patterns. Order matters: we strip code/HTML first so they
# can't shadow later regex (e.g. a `**` inside a code block).
# Tolerates CRLF, optional BOM, and a closing `---` at EOF without trailing newline.
_FRONTMATTER_RE = re.compile(r"\A\ufeff?---\r?\n.*?\r?\n---[ \t]*(?:\r?\n|\Z)", re.DOTALL)
# Matches a heading line introducing an appendix / references / bibliography /
# footnotes / endnotes / works-cited section. Any heading level (#..######).
# We cut the body at this point so the TTS does not read citation dumps.
_APPENDIX_CUTOFF_RE = re.compile(
    r"^#{1,6}\s+(?:appendix|appendices|appendix\s+[a-z0-9]+"
    r"|references?|bibliography|works\s+cited|footnotes?|endnotes?|"
    r"further\s+reading|sources)\b.*$",
    re.IGNORECASE | re.MULTILINE,
)
_FENCED_CODE_RE = re.compile(r"```.*?```", re.DOTALL)
_INLINE_CODE_RE = re.compile(r"`[^`\n]+`")
_HTML_TAG_RE = re.compile(r"<[^>]+>")
# Obsidian callout marker on its own line: `> [!note] Title` → keep "Title" as a sentence.
_CALLOUT_HEADER_RE = re.compile(r"^>\s*\[!([a-zA-Z0-9_-]+)\][+-]?\s*(.*)$", re.MULTILINE)
# Wiki-links: [[Target|Display]] → Display ;  [[Target]] → Target
_WIKILINK_RE = re.compile(r"\[\[([^\]|]+?)(?:\|([^\]]+?))?\]\]")
# Markdown links [text](url) → text
_MDLINK_RE = re.compile(r"\[([^\]]+?)\]\(([^)]+?)\)")
# Image syntax ![alt](url)
_IMAGE_RE = re.compile(r"!\[[^\]]*\]\([^)]*\)")
# Emphasis markers — strip leaving the inner text
_EMPHASIS_RE = re.compile(r"(\*\*\*|\*\*|\*|___|__|_|~~)(.+?)\1", re.DOTALL)
# Markdown table rows (lines composed entirely of pipes/dashes/spaces)
_TABLE_DIVIDER_RE = re.compile(r"^\s*\|?[\s\-:|]+\|?\s*$", re.MULTILINE)
# Block-quote markers at line start
_BLOCKQUOTE_RE = re.compile(r"^>\s?", re.MULTILINE)
# List bullets and numbers at line start
_LIST_BULLET_RE = re.compile(r"^\s*([-*+]|\d+[.)])\s+", re.MULTILINE)
# Heading markers (#, ##, ...) at line start; we keep the text but mark a section
_HEADING_RE = re.compile(r"^(#{1,6})\s+(.+?)\s*#*\s*$", re.MULTILINE)
# Multiple consecutive blank lines → single blank line
_MULTI_BLANK_RE = re.compile(r"\n{3,}")
# Standalone horizontal rules
_HRULE_RE = re.compile(r"^\s*([-*_])\1{2,}\s*$", re.MULTILINE)

# Standalone Obsidian-style tags or stray "#word" tokens left behind after
# heading + wikilink processing. Matches "#tag", "#tag-name", "#area/sub" but
# not characters embedded in a word (e.g. "C#" stays intact because of \B).
_STRAY_HASHTAG_RE = re.compile(r"(?<!\w)#([\w][\w/_-]*)")

# Unicode glyphs that are unspeakable AND that crash Windows cp1252 stdout
# inside F5-TTS's internal `print(gen_text...)`. We map each to a sensible
# spoken / printable substitute. Add new entries here when a new symbol blows
# up encoding.
_UNICODE_SUBSTITUTIONS = {
    "\u2192": " to ",       # → rightwards arrow
    "\u2190": " from ",     # ← leftwards arrow
    "\u2194": " versus ",   # ↔ left-right arrow
    "\u21d2": " implies ",  # ⇒
    "\u21d4": " iff ",      # ⇔
    "\u00a7": "section ",  # § section sign
    "\u00b6": "",            # ¶ pilcrow
    "\u2013": "-",          # – en dash
    "\u2014": " - ",        # — em dash
    "\u2026": "...",        # … ellipsis
    "\u2018": "'",          # ' left single quote
    "\u2019": "'",          # ' right single quote
    "\u201c": '"',          # " left double quote
    "\u201d": '"',          # " right double quote
    "\u2022": "",            # • bullet
    "\u00d7": " by ",       # × multiplication sign  (e.g. "2×2 framework")
    "\u00f7": " divided by ",  # ÷
    "\u2260": " not equal to ",  # ≠
    "\u2264": " less than or equal to ",   # ≤
    "\u2265": " greater than or equal to ",  # ≥
    "\u00b1": " plus or minus ",  # ±
}


# Sentinel used internally to mark section boundaries before chunking. It is
# stripped before audio synthesis but preserved by the chunker so we know where
# to insert longer inter-section pauses.
SECTION_MARK = "@@SECTION@@"


def _extract_frontmatter(text: str) -> tuple[dict[str, str], str]:
    """Parse a minimal YAML frontmatter block.

    We do NOT pull in PyYAML — we only need top-level scalar fields (title,
    author, etc.). Anything more exotic falls through and is ignored.

    Args:
        text: Full raw markdown source.

    Returns:
        A tuple ``(fields, body)`` where ``fields`` is a string→string mapping
        and ``body`` is the markdown content after the frontmatter block.
    """
    m = _FRONTMATTER_RE.match(text)
    if not m:
        return {}, text
    block = m.group(0).strip("-\n")
    fields: dict[str, str] = {}
    for line in block.splitlines():
        if ":" not in line:
            continue
        key, _, value = line.partition(":")
        fields[key.strip().lower()] = value.strip().strip('"').strip("'")
    return fields, text[m.end():]


def _truncate_at_appendix(text: str) -> str:
    """Drop everything from the first appendix/references-style heading onward.

    Avoids spending TTS time on appendices, bibliographies, footnotes, etc.
    Matches headings like ``# Appendix``, ``## Appendix A``, ``## References``,
    ``### Bibliography``, ``# Works Cited``, ``## Footnotes``, ``# Sources``.
    """
    m = _APPENDIX_CUTOFF_RE.search(text)
    if m:
        return text[: m.start()].rstrip()
    return text


def clean_markdown(text: str) -> str:
    """Convert Obsidian-flavored markdown into clean speakable plain text.

    Pipeline (order matters):
        1. Drop fenced code blocks, inline code, raw HTML, images.
        2. Reformat Obsidian callout headers into a sentence form.
        3. Resolve wiki-links and markdown links to their visible text.
        4. Strip emphasis markers.
        5. Reduce table rows / blockquote markers / list bullets to plain lines.
        6. Convert headings to a sentinel-marked sentence.
        7. Collapse whitespace.

    Args:
        text: Raw markdown body (frontmatter already removed).

    Returns:
        Plain text with section markers (``SECTION_MARK``) where headings were.
    """
    # 1. Code / HTML / images — these MUST go first so their contents can't
    #    leak into later regex passes.
    text = _FENCED_CODE_RE.sub("", text)
    text = _INLINE_CODE_RE.sub("", text)
    text = _IMAGE_RE.sub("", text)
    text = _HTML_TAG_RE.sub("", text)

    # 2. Callout headers: "> [!important] Read this" → "Important. Read this."
    def _callout_repl(m: re.Match[str]) -> str:
        kind = m.group(1).replace("-", " ").strip().capitalize()
        rest = m.group(2).strip()
        return f"{kind}. {rest}".rstrip(". ") + "."
    text = _CALLOUT_HEADER_RE.sub(_callout_repl, text)

    # 3. Links → display text
    #    Wikilinks: prefer the display alias; otherwise use the target. Strip
    #    Obsidian section anchors (e.g. ``[[Note#Heading]]`` -> "Note, Heading"
    #    and ``[[#Heading]]`` -> "Heading") so the TTS does not say "hashtag".
    def _wiki_repl(m: re.Match[str]) -> str:
        chosen = (m.group(2) or m.group(1)).strip()
        # If no display alias, sanitise the raw target.
        if not m.group(2):
            chosen = chosen.lstrip("#")
            chosen = chosen.replace("#", ", ")
        return chosen
    text = _WIKILINK_RE.sub(_wiki_repl, text)
    text = _MDLINK_RE.sub(lambda m: m.group(1), text)

    # 4. Emphasis (run twice in case of nested **_x_**)
    for _ in range(2):
        text = _EMPHASIS_RE.sub(lambda m: m.group(2), text)

    # 5. Tables / blockquotes / lists / hrules
    text = _TABLE_DIVIDER_RE.sub("", text)
    text = _HRULE_RE.sub("", text)
    text = _BLOCKQUOTE_RE.sub("", text)
    text = _LIST_BULLET_RE.sub("", text)

    # 6. Headings → sentinel-marked sentence. We keep the heading TEXT because
    #    skipping it removes structure the listener depends on.
    def _heading_repl(m: re.Match[str]) -> str:
        title = m.group(2).strip().rstrip(".").rstrip()
        return f"\n\n{SECTION_MARK}{title}.\n\n"
    text = _HEADING_RE.sub(_heading_repl, text)

    # 6b. Strip stray "#word" tokens that survived (Obsidian tags / link
    #     anchor fragments not caught by the wikilink rule). Replace the
    #     leading "#" with nothing so "#A.1" -> "A.1", "#far-transfer" ->
    #     "far-transfer". Words like "C#" are preserved by the (?<!\w) guard.
    text = _STRAY_HASHTAG_RE.sub(lambda m: m.group(1).replace("-", " ").replace("_", " "), text)

    # 7. Whitespace normalization
    text = _MULTI_BLANK_RE.sub("\n\n", text)
    text = "\n".join(line.rstrip() for line in text.splitlines())

    # 8. Replace unspeakable Unicode glyphs with readable substitutes.
    for src, dst in _UNICODE_SUBSTITUTIONS.items():
        text = text.replace(src, dst)
    return text.strip()


def _apply_cp1252_safety(text: str) -> str:
    """Drop characters that can't encode to cp1252.

    F5-TTS on Windows calls ``print(gen_text)`` internally, which crashes on
    non-cp1252 codepoints. Apply this only when using the f5tts backend.
    """
    return text.encode("cp1252", errors="ignore").decode("cp1252")


def derive_title(fields: dict[str, str], cleaned_text: str, fallback: str) -> str:
    """Derive a display title from frontmatter, the first heading, or filename."""
    if "title" in fields and fields["title"]:
        return fields["title"]
    # First section-marked heading in the cleaned text
    for line in cleaned_text.splitlines():
        if line.startswith(SECTION_MARK):
            return line.removeprefix(SECTION_MARK).rstrip(".").strip()
    return fallback


