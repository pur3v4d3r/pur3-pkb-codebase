@dataclass
class BackendConfig:
    """Backend-tunable parameters surfaced via the CLI."""
    voice: str
    rate_pct: int = 0          # percentage adjust, e.g. -10 = 10% slower
    pitch_hz: int = 0          # ± Hz adjustment (edge backend)
    speaker_wav: Path | None = None  # XTTS reference clip


class TTSBackend(ABC):
    """Abstract synthesizer.

    Implementations must take a piece of text plus a destination path and
    write a playable WAV/MP3 to that path. Concatenation is handled by the
    caller, not the backend.
    """

    name: str = "abstract"

    def __init__(self, config: BackendConfig) -> None:
        self.config = config

    @abstractmethod
    def synthesize(self, text: str, dest: Path) -> None:
        """Render ``text`` to ``dest`` (a .mp3 or .wav file)."""

    def warmup(self) -> None:
        """Optional model preload hook. Default is a no-op."""


class EdgeTTSBackend(TTSBackend):
    """Microsoft Edge / Azure neural voices via the `edge-tts` package.

    Free, no API key, ~250 voices. Output is MP3.
    """
    name = "edge"

    def __init__(self, config: BackendConfig) -> None:
        super().__init__(config)
        try:
            import edge_tts  # type: ignore
        except ImportError as exc:
            raise BackendUnavailableError(
                "edge-tts not installed. Run: pip install edge-tts"
            ) from exc
        self._edge_tts = edge_tts

    def synthesize(self, text: str, dest: Path) -> None:
        rate_str = f"{self.config.rate_pct:+d}%"
        pitch_str = f"{self.config.pitch_hz:+d}Hz"
        comm = self._edge_tts.Communicate(
            text=text,
            voice=self.config.voice,
            rate=rate_str,
            pitch=pitch_str,
        )
        # edge-tts is async-only. We isolate the event loop per call so we
        # don't fight any caller-side loop policy.
        try:
            asyncio.run(comm.save(str(dest)))
        except Exception as exc:  # pragma: no cover - network / service errors
            raise SynthesisError(f"edge-tts failed: {exc}") from exc


class KokoroBackend(TTSBackend):
    """Local Kokoro-82M pipeline via the `kokoro` package.

    Runs on CPU but is dramatically faster on CUDA. Output is WAV.
    """
    name = "kokoro"

    def __init__(self, config: BackendConfig) -> None:
        super().__init__(config)
        try:
            from kokoro import KPipeline  # type: ignore
            import soundfile as sf  # type: ignore
        except ImportError as exc:
            raise BackendUnavailableError(
                "kokoro/soundfile not installed. Run: "
                "pip install kokoro soundfile"
            ) from exc
        self._sf = sf
        # NOTE: lang_code is derived from voice prefix: 'af_*' / 'am_*' = American.
        self._pipe = KPipeline(lang_code=config.voice[0] if config.voice else "a")

    def synthesize(self, text: str, dest: Path) -> None:
        # PERF: Kokoro emits a generator of audio fragments; we concatenate
        #       them in-memory. Speed is controlled by the `speed` parameter
        #       (1.0 = nominal). Map rate_pct → multiplicative factor.
        speed = max(0.5, min(2.0, 1.0 + self.config.rate_pct / 100.0))
        try:
            fragments = list(self._pipe(text, voice=self.config.voice, speed=speed))
        except Exception as exc:
            raise SynthesisError(f"kokoro failed: {exc}") from exc
        if not fragments:
            raise SynthesisError("kokoro produced no audio")
        # Each fragment yields (graphemes, phonemes, audio_tensor). Concat audio.
        import numpy as np  # local import — only needed if user picked kokoro
        audio = np.concatenate([np.asarray(frag[2]) for frag in fragments])
        self._sf.write(str(dest), audio, 24000)


