def configure_logging(verbosity: int, quiet: bool) -> None:
    """Configure root logger from CLI verbosity flags."""
    if quiet:
        level = logging.ERROR
    elif verbosity >= 2:
        level = logging.DEBUG
    elif verbosity == 1:
        level = logging.INFO
    else:
        level = logging.WARNING
    logging.basicConfig(
        level=level,
        format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
        datefmt="%H:%M:%S",
    )


def _resolve_voice(backend_name: str, override: str | None) -> str:
    return override or DEFAULT_VOICE[backend_name]


def _resolve_chunk_chars(backend_name: str, override: int | None) -> int:
    if override is not None:
        if override <= 0:
            raise ValueError("--chunk-chars must be positive")
        return override
    return DEFAULT_CHUNK_CHARS[backend_name]


def main(argv: list[str] | None = None) -> int:
    """Main entry point. Returns a process exit code."""
    parser = build_parser()
    args = parser.parse_args(argv)
    configure_logging(args.verbose, args.quiet)

    # Pre-flight: shared deps
    if not args.dry_run and AudioSegment is None:
        logger.error("pydub is required. Install with: pip install pydub")
        return 5
    if not args.dry_run and shutil.which("ffmpeg") is None:
        logger.error("ffmpeg not found on PATH. Install ffmpeg and retry.")
        return 5

    try:
        report_paths = discover_reports(args.input)
    except FileNotFoundError as exc:
        logger.error("%s", exc)
        return 2
    if not report_paths:
        logger.error("No markdown files found under %s", args.input)
        return 4

    cfg = BackendConfig(
        voice=_resolve_voice(args.backend, args.voice),
        rate_pct=args.rate_pct,
        pitch_hz=args.pitch_hz,
        speaker_wav=args.speaker_wav,
    )
    try:
        backend: TTSBackend | None = None if args.dry_run else build_backend(args.backend, cfg)
    except BackendUnavailableError as exc:
        logger.error("%s", exc)
        return 6

    try:
        chunk_chars = _resolve_chunk_chars(args.backend, args.chunk_chars)
    except ValueError as exc:
        logger.error("%s", exc)
        return 3

    if backend is not None:
        try:
            backend.warmup()
        except Exception:  # pragma: no cover
            logger.exception("backend warmup failed (continuing)")

    failures = 0
    for path in report_paths:
        try:
            report = load_report(path)
        except Exception as exc:
            logger.error("Failed to load %s: %s", path, exc)
            failures += 1
            continue

        out_dir = args.output_dir if args.output_dir else report.path.parent
        # In dry-run mode we may not have a backend; pass a sentinel.
        result = synthesize_report(
            report,
            backend if backend is not None else _DryRunBackend(cfg),
            out_dir=out_dir,
            out_format=args.format,
            chunk_chars=chunk_chars,
            overwrite=args.overwrite,
            dry_run=args.dry_run,
        )
        if result.ok:
            if result.error == "skipped-exists":
                logger.info("• %-40s [skipped]", report.title[:40])
            elif args.dry_run:
                logger.info("• %-40s [dry-run %d chunks]",
                            report.title[:40], result.chunk_count)
            else:
                logger.info("• %-40s → %s (%.1fs)",
                            report.title[:40],
                            result.output_path.name if result.output_path else "?",
                            result.duration_ms / 1000.0)
        else:
            failures += 1
            logger.error("• %-40s FAILED: %s",
                         report.title[:40], result.error)

    log_done = logger.warning if failures else logger.info
    log_done("Done. %d ok / %d failed / %d total",
             len(report_paths) - failures, failures, len(report_paths))
    if failures and args.strict:
        return 7
    return 0


class _DryRunBackend(TTSBackend):
    """Sentinel — never invoked because synthesize_report short-circuits in dry_run."""
    name = "dry-run"
    def synthesize(self, text: str, dest: Path) -> None:  # pragma: no cover
        raise RuntimeError("dry-run backend should not synthesize")


