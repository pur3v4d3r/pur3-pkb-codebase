def load_report(path: Path) -> Report:
    """Read a markdown file and produce a ready-to-synthesize ``Report``."""
    raw = path.read_text(encoding="utf-8")
    fields, body = _extract_frontmatter(raw)
    body = _truncate_at_appendix(body)
    cleaned = clean_markdown(body)
    title = derive_title(fields, cleaned, fallback=path.stem)
    author = fields.get("author") or fields.get("by")
    # Strip the section sentinel from the title we tag (it's only useful
    # internally to the chunker).
    title = title.replace(SECTION_MARK, "").strip() or path.stem
    return Report(path=path.resolve(), title=title, author=author, text=cleaned)


def discover_reports(target: Path) -> list[Path]:
    """Resolve a file or folder argument to a list of markdown paths."""
    if target.is_file():
        return [target]
    if target.is_dir():
        # NOTE: rglob walks recursively; sort for deterministic ordering.
        return sorted(p for p in target.rglob("*.md") if p.is_file())
    raise FileNotFoundError(f"Not a file or directory: {target}")


def synthesize_report(
    report: Report,
    backend: TTSBackend,
    *,
    out_dir: Path,
    out_format: str,
    chunk_chars: int,
    overwrite: bool,
    dry_run: bool,
) -> SynthesisResult:
    """Run the full per-report pipeline.

    Returns a ``SynthesisResult``; never raises for ordinary synthesis
    failures (those are recorded on the result), but DOES raise for caller-
    bug conditions like a missing output directory we can't create.
    """
    out_path = out_dir / f"{_safe_stem(report.path.stem)}.{out_format}"
    if out_path.exists() and not overwrite and not dry_run:
        logger.info("Skipping %s (exists; use --overwrite to replace)", out_path.name)
        return SynthesisResult(report, out_path, ok=True, chunk_count=0,
                               duration_ms=0, error="skipped-exists")

    chunks = chunk_text(report.text, chunk_chars)
    if not chunks:
        return SynthesisResult(report, None, ok=False, chunk_count=0,
                               duration_ms=0, error="no-content")

    logger.info("Report %r → %d chunks (~%d chars total)",
                report.title, len(chunks), len(report.text))

    if dry_run:
        for ch in chunks[:3]:
            preview = ch.text[:120].replace("\n", " ")
            logger.info("  chunk %d (break=%s): %s%s",
                        ch.index, ch.is_section_break, preview,
                        "…" if len(ch.text) > 120 else "")
        return SynthesisResult(report, out_path, ok=True,
                               chunk_count=len(chunks), duration_ms=0)

    out_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="rtt_") as td:
        td_path = Path(td)
        chunk_files: list[Path] = []
        for ch in chunks:
            # Use a content-hash filename so a re-run of the same chunk text
            # is at least debug-traceable in the temp dir.
            h = hashlib.sha1(ch.text.encode("utf-8")).hexdigest()[:10]
            cf = td_path / f"{ch.index:04d}_{h}.{_chunk_format(backend)}"
            try:
                chunk_text_final = (
                    _apply_cp1252_safety(ch.text)
                    if backend.name == "f5tts" else ch.text
                )
                backend.synthesize(chunk_text_final, cf)
            except SynthesisError as exc:
                logger.error("chunk %d synthesis failed: %s", ch.index, exc)
                return SynthesisResult(report, None, ok=False,
                                       chunk_count=len(chunks), duration_ms=0,
                                       error=str(exc))
            chunk_files.append(cf)
        try:
            duration = assemble_audio(chunk_files, chunks, out_path, out_format)
        except AudioAssemblyError as exc:
            return SynthesisResult(report, None, ok=False,
                                   chunk_count=len(chunks), duration_ms=0,
                                   error=str(exc))

    tag_mp3(out_path, title=report.title, author=report.author)
    return SynthesisResult(report, out_path, ok=True,
                           chunk_count=len(chunks), duration_ms=duration)


def _chunk_format(backend: TTSBackend) -> str:
    """Per-backend natural output extension for individual chunk files."""
    if backend.name == "edge":
        return "mp3"
    return "wav"  # kokoro and xtts both write WAV natively


_INVALID_CHARS_RE = re.compile(r'[<>:"/\\|?*\x00-\x1f]')


def _safe_stem(stem: str) -> str:
    """Sanitize a filename stem for cross-platform safety."""
    cleaned = _INVALID_CHARS_RE.sub("_", stem).strip(" .")
    return cleaned or "report"


