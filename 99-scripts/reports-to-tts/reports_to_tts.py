_SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?])\s+(?=[A-Z\"'\u201c\u2018(])")


def chunk_text(text: str, max_chars: int) -> list[Chunk]:
    """Split cleaned text into TTS-sized chunks at safe linguistic boundaries.

    Strategy:
        - Split on section markers first (each section becomes its own chunk
          family with ``is_section_break=True`` on its first chunk).
        - Within each section, if the section exceeds ``max_chars``, sub-split
          at sentence boundaries; if a single sentence still exceeds the
          ceiling, hard-wrap at the nearest whitespace under the limit.

    Args:
        text:      Cleaned text (output of ``clean_markdown``).
        max_chars: Per-chunk character ceiling.

    Returns:
        A list of ``Chunk`` records in narration order.
    """
    if max_chars <= 0:
        raise ValueError("max_chars must be positive")

    # INVARIANT: ``sections`` preserves narration order. The leading split
    # on SECTION_MARK can produce an empty first element if the document
    # opens with a heading; we filter empties below.
    raw_sections = text.split(SECTION_MARK)
    sections = [s.strip() for s in raw_sections if s.strip()]

    chunks: list[Chunk] = []
    idx = 0
    for s_i, section in enumerate(sections):
        # Each section's first chunk is the section break (only s_i>0 actually
        # follows a heading boundary; the first section is the document opener
        # with no preceding silence).
        first_in_section = True
        for piece in _split_section(section, max_chars):
            chunks.append(Chunk(
                index=idx,
                text=piece,
                is_section_break=(first_in_section and s_i > 0),
            ))
            idx += 1
            first_in_section = False
    return chunks


def _split_section(section: str, max_chars: int) -> Iterable[str]:
    """Yield sub-strings of ``section`` each under ``max_chars``."""
    if len(section) <= max_chars:
        yield section
        return
    sentences = _SENTENCE_SPLIT_RE.split(section)
    buf: list[str] = []
    buf_len = 0
    for sent in sentences:
        if buf_len + len(sent) + 1 > max_chars and buf:
            yield " ".join(buf)
            buf, buf_len = [], 0
        if len(sent) > max_chars:
            # PERF: pathological long sentence — hard-wrap at whitespace.
            yield from _hard_wrap(sent, max_chars)
            continue
        buf.append(sent)
        buf_len += len(sent) + 1
    if buf:
        yield " ".join(buf)


def _hard_wrap(s: str, max_chars: int) -> Iterable[str]:
    """Last-resort wrap a single overlong sentence at whitespace."""
    while len(s) > max_chars:
        cut = s.rfind(" ", 0, max_chars)
        if cut == -1:
            cut = max_chars
        yield s[:cut].strip()
        s = s[cut:].strip()
    if s:
        yield s


