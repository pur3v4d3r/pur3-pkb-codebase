def assemble_audio(
    chunk_files: Sequence[Path],
    chunks: Sequence[Chunk],
    dest: Path,
    out_format: str,
) -> int:
    """Concatenate per-chunk audio with appropriate inter-chunk silences.

    Args:
        chunk_files: One audio file per chunk (same length / order).
        chunks:      The Chunk metadata aligned with ``chunk_files``.
        dest:        Final output file path.
        out_format:  One of SUPPORTED_FORMATS (``mp3`` | ``wav`` | ``ogg``).

    Returns:
        Total duration of the assembled audio in milliseconds.

    Raises:
        AudioAssemblyError: pydub or ffmpeg failed.
    """
    if AudioSegment is None:
        raise AudioAssemblyError(
            "pydub is not installed. Run: pip install pydub  (and ensure "
            "ffmpeg is on PATH)."
        )
    if len(chunk_files) != len(chunks):
        raise AudioAssemblyError("chunk_files / chunks length mismatch")

    try:
        combined = AudioSegment.silent(duration=0)
        for cf, ch in zip(chunk_files, chunks):
            seg = AudioSegment.from_file(cf)
            if combined.duration_seconds > 0:
                pause = SECTION_PAUSE_MS if ch.is_section_break else SENTENCE_PAUSE_MS
                combined += AudioSegment.silent(duration=pause)
            combined += seg
        dest.parent.mkdir(parents=True, exist_ok=True)
        combined.export(dest, format=out_format)
        return int(combined.duration_seconds * 1000)
    except Exception as exc:  # pragma: no cover - ffmpeg / IO failures
        raise AudioAssemblyError(f"failed to assemble audio: {exc}") from exc


def tag_mp3(path: Path, *, title: str, author: str | None) -> None:
    """Write minimal ID3 tags to an MP3 file. No-op for non-MP3 formats.

    Quietly logs and continues on tagging failure — bad tags should not
    invalidate an otherwise successful synthesis.
    """
    if path.suffix.lower() != ".mp3" or EasyID3 is None:
        return
    try:
        try:
            tags = EasyID3(path)
        except ID3NoHeaderError:
            tags = EasyID3()
            tags.save(path)
            tags = EasyID3(path)
        tags["title"] = title
        if author:
            tags["artist"] = author
        tags["genre"] = "Spoken & Audio"
        tags.save(path)
    except Exception as exc:  # pragma: no cover
        logger.warning("ID3 tagging failed for %s: %s", path.name, exc)


