def _strip_boilerplate(body: str) -> str:
    """Remove placeholder callouts and auto-stub notices to compute true body length."""
    cleaned = _AUTO_STUB_RE.sub("", body)
    # Drop "Referenced By" section (auto-generated, not real content)
    cleaned = re.sub(
        r"## Referenced By\s*\n(?:- \[\[.*?\]\]\s*\n)*", "", cleaned
    )
    return cleaned.strip()


def _has_real_definition(body: str) -> bool:
    """True iff ``[!definition]`` callout exists and is NOT the v3 stub placeholder."""
    if "!definition" not in body.lower():
        return False
    return not bool(_PLACEHOLDER_DEF_RE.search(body))


def _looks_comprehensive(stub: StubCandidate) -> bool:
    """True iff the stub is already a fully fleshed-out note."""
    return (
        stub.body_len >= COMPREHENSIVE_BODY_THRESHOLD
        and stub.h2_count >= COMPREHENSIVE_MIN_H2
        and stub.has_real_definition
    )


def parse_stub(path: Path) -> StubCandidate | None:
    """Parse one source stub file into a :class:`StubCandidate`.

    Args:
        path: Path to a ``.md`` file.

    Returns:
        StubCandidate, or None if the file cannot be read.
    """
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError as e:
        logger.warning("Read failed for %s: %s", path, e)
        return None

    fm, body = parse_frontmatter(text)
    raw_title = str(fm.get("title", "")).strip().strip('"').strip()
    title = raw_title if raw_title else path.stem

    aliases_raw = fm.get("aliases") or []
    aliases = [str(a).strip() for a in aliases_raw if str(a).strip()]

    # ref-count: try multiple frontmatter keys
    ref_count = 0
    for key in ("referenced-by-count", "ref-count", "incoming-links"):
        v = fm.get(key)
        if isinstance(v, int):
            ref_count = max(ref_count, v)
        elif isinstance(v, str) and v.isdigit():
            ref_count = max(ref_count, int(v))

    cleaned_body = _strip_boilerplate(body)

    return StubCandidate(
        path=path,
        title=title,
        normalized_key=normalize_key(title or path.stem),
        ref_count=ref_count,
        alias_count=len(aliases),
        body_len=len(cleaned_body),
        h2_count=len(_H2_RE.findall(body)),
        has_real_definition=_has_real_definition(body),
        aliases=aliases,
    )


def classify_stub(stub: StubCandidate, target_index: set[str]) -> None:
    """Assign ``decision`` and ``reason`` in-place. Does not handle dedup
    against other stubs — that runs in a second pass after scoring.

    Args:
        stub: A parsed stub. Mutated.
        target_index: Set of keys already present in the target folder.
    """
    # Check #1: already enriched in target?
    if stub.normalized_key and stub.normalized_key in target_index:
        stub.is_already_enriched = True
        stub.decision = Decision.SKIP_ALREADY_ENRICHED
        stub.reason = f"key {stub.normalized_key!r} present in target"
        return

    # Check #2: aliases already enriched?
    for alias in stub.aliases:
        if normalize_key(alias) in target_index:
            stub.is_already_enriched = True
            stub.decision = Decision.SKIP_ALREADY_ENRICHED
            stub.reason = f"alias {alias!r} present in target"
            return

    # Check #3: already comprehensive — bypass LLM entirely
    if _looks_comprehensive(stub):
        stub.decision = Decision.READY_FOR_VAULT
        stub.reason = (
            f"body={stub.body_len}c, h2={stub.h2_count}, real-def=yes"
        )
        return

    # Check #4: low signal — empty body AND zero references
    if stub.body_len < EMPTY_BODY_THRESHOLD and stub.ref_count == 0:
        stub.decision = Decision.SKIP_LOW_SIGNAL
        stub.reason = f"body={stub.body_len}c, refs=0"
        return

    # Default: candidate
    stub.decision = Decision.CANDIDATE
    stub.reason = (
        f"body={stub.body_len}c, refs={stub.ref_count}, h2={stub.h2_count}"
    )


# ════════════════════════════════════════════════════════════════════════════
# Scoring
# ════════════════════════════════════════════════════════════════════════════

def score_stub(stub: StubCandidate) -> int:
    """Compute the priority score for a candidate stub.

    Heuristic: ``referenced-by-count`` is the strongest signal (it counts how
    many other notes already wiki-link to this concept — a measure of how
    central the concept is to the existing graph). Aliases and existing body
    content add smaller bonuses.

    Args:
        stub: A candidate stub.

    Returns:
        Integer score. Higher = higher priority.
    """
    score = stub.ref_count * 10
    score += stub.alias_count * 5
    if stub.body_len >= EMPTY_BODY_THRESHOLD:
        score += 10
    if stub.has_real_definition:
        score += 25
    # Mild penalty for very long titles (often disambiguator-heavy variants)
    if len(stub.title) > 60:
        score -= 5
    return score


def dedupe_by_key(candidates: list[StubCandidate]) -> list[StubCandidate]:
    """Within candidates, keep the highest-scoring stub per normalized key.

    Mutates losing candidates' ``decision`` to ``SKIP_DUPLICATE``.

    Args:
        candidates: All scored stubs (kept and rejected).

    Returns:
        The list unchanged (mutated in place); the winners are those still
        with ``decision == CANDIDATE``.
    """
    by_key: dict[str, StubCandidate] = {}
    for stub in candidates:
        if stub.decision != Decision.CANDIDATE or not stub.normalized_key:
            continue
        winner = by_key.get(stub.normalized_key)
        if winner is None or stub.score > winner.score:
            if winner is not None:
                winner.decision = Decision.SKIP_DUPLICATE
                winner.reason = (
                    f"lost to {stub.path.name!r} (score {stub.score} vs {winner.score})"
                )
            by_key[stub.normalized_key] = stub
        else:
            stub.decision = Decision.SKIP_DUPLICATE
            stub.reason = (
                f"lost to {winner.path.name!r} (score {winner.score} vs {stub.score})"
            )
    return candidates


def select_top_n(candidates: list[StubCandidate], top_n: int) -> list[StubCandidate]:
    """Return the top-N candidates by score; mark the rest as ``NOT_SELECTED``.

    Args:
        candidates: All scored stubs.
        top_n: Maximum keepers (0 = no cap).

    Returns:
        The selected list (sorted by score descending).
    """
    keepers = [s for s in candidates if s.decision == Decision.CANDIDATE]
    keepers.sort(key=lambda s: (-s.score, s.title.lower()))
    if top_n > 0 and len(keepers) > top_n:
        for loser in keepers[top_n:]:
            loser.decision = Decision.NOT_SELECTED
            loser.reason = f"score {loser.score} below top-{top_n} cutoff"
        keepers = keepers[:top_n]
    return keepers


