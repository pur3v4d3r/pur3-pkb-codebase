# Frontmatter parsing (standalone — does not depend on lib/frontmatter)
# ════════════════════════════════════════════════════════════════════════════

def parse_frontmatter(text: str) -> tuple[dict[str, Any], str]:
    """Split a Markdown file into (frontmatter dict, body text).

    Returns ``({}, text)`` if no frontmatter block is found or parsing fails.

    Args:
        text: Full file contents.

    Returns:
        A tuple of (frontmatter dict, body string).
    """
    match = _FM_RE.match(text)
    if not match:
        return {}, text
    try:
        fm = yaml.safe_load(match.group(1)) or {}
        if not isinstance(fm, dict):
            return {}, text
    except yaml.YAMLError as e:
        logger.debug("YAML parse failed: %s", e)
        return {}, text
    body = text[match.end():]
    return fm, body


