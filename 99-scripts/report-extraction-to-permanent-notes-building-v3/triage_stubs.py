class Decision:
    """Classification verdicts. String constants for CSV-friendly reporting."""

    CANDIDATE = "candidate"
    SKIP_ALREADY_ENRICHED = "skip-already-enriched"
    SKIP_DUPLICATE = "skip-duplicate"
    SKIP_LOW_SIGNAL = "skip-low-signal"
    READY_FOR_VAULT = "ready-for-vault"
    SKIP_PARSE_ERROR = "skip-parse-error"
    NOT_SELECTED = "not-selected"  # Was a candidate but lost the top-N cut


@dataclass
class StubCandidate:
    """One source stub plus everything needed to triage it.

    Attributes:
        path: Absolute path to the source ``.md`` file.
        title: Display title (frontmatter ``title`` or filename stem).
        normalized_key: Canonical kebab-case identifier used for dedup against
            target index and against other source stubs.
        ref_count: ``referenced-by-count`` from frontmatter (0 if missing).
        alias_count: Number of aliases declared in frontmatter.
        body_len: Length of body text (frontmatter stripped).
        h2_count: Number of ``##`` headings in body.
        has_real_definition: True if ``[!definition]`` callout has real prose
            (not the v3 placeholder).
        is_already_enriched: True if a target file with the same key exists.
        score: Composite priority score; higher = better candidate.
        decision: One of the ``Decision.*`` constants.
        reason: Human-readable explanation of the decision.
    """

    path: Path
    title: str
    normalized_key: str
    ref_count: int = 0
    alias_count: int = 0
    body_len: int = 0
    h2_count: int = 0
    has_real_definition: bool = False
    is_already_enriched: bool = False
    score: int = 0
    decision: str = Decision.CANDIDATE
    reason: str = ""
    aliases: list[str] = field(default_factory=list)


