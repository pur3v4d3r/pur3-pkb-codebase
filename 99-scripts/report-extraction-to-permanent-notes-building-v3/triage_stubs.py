# I/O layer
# ════════════════════════════════════════════════════════════════════════════

def scan_source(source_dir: Path) -> list[StubCandidate]:
    """Recursively parse every ``.md`` file under ``source_dir``.

    Args:
        source_dir: The stub folder to triage.

    Returns:
        List of parsed StubCandidates (unparseable files dropped, with a
        warning logged).
    """
    if not source_dir.is_dir():
        raise TriageError(f"Source dir not found: {source_dir}")

    stubs: list[StubCandidate] = []
    for md_path in sorted(source_dir.rglob("*.md")):
        stub = parse_stub(md_path)
        if stub is not None:
            stubs.append(stub)
    logger.info("Scanned %d source files from %s", len(stubs), source_dir)
    return stubs


def copy_to_curated(
    stubs: Iterable[StubCandidate],
    dest_dir: Path,
    *,
    dry_run: bool = False,
) -> int:
    """Copy each stub's source file into ``dest_dir``. Returns count copied.

    Filename collisions (different source filenames normalizing to same key
    but only one survives dedup, so this should be rare) are resolved by
    appending the score: ``<stem>__score-<N>.md``.

    Args:
        stubs: Stubs to copy.
        dest_dir: Destination directory (created if absent).
        dry_run: If True, log only — do not write.

    Returns:
        Number of files actually copied (0 in dry-run).
    """
    if not dry_run:
        dest_dir.mkdir(parents=True, exist_ok=True)
    n = 0
    for stub in stubs:
        target = dest_dir / stub.path.name
        if target.exists() and target.resolve() != stub.path.resolve():
            target = dest_dir / f"{stub.path.stem}__score-{stub.score}.md"
        if dry_run:
            logger.debug("[dry-run] would copy %s → %s", stub.path.name, target.name)
        else:
            shutil.copy2(stub.path, target)
            n += 1
    return n


def write_report(stubs: list[StubCandidate], report_path: Path) -> None:
    """Write the full classification of every scanned stub to CSV.

    Args:
        stubs: All stubs (kept and rejected).
        report_path: Output ``.csv`` path.
    """
    report_path.parent.mkdir(parents=True, exist_ok=True)
    with report_path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow([
            "decision", "score", "ref_count", "body_len", "h2_count",
            "real_def", "key", "title", "path", "reason",
        ])
        # Sort: candidates first by score, then everything else by decision
        ordered = sorted(
            stubs,
            key=lambda s: (
                0 if s.decision == Decision.CANDIDATE else
                1 if s.decision == Decision.READY_FOR_VAULT else
                2 if s.decision == Decision.NOT_SELECTED else 3,
                -s.score,
                s.title.lower(),
            ),
        )
        for s in ordered:
            writer.writerow([
                s.decision, s.score, s.ref_count, s.body_len, s.h2_count,
                "yes" if s.has_real_definition else "no",
                s.normalized_key, s.title, str(s.path), s.reason,
            ])
    logger.info("Wrote triage report: %s", report_path)


# ════════════════════════════════════════════════════════════════════════════
# Orchestration
# ════════════════════════════════════════════════════════════════════════════

def run_triage(
    source_dir: Path,
    target_dir: Path,
    output_root: Path,
    *,
    top_n: int,
    include_comprehensive: bool,
    dry_run: bool,
) -> dict[str, int]:
    """End-to-end triage. Returns a stats dict for the summary table.

    Args:
        source_dir: Folder containing the 1,200+ stubs.
        target_dir: Folder containing the canonical enriched notes.
        output_root: Parent dir for the three output buckets.
        top_n: Maximum curated keepers (0 = uncapped).
        include_comprehensive: If True, also copy ``ready-for-vault`` stubs to
            the curated dir (so enrich_stubs.py touches them too). Off by
            default — comprehensive notes shouldn't be re-LLM'd.
        dry_run: If True, no files are written.

    Returns:
        Dict of counts per bucket.
    """
    target_index = build_target_index(target_dir)
    all_stubs = scan_source(source_dir)

    # Phase A: per-stub classification
    for stub in all_stubs:
        classify_stub(stub, target_index)
        stub.score = score_stub(stub)

    # Phase B: cross-stub dedup
    dedupe_by_key(all_stubs)

    # Phase C: top-N selection
    keepers = select_top_n(all_stubs, top_n)
    comprehensive = [s for s in all_stubs if s.decision == Decision.READY_FOR_VAULT]

    # Phase D: I/O
    curated_dir = output_root / "curated-for-enrichment"
    comp_dir = output_root / "already-comprehensive"
    report_path = output_root / "triage-report.csv"

    n_curated = copy_to_curated(keepers, curated_dir, dry_run=dry_run)
    n_comp = copy_to_curated(comprehensive, comp_dir, dry_run=dry_run)

    if include_comprehensive and not dry_run:
        # Also copy comprehensive into the curated dir so enrich_stubs sees them
        copy_to_curated(comprehensive, curated_dir, dry_run=False)

    if not dry_run:
        write_report(all_stubs, report_path)

    # Build stats dict
    by_decision: dict[str, int] = {}
    for s in all_stubs:
        by_decision[s.decision] = by_decision.get(s.decision, 0) + 1

    return {
        "total": len(all_stubs),
        "target_index_size": len(target_index),
        "curated_copied": n_curated,
        "comprehensive_copied": n_comp,
        **by_decision,
    }


