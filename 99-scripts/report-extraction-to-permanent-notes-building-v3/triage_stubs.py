# Target index — the "already done" lookup
# ════════════════════════════════════════════════════════════════════════════

def build_target_index(target_dir: Path) -> set[str]:
    """Build the set of normalized keys already present in the target folder.

    A stub matching any of these keys is classified as already enriched.

    Args:
        target_dir: Directory of canonical enriched notes.

    Returns:
        Set of normalized keys. Empty set if target_dir is missing.
    """
    if not target_dir.is_dir():
        logger.warning("Target dir not found, index will be empty: %s", target_dir)
        return set()

    index: set[str] = set()
    for md_path in target_dir.rglob("*.md"):
        # Filename-derived key
        index.add(normalize_key(md_path.stem))
        # Title- and alias-derived keys (titles may differ from filenames)
        try:
            text = md_path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        fm, _ = parse_frontmatter(text)
        title = fm.get("title")
        if title:
            index.add(normalize_key(str(title)))
        for alias in (fm.get("aliases") or []):
            index.add(normalize_key(str(alias)))

    index.discard("")
    logger.info("Built target index: %d unique keys from %s", len(index), target_dir)
    return index


