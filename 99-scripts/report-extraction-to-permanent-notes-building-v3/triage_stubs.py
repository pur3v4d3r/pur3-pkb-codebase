def normalize_key(name: str) -> str:
    """Reduce a title or filename to a canonical kebab-case lookup key.

    Strips parenthetical disambiguators, punctuation, smart-quotes, and
    collapses whitespace + hyphens. Used to dedup variants like::

        "Achievement Goal"                                 → "achievement-goal"
        "Achievement-Goal.md"                              → "achievement-goal"
        "Achievement Goal (Achievement Goal Theory ...)"   → "achievement-goal"
        "achievement-goal-theory.md"                       → "achievement-goal-theory"

    Note: this is an *aggressive* normalizer — it intentionally collapses
    "Achievement Goal" and "Achievement Goal (AGT tradition)" to the same key
    because in your taxonomy they should resolve to one note.

    Args:
        name: Title string or filename (with or without ``.md``).

    Returns:
        Lowercase kebab-case string. Empty string if input has no alpha chars.
    """
    if not name:
        return ""
    s = str(name).strip()
    # Strip extension
    if s.lower().endswith(".md"):
        s = s[:-3]
    # Drop parenthetical content
    s = re.sub(r"\s*\([^)]*\)\s*", " ", s)
    # Normalize separators and unicode dashes to ASCII hyphen
    s = s.replace("—", "-").replace("–", "-").replace("'", "").replace("\u2019", "")
    # Replace any non-alphanumeric run with single hyphen
    s = re.sub(r"[^a-zA-Z0-9]+", "-", s)
    # Collapse repeated hyphens, strip edge hyphens, lowercase
    s = re.sub(r"-+", "-", s).strip("-").lower()
    return s


