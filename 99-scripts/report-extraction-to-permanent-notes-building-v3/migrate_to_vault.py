def clean_related_line(line_content: str, top_n: int) -> tuple[str, int, int]:
    """Dedupe wiki-links in a `**Related:**` line, keep top-N by frequency.

    Per user's choice in clarification: preserves the implicit centrality
    signal (links appearing many times are likely more central concepts) by
    using frequency-based ranking rather than alphabetical or first-seen.

    Args:
        line_content: The text after `**Related:**` and before EOL.
        top_n: Maximum number of unique links to keep (0 = uncapped).

    Returns:
        Tuple of (cleaned content joined with ` \u00b7 `, count_before, count_after).
    """
    matches = _WIKI_LINK_RE.findall(line_content)
    count_before = len(matches)
    if not matches:
        return line_content.strip(), 0, 0

    # Reconstruct the full link text (handles `[[A|alias]]` form)
    full_links: list[str] = []
    for m in _WIKI_LINK_RE.finditer(line_content):
        full_links.append(m.group(0))

    # Frequency rank, then take top-N preserving order of first appearance
    counter = Counter(full_links)
    ranked = sorted(
        counter.items(),
        key=lambda kv: (-kv[1], full_links.index(kv[0])),
    )
    if top_n > 0:
        ranked = ranked[:top_n]
    cleaned = [link for link, _ in ranked]
    return " \u00b7 ".join(cleaned), count_before, len(cleaned)


def transform_body(body: str, top_related: int) -> tuple[str, int, int]:
    """Find and clean the `**Related:**` line(s) in the body.

    Args:
        body: Full body text (frontmatter already stripped).
        top_related: Cap for the related-links list.

    Returns:
        Tuple of (transformed body, total links before, total links after).
    """
    total_before = 0
    total_after = 0

    def _replace(m: re.Match[str]) -> str:
        nonlocal total_before, total_after
        prefix = m.group(1)
        content = m.group(2)
        cleaned, before, after = clean_related_line(content, top_related)
        total_before += before
        total_after += after
        return f"{prefix}{cleaned}"

    new_body = _RELATED_LINE_RE.sub(_replace, body)
    return new_body, total_before, total_after


