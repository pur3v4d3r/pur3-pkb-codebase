def main(argv: list[str] | None = None) -> int:
    """Main entry point. Returns the process exit code."""
    parser = build_parser()
    args = parser.parse_args(argv)
    configure_logging(args.verbose, args.quiet)

    if not args.source_dir.is_dir():
        logger.error("Source directory not found: %s", args.source_dir)
        logger.error(
            "Hint: run triage_stubs.py first to populate the "
            "'already-comprehensive' bucket."
        )
        return 2

    try:
        records, stats = run_migration(
            source_dir=args.source_dir,
            staging_dir=args.staging_dir,
            vault_dir=args.vault_dir,
            top_related=args.top_related,
            dry_run=args.dry_run,
        )
    except MigrationError as e:
        logger.error("Migration failed: %s", e)
        return 2
    except KeyboardInterrupt:
        logger.warning("Interrupted by user")
        return 130
    except Exception:  # noqa: BLE001 -- top-level safety net
        logger.exception("Unexpected error during migration")
        return 1

    if stats.get("total", 0) == 0:
        logger.warning("No source files found in %s", args.source_dir)
        return 4

    if not args.dry_run:
        write_report(records, args.staging_dir / "migration-report.csv")

    _print_summary(stats, args.staging_dir, args.dry_run)
    return 0


