def run_migration(
    source_dir: Path,
    staging_dir: Path,
    vault_dir: Path,
    *,
    top_related: int,
    dry_run: bool,
) -> tuple[list[MigrationRecord], dict[str, int]]:
    """End-to-end migration. Returns (records, stats dict).

    Args:
        source_dir: Folder of already-comprehensive source notes.
        staging_dir: Where to write the normalized output.
        vault_dir: Canonical vault folder (read-only, collision check only).
        top_related: Cap on `**Related:**` wiki-links.
        dry_run: If True, write nothing.
    """
    if not source_dir.is_dir():
        raise MigrationError(f"Source dir not found: {source_dir}")

    vault_index = build_vault_index(vault_dir)
    sources = sorted(source_dir.rglob("*.md"))
    logger.info("Scanning %d source files from %s", len(sources), source_dir)

    records: list[MigrationRecord] = []
    for src in sources:
        rec = migrate_one(
            src,
            staging_dir=staging_dir,
            vault_index=vault_index,
            top_related=top_related,
            dry_run=dry_run,
        )
        records.append(rec)

    by_outcome: dict[str, int] = {}
    total_before = 0
    total_after = 0
    for r in records:
        by_outcome[r.outcome] = by_outcome.get(r.outcome, 0) + 1
        total_before += r.related_links_before
        total_after += r.related_links_after

    stats = {
        "total": len(records),
        "vault_index_size": len(vault_index),
        "related_links_before": total_before,
        "related_links_after": total_after,
        **by_outcome,
    }
    return records, stats


def write_report(records: list[MigrationRecord], report_path: Path) -> None:
    """Write the migration outcomes to CSV."""
    report_path.parent.mkdir(parents=True, exist_ok=True)
    with report_path.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow([
            "outcome", "new_filename", "links_before", "links_after",
            "aliases_added", "source_path", "new_path", "reason",
        ])
        for r in sorted(records, key=lambda r: (r.outcome, r.new_filename)):
            w.writerow([
                r.outcome, r.new_filename,
                r.related_links_before, r.related_links_after,
                "; ".join(r.aliases_added),
                str(r.source_path), str(r.new_path), r.reason,
            ])
    logger.info("Wrote migration report: %s", report_path)


