def build_vault_index(vault_dir: Path) -> set[str]:
    """Set of existing filename stems in the canonical vault folder.

    Used to skip migrations that would overwrite an already-vaulted note.

    Args:
        vault_dir: Path to the canonical vault folder.

    Returns:
        Set of lowercased filename stems. Empty if vault_dir is missing.
    """
    if not vault_dir.is_dir():
        logger.warning("Vault dir not found, collision check disabled: %s", vault_dir)
        return set()
    stems = {p.stem.lower() for p in vault_dir.rglob("*.md")}
    logger.info("Built vault index: %d filenames from %s", len(stems), vault_dir)
    return stems


