def parse_frontmatter(text: str) -> tuple[dict[str, Any], str]:
    """Split a Markdown file into (frontmatter dict, body text).

    Returns ``({}, text)`` if no frontmatter block is found or parsing fails.
    """
    match = _FM_RE.match(text)
    if not match:
        return {}, text
    try:
        fm = yaml.safe_load(match.group(1)) or {}
        if not isinstance(fm, dict):
            return {}, text
    except yaml.YAMLError as e:
        logger.debug("YAML parse failed: %s", e)
        return {}, text
    body = text[match.end():]
    return fm, body


def dump_frontmatter(fm: dict[str, Any]) -> str:
    """Serialize a frontmatter dict back to a YAML block.

    Uses block-style sequences for list fields (matches vault style).

    Args:
        fm: Frontmatter dict.

    Returns:
        String including leading ``---`` and trailing ``---\\n``.
    """
    body = yaml.safe_dump(
        fm,
        sort_keys=False,
        allow_unicode=True,
        default_flow_style=False,
        width=120,
    )
    return f"---\n{body}---\n"


def normalize_frontmatter(
    fm: dict[str, Any],
    *,
    source_title: str,
    slug: str,
) -> tuple[dict[str, Any], list[str]]:
    """Return a normalized frontmatter dict plus the list of aliases added.

    Behavior:
        - Sets ``title`` to the source title if missing.
        - Generates ``aliases`` from slug + spaced-title form (per user's
          choice in clarification).
        - Preserves source-provided aliases; merges with generated ones.
        - Ensures required fields exist with sensible defaults.
        - Leaves all other source-provided fields untouched.

    Args:
        fm: Source frontmatter dict (mutated copy returned).
        source_title: Title from the source frontmatter or filename.
        slug: kebab-case slug for this note.

    Returns:
        Tuple of (normalized frontmatter dict, list of aliases newly added).
    """
    out = dict(fm)  # shallow copy

    # title
    if not out.get("title"):
        out["title"] = source_title

    # aliases: merge source + generated
    existing_aliases = out.get("aliases") or []
    if not isinstance(existing_aliases, list):
        existing_aliases = [str(existing_aliases)]
    existing_set = {str(a).strip() for a in existing_aliases if str(a).strip()}

    generated: list[str] = []
    spaced_form = source_title.strip()
    if spaced_form and spaced_form not in existing_set:
        generated.append(spaced_form)
    if slug and slug not in existing_set and slug != spaced_form:
        generated.append(slug)

    out["aliases"] = [
        *(str(a) for a in existing_aliases if str(a).strip()),
        *generated,
    ]

    # Ensure required fields with safe defaults if missing
    out.setdefault("type", "permanent-note")
    out.setdefault("status", "evergreen")
    if "tags" not in out or not out["tags"]:
        out["tags"] = ["permanent-note"]
    elif not isinstance(out["tags"], list):
        out["tags"] = [str(out["tags"])]

    return out, generated


