def migrate_one(
    src: Path,
    *,
    staging_dir: Path,
    vault_index: set[str],
    top_related: int,
    dry_run: bool,
) -> MigrationRecord:
    """Migrate one source file. Returns a :class:`MigrationRecord`."""
    try:
        text = src.read_text(encoding="utf-8", errors="replace")
    except OSError as e:
        return MigrationRecord(
            source_path=src,
            new_filename="",
            new_path=Path(),
            outcome=Outcome.SKIPPED_PARSE_ERROR,
            reason=f"read failed: {e}",
        )

    fm, body = parse_frontmatter(text)
    source_title = str(fm.get("title", "")).strip().strip('"').strip() or src.stem
    slug = kebab_filename(source_title) or kebab_filename(src.stem)
    if not slug:
        return MigrationRecord(
            source_path=src,
            new_filename="",
            new_path=Path(),
            outcome=Outcome.SKIPPED_PARSE_ERROR,
            reason="could not derive a kebab-case slug",
        )

    new_filename = f"{slug}.md"
    new_path = staging_dir / new_filename

    # Collision against the canonical vault?
    if slug.lower() in vault_index:
        return MigrationRecord(
            source_path=src,
            new_filename=new_filename,
            new_path=new_path,
            outcome=Outcome.SKIPPED_COLLISION,
            reason=f"vault already has {new_filename}",
        )

    # Normalize frontmatter
    new_fm, generated_aliases = normalize_frontmatter(
        fm, source_title=source_title, slug=slug,
    )

    # Clean the body
    new_body, before, after = transform_body(body, top_related)

    # Compose the new file content
    new_text = dump_frontmatter(new_fm) + new_body

    if dry_run:
        return MigrationRecord(
            source_path=src,
            new_filename=new_filename,
            new_path=new_path,
            outcome=Outcome.DRY_RUN,
            reason="dry-run -- no write",
            related_links_before=before,
            related_links_after=after,
            aliases_added=generated_aliases,
        )

    new_path.parent.mkdir(parents=True, exist_ok=True)
    new_path.write_text(new_text, encoding="utf-8")
    return MigrationRecord(
        source_path=src,
        new_filename=new_filename,
        new_path=new_path,
        outcome=Outcome.MIGRATED,
        reason="ok",
        related_links_before=before,
        related_links_after=after,
        aliases_added=generated_aliases,
    )


