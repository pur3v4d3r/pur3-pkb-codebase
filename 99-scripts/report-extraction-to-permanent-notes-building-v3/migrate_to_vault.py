def kebab_filename(name: str) -> str:
    """Convert a free-form title or filename to aggressive kebab-case.

    Distinct from ``normalize_key`` in triage_stubs.py: this function
    PRESERVES parenthetical content (slugged) so that distinct concepts like
    ``"Chunk (Miller, 1956)"`` do not collide. Dedup against the source set
    happens during triage; by the time files reach this script they are
    already unique.

    Examples::

        "4CID Blueprint Completeness Checklist.md"
            -> "4cid-blueprint-completeness-checklist"
        "2x2 Achievement Goal Framework"
            -> "2x2-achievement-goal-framework"
        "Chunk (Miller, 1956; Chase & Simon, 1973)"
            -> "chunk-miller-1956-chase-simon-1973"

    Args:
        name: Title or filename (with or without ``.md``).

    Returns:
        Lowercase kebab-case string. Empty string if input has no alpha chars.
    """
    if not name:
        return ""
    s = str(name).strip()
    if s.lower().endswith(".md"):
        s = s[:-3]
    # Transliterate non-ASCII characters to ASCII
    for src_char, ascii_char in _TRANSLIT.items():
        s = s.replace(src_char, ascii_char)
    # Drop any remaining non-ASCII via best-effort encode
    s = s.encode("ascii", errors="ignore").decode("ascii")
    # Replace any non-alphanumeric run with single hyphen
    s = re.sub(r"[^a-zA-Z0-9]+", "-", s)
    s = re.sub(r"-+", "-", s).strip("-").lower()
    return s


