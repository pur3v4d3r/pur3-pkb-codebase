@dataclass
class RunStats:
    scanned: int = 0
    enhanced: int = 0
    cached: int = 0
    skipped_empty: int = 0
    failed: int = 0
    written: int = 0


def enhance_all(
    notes: list[V6Note],
    client: OllamaClient,
    *,
    model: str,
    bypass_cache: bool,
    dry_run: bool,
    output_dir: Path | None,
    input_dir: Path,
) -> tuple[list[EnhancementResult], RunStats]:
    """Enhance every note in ``notes``. Returns (results, stats)."""
    stats = RunStats(scanned=len(notes))
    results: list[EnhancementResult] = []
    today = dt.date.today().isoformat()
    progress_ctx, advance = _make_progress(len(notes))
    with progress_ctx as progress:
        task_id = progress.add_task("Enhancing", total=len(notes)) if progress else None
        for note in notes:
            try:
                result = enhance_one(
                    note, client, model=model, bypass_cache=bypass_cache,
                )
            except OllamaUnavailableError:
                logger.error("Ollama unavailable — aborting run")
                raise
            except Exception as e:  # defensive
                logger.exception("Unexpected error enhancing %s", note.path.name)
                result = EnhancementResult(
                    note=note, ok=False, cached=False, response=None,
                    error=f"unexpected: {e}",
                )

            if not result.ok or result.response is None:
                stats.failed += 1
                if result.error == "LLM returned no new material":
                    stats.skipped_empty += 1
                    stats.failed -= 1
                logger.warning(
                    "No enhancement for %s: %s", note.path.name, result.error,
                )
                results.append(result)
                advance(progress, task_id)
                continue

            if result.cached:
                stats.cached += 1
            stats.enhanced += 1

            pass_n = note.enhancement_passes + 1
            preamble, merged_sections = merge_response(
                note, result.response, pass_n=pass_n, today=today,
            )
            new_body = _reassemble(preamble, merged_sections)
            new_fm = update_frontmatter(
                note.frontmatter, pass_n=pass_n, model=model, today=today,
            )
            new_content = render_frontmatter(new_fm) + "\n" + new_body

            dest = _resolve_output_path(note.path, input_dir, output_dir)
            if not dry_run:
                try:
                    write_note_atomic(dest, new_content)
                    stats.written += 1
                except OSError as e:
                    logger.error("Write failed for %s: %s", dest, e)
                    stats.failed += 1
                    results.append(EnhancementResult(
                        note=note, ok=False, cached=result.cached,
                        response=result.response, error=f"write failed: {e}",
                    ))
                    advance(progress, task_id)
                    continue

            results.append(EnhancementResult(
                note=note, ok=True, cached=result.cached,
                response=result.response, error=None, written_path=dest,
            ))
            logger.info(
                "%s %s (pass %d, %s)",
                "Would enhance" if dry_run else "Enhanced",
                note.path.name, pass_n,
                "cache-hit" if result.cached else "live",
            )
            advance(progress, task_id)
    return results, stats


def _resolve_output_path(
    src: Path, input_dir: Path, output_dir: Path | None,
) -> Path:
    if output_dir is None:
        return src
    try:
        rel = src.relative_to(input_dir)
    except ValueError:
        rel = Path(src.name)
    return output_dir / rel


def _make_progress(total: int):
    """Return (context_manager, advance_fn). No-op when rich is missing."""
    if not _RICH_AVAILABLE or total == 0:
        from contextlib import nullcontext

        def _noop(_p, _t):  # noqa: ANN001
            return None
        return nullcontext(None), _noop

    progress = Progress(
        SpinnerColumn(),
        TextColumn("[progress.description]{task.description}"),
        BarColumn(),
        MofNCompleteColumn(),
        TimeElapsedColumn(),
    )

    def _advance(p, t):
        if p is not None and t is not None:
            p.advance(t)

    return progress, _advance


