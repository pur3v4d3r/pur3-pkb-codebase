def _safe_str(v: Any, default: str = "") -> str:
    if v is None:
        return default
    if isinstance(v, list):
        return ", ".join(str(x) for x in v if x)
    return str(v)


def _safe_list(v: Any) -> list[str]:
    if v is None:
        return []
    if isinstance(v, list):
        return [str(x) for x in v if x]
    return [str(v)]


def load_note(path: Path) -> V6Note:
    """Parse a V6 permanent-note markdown file into a :class:`V6Note`.

    Raises:
        NoteParseError: When the file lacks YAML frontmatter or is empty.
    """
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as e:
        raise NoteParseError(f"Cannot read {path}: {e}") from e
    if not text.strip():
        raise NoteParseError(f"Empty file: {path}")
    try:
        fm, body = parse_frontmatter(text)
    except Exception as e:  # ruamel raises various error types
        raise NoteParseError(f"Frontmatter parse failed for {path}: {e}") from e
    if not isinstance(fm, dict) or not fm:
        raise NoteParseError(f"Missing or non-mapping frontmatter: {path}")
    title = _safe_str(fm.get("title")) or path.stem.replace("-", " ").title()
    domain = _safe_str(fm.get("domain"), "general")
    parent = _safe_str(fm.get("parent-concept"), "")
    aliases = _safe_list(fm.get("aliases"))
    provenance = fm.get("provenance") or {}
    passes = 0
    if isinstance(provenance, dict):
        try:
            passes = int(provenance.get("enhancement-passes", 0) or 0)
        except (TypeError, ValueError):
            passes = 0
    _, sections = _split_sections(body)
    return V6Note(
        path=path,
        title=title,
        domain=domain,
        parent_concept=parent,
        aliases=aliases,
        frontmatter=dict(fm),
        body=body,
        sections=sections,
        enhancement_passes=passes,
    )


def scan_notes(
    input_dir: Path,
    *,
    name_filter: str | None,
    max_passes: int,
    re_enhance: bool,
    limit: int | None,
) -> list[V6Note]:
    """Discover candidate notes for enhancement under ``input_dir``."""
    if not input_dir.is_dir():
        raise FileNotFoundError(f"Input directory not found: {input_dir}")
    notes: list[V6Note] = []
    files = sorted(input_dir.glob("*.md"))
    for path in files:
        if name_filter and name_filter.lower() not in path.stem.lower():
            continue
        try:
            note = load_note(path)
        except NoteParseError as e:
            logger.warning("Skipping unparseable note %s: %s", path.name, e)
            continue
        if not re_enhance and note.enhancement_passes >= max_passes:
            logger.debug(
                "Skipping %s — already enhanced %d/%d times",
                path.name, note.enhancement_passes, max_passes,
            )
            continue
        notes.append(note)
        if limit is not None and len(notes) >= limit:
            break
    return notes


