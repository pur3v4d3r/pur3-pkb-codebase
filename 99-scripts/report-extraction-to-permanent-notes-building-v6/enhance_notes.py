def _build_body_excerpt(note: V6Note, max_chars: int = 6000) -> str:
    """Compact representation of the existing note body for the prompt.

    The full body of dense V6 notes can exceed model context budgets when
    the prompt template + system prompt are added on top. We truncate
    section by section, preserving the heading structure so the model can
    see what it must NOT duplicate.
    """
    if len(note.body) <= max_chars:
        return note.body.strip()
    parts: list[str] = []
    budget = max_chars
    preamble, sections = _split_sections(note.body)
    if preamble.strip():
        snippet = preamble.strip()[:1500]
        parts.append(snippet)
        budget -= len(snippet)
    for name in CANONICAL_SECTIONS:
        if name not in sections or budget <= 200:
            continue
        body = sections[name].strip()
        snippet = body[: max(200, budget // max(1, len(sections)))]
        parts.append(f"## {name}\n{snippet}")
        budget -= len(snippet) + len(name) + 4
    return "\n\n".join(parts)


_RELATION_FIELDS: tuple[str, ...] = (
    "related", "prerequisites", "specializes", "broader", "see-also",
    "contrasts-with", "contradicts", "applies-to", "formalizes",
    "instance-of", "supports", "refines",
)

_WIKILINK_RE = re.compile(r"\[\[([^\]|#]+?)(?:#[^\]|]*)?(?:\|[^\]]*)?\]\]")


def _extract_related_concepts(fm: dict[str, Any]) -> list[tuple[str, str]]:
    """Extract (slug, relation_type) pairs from frontmatter relation fields.

    Empty placeholder targets like ``[[]]`` are filtered out. Duplicates
    (same slug under different relations) are kept since the relation type
    carries semantic meaning for rationale generation.
    """
    out: list[tuple[str, str]] = []
    seen: set[tuple[str, str]] = set()
    for field in _RELATION_FIELDS:
        raw = fm.get(field)
        if not raw:
            continue
        items = raw if isinstance(raw, list) else [raw]
        for item in items:
            s = str(item).strip()
            if not s:
                continue
            for m in _WIKILINK_RE.finditer(s):
                slug = m.group(1).strip()
                if not slug:
                    continue
                key = (slug, field)
                if key in seen:
                    continue
                seen.add(key)
                out.append(key)
            # Also accept bare slugs (no wiki-link wrapper)
            if "[[" not in s and s:
                key = (s, field)
                if key not in seen:
                    seen.add(key)
                    out.append(key)
    return out


def _build_user_prompt(note: V6Note) -> str:
    related = _extract_related_concepts(note.frontmatter)
    if related:
        related_str = "\n".join(
            f"  - {slug}  ({relation})" for slug, relation in related
        )
    else:
        related_str = "  (none listed in frontmatter)"
    distinction_str = "\n".join(f"  - {d}" for d in KEY_DISTINCTION_SUGGESTIONS)
    return _USER_PROMPT_TEMPLATE.format(
        title=note.title,
        domain=note.domain or "general",
        parent=note.parent_concept or "(none specified)",
        aliases=", ".join(note.aliases) if note.aliases else "(none)",
        related_concepts=related_str,
        distinction_suggestions=distinction_str,
        body_excerpt=_build_body_excerpt(note),
    )


# ════════════════════════════════════════════════════════════════════════════
# LLM call
# ════════════════════════════════════════════════════════════════════════════

def _body_hash(body: str) -> str:
    """Stable content fingerprint used in the cache key."""
    return hashlib.sha1(body.encode("utf-8")).hexdigest()[:16]


def enhance_one(
    note: V6Note,
    client: OllamaClient,
    *,
    model: str,
    bypass_cache: bool,
) -> EnhancementResult:
    """Run a single LLM enhancement pass against ``note``."""
    user_prompt = _build_user_prompt(note)
    cache_key_inputs = (
        PROMPT_CONTRACT_VERSION,
        model,
        note.title,
        _body_hash(note.body),
    )
    try:
        rsp = client.chat_json(
            system=SYSTEM_PROMPT,
            user=user_prompt,
            schema=EnhancementResponse,
            cache_key_inputs=cache_key_inputs,
            model=model,
            bypass_cache=bypass_cache,
        )
    except StructuredOutputError as e:
        return EnhancementResult(
            note=note, ok=False, cached=False, response=None,
            error=f"Schema validation failed: {e}",
        )
    except OllamaUnavailableError:
        raise   # bubble up — pipeline-level failure
    except LLMError as e:
        return EnhancementResult(
            note=note, ok=False, cached=False, response=None,
            error=f"LLM error: {e}",
        )
    response: EnhancementResponse = rsp.parsed  # type: ignore[assignment]
    if response.is_empty():
        return EnhancementResult(
            note=note, ok=False, cached=rsp.cached, response=response,
            error="LLM returned no new material",
        )
    return EnhancementResult(
        note=note, ok=True, cached=rsp.cached, response=response, error=None,
    )


# ════════════════════════════════════════════════════════════════════════════
# Section appenders
# ════════════════════════════════════════════════════════════════════════════

def _marker(pass_n: int, today: str) -> str:
    return f"<!-- enhancement-pass:{pass_n} ({today}) -->"


def _append_paragraphs(
    sections: dict[str, str],
    section_name: str,
    paragraphs: list[str],
    pass_n: int,
    today: str,
) -> bool:
    """Append plain-prose paragraphs to a section. Returns True if changed."""
    cleaned = [p.strip() for p in paragraphs if p and p.strip()]
    if not cleaned:
        return False
    block = "\n\n".join(cleaned)
    addition = f"\n\n{_marker(pass_n, today)}\n{block}\n"
    if section_name in sections:
        sections[section_name] = sections[section_name].rstrip() + addition
    else:
        sections[section_name] = addition.lstrip("\n")
    return True


def _append_implications(
    sections: dict[str, str],
    items: list[_Implication],
    existing_count: int,
    pass_n: int,
    today: str,
) -> bool:
    if not items:
        return False
    blocks: list[str] = [_marker(pass_n, today)]
    for i, imp in enumerate(items, start=existing_count + 1):
        body = imp.body.strip().replace("\n", "\n> ")
        blocks.append(
            f"> [!example] **Application {i} — {imp.scenario.strip()}**\n> {body}"
        )
    addition = "\n\n" + "\n\n".join(blocks) + "\n"
    section = "Practical Implications"
    if section in sections:
        sections[section] = sections[section].rstrip() + addition
    else:
        sections[section] = addition.lstrip("\n")
    return True


def _append_distinctions(
    sections: dict[str, str],
    items: list[_Distinction],
    pass_n: int,
    today: str,
) -> bool:
    if not items:
        return False
    blocks: list[str] = [_marker(pass_n, today)]
    for d in items:
        body = d.body.strip().replace("\n", "\n> ")
        blocks.append(
            f"> [!key-distinction] **{d.title.strip()}**\n> {body}"
        )
    addition = "\n\n" + "\n\n".join(blocks) + "\n"
    section = "Key Distinctions"
    if section in sections:
        sections[section] = sections[section].rstrip() + addition
    else:
        sections[section] = addition.lstrip("\n")
    return True


def _append_figures(
    sections: dict[str, str],
    items: list[_Figure],
    pass_n: int,
    today: str,
) -> bool:
    if not items:
        return False
    lines: list[str] = [_marker(pass_n, today)]
    for f in items:
        lines.append(f"- **{f.name.strip()}** — {f.contribution.strip()}")
    addition = "\n\n" + "\n".join(lines) + "\n"
    section = "Key Figures"
    if section in sections:
        sections[section] = sections[section].rstrip() + addition
    else:
        sections[section] = addition.lstrip("\n")
    return True


def _append_questions(
    sections: dict[str, str],
    items: list[_Question],
    pass_n: int,
    today: str,
) -> bool:
    if not items:
        return False
    blocks: list[str] = [_marker(pass_n, today)]
    for q in items:
        body_lines = [f"> {q.question.strip()}"]
        if q.resolution and q.resolution.strip():
            body_lines.append(">")
            body_lines.append(f"> *What would resolve it:* {q.resolution.strip()}")
        blocks.append("> [!open-question] **Question**\n" + "\n".join(body_lines))
    addition = "\n\n" + "\n\n".join(blocks) + "\n"
    section = "Open Questions"
    if section in sections:
        sections[section] = sections[section].rstrip() + addition
    else:
        sections[section] = addition.lstrip("\n")
    return True


def _append_misconceptions(
    sections: dict[str, str],
    items: list[_Misconception],
    pass_n: int,
    today: str,
) -> bool:
    """Append a Common Misconceptions section / block. Returns True if changed."""
    if not items:
        return False
    blocks: list[str] = [_marker(pass_n, today)]
    for m in items:
        misc = m.misconception.strip().rstrip(".") + "."
        correction = m.correction.strip().replace("\n", "\n> ")
        blocks.append(
            f"> [!warning] **Misconception** — {misc}\n>\n> {correction}"
        )
    addition = "\n\n" + "\n\n".join(blocks) + "\n"
    section = "Common Misconceptions"
    if section in sections:
        sections[section] = sections[section].rstrip() + addition
    else:
        sections[section] = addition.lstrip("\n")
    return True


def _append_connection_rationales(
    sections: dict[str, str],
    items: list[_ConnectionRationale],
    pass_n: int,
    today: str,
) -> bool:
    """Append a 'Why these connections matter' subsection to Connections & Context.

    The original auto-generated relation list (Falls under, Prerequisites, etc.)
    is preserved verbatim; rationales are appended below it under their own
    enhancement marker so they can be identified and rolled back.
    """
    if not items:
        return False
    blocks: list[str] = [
        _marker(pass_n, today),
        "### Why these connections matter",
    ]
    for c in items:
        target = c.target.strip().strip("[]")
        relation = (c.relation or "related-to").strip()
        rationale = c.rationale.strip().replace("\n", "\n> ")
        blocks.append(
            f"> [!connection] **[[{target}]]** — *{relation}*\n> {rationale}"
        )
    addition = "\n\n" + "\n\n".join(blocks) + "\n"
    section = "Connections & Context"
    if section in sections:
        sections[section] = sections[section].rstrip() + addition
    else:
        sections[section] = addition.lstrip("\n")
    return True


def merge_response(
    note: V6Note,
    response: EnhancementResponse,
    *,
    pass_n: int,
    today: str,
) -> tuple[str, dict[str, str]]:
    """Merge an EnhancementResponse into a copy of the note's sections.

    Returns:
        (preamble, updated_sections) ready for ``_reassemble``.
    """
    preamble, _ = _split_sections(note.body)
    sections: dict[str, str] = dict(note.sections)
    existing_implications = sections.get("Practical Implications", "").count(
        "[!example]"
    )

    _append_paragraphs(
        sections, "Core Explanation", response.extra_explanation_paragraphs,
        pass_n, today,
    )
    if response.mechanism_addition and response.mechanism_addition.strip():
        _append_paragraphs(
            sections, "Mechanism", [response.mechanism_addition], pass_n, today,
        )
    _append_implications(
        sections, response.extra_implications, existing_implications, pass_n, today,
    )
    _append_distinctions(sections, response.extra_distinctions, pass_n, today)
    _append_misconceptions(sections, response.common_misconceptions, pass_n, today)
    _append_figures(sections, response.extra_figures, pass_n, today)
    _append_questions(sections, response.extra_questions, pass_n, today)
    if response.synthesis_addition and response.synthesis_addition.strip():
        _append_paragraphs(
            sections, "Synthesis", [response.synthesis_addition], pass_n, today,
        )
    if response.evidence_addition and response.evidence_addition.strip():
        _append_paragraphs(
            sections, "Evidence", [response.evidence_addition], pass_n, today,
        )
    _append_connection_rationales(
        sections, response.connection_rationales, pass_n, today,
    )
    return preamble, sections


# ════════════════════════════════════════════════════════════════════════════
# Frontmatter update
# ════════════════════════════════════════════════════════════════════════════

def update_frontmatter(
    fm: dict[str, Any],
    *,
    pass_n: int,
    model: str,
    today: str,
) -> dict[str, Any]:
    """Return a new frontmatter dict with enhancement provenance applied.

    Preserves all user-editable fields. Only writes/updates:
        - updated
        - maturity-stage  (budding → evergreen after pass >= 2)
        - depth-level     ('elaborated' → 'enhanced')
        - provenance.enhancement-passes
        - provenance.enhancement-model
        - provenance.enhancement-method
        - provenance.last-enhanced
    """
    out = dict(fm)
    out["updated"] = today
    if pass_n >= 2 and out.get("maturity-stage") == "budding":
        out["maturity-stage"] = "evergreen"
    if out.get("depth-level") in (None, "", "elaborated"):
        out["depth-level"] = "enhanced"
    provenance = dict(out.get("provenance") or {})
    provenance["enhancement-passes"] = pass_n
    provenance["enhancement-model"] = model
    provenance["enhancement-method"] = "enhance_notes-v1"
    provenance["last-enhanced"] = today
    out["provenance"] = provenance
    return out


