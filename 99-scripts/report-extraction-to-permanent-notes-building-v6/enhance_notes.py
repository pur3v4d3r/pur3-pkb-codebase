def configure_logging(verbosity: int, quiet: bool) -> None:
    """Configure root logger from CLI verbosity flags."""
    if quiet:
        level = logging.ERROR
    elif verbosity >= 2:
        level = logging.DEBUG
    elif verbosity == 1:
        level = logging.INFO
    else:
        level = logging.WARNING
    logging.basicConfig(
        level=level,
        format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
    )


def _summarize_response(resp: EnhancementResponse | None) -> dict[str, int]:
    """Return per-section addition counts for a single enhancement response."""
    if resp is None:
        return {}
    counts: dict[str, int] = {}
    if resp.extra_explanation_paragraphs:
        counts["Core Explanation paragraphs"] = len(resp.extra_explanation_paragraphs)
    if resp.mechanism_addition:
        counts["Mechanism addition"] = 1
    if resp.extra_implications:
        counts["Practical Implications"] = len(resp.extra_implications)
    if resp.extra_distinctions:
        counts["Key Distinctions"] = len(resp.extra_distinctions)
    if resp.common_misconceptions:
        counts["Common Misconceptions"] = len(resp.common_misconceptions)
    if resp.extra_figures:
        counts["Key Figures"] = len(resp.extra_figures)
    if resp.extra_questions:
        counts["Open Questions"] = len(resp.extra_questions)
    if resp.synthesis_addition:
        counts["Synthesis addition"] = 1
    if resp.evidence_addition:
        counts["Evidence addition"] = 1
    if resp.connection_rationales:
        counts["Connection rationales"] = len(resp.connection_rationales)
    return counts


def write_run_report(
    results: list[EnhancementResult],
    stats: RunStats,
    args: argparse.Namespace,
    *,
    report_dir: Path,
) -> Path:
    """Write a markdown report of an enhancement run.

    The report lists every successfully enhanced note with a per-section
    breakdown of what the LLM added. Useful for reviewing and rolling back.

    Args:
        results: All EnhancementResults from the run.
        stats: Aggregate run statistics.
        args: Parsed CLI args (used for run metadata).
        report_dir: Destination directory; created if missing.

    Returns:
        The path to the written report file.

    Raises:
        OSError: If the report directory or file cannot be written.
    """
    report_dir.mkdir(parents=True, exist_ok=True)
    ts = dt.datetime.now()
    stamp = ts.strftime("%Y-%m-%d_%H%M%S")
    report_path = report_dir / f"enhancement-run-{stamp}.md"

    enhanced = [r for r in results if r.ok]
    cached_only = [r for r in enhanced if r.cached]
    live = [r for r in enhanced if not r.cached]
    failed = [r for r in results if not r.ok]

    lines: list[str] = []
    lines.append("---")
    lines.append(f"title: Enhancement Run — {ts.isoformat(timespec='seconds')}")
    lines.append("type: enhancement-run-report")
    lines.append("tags: [enhancement-report, v6-pipeline]")
    lines.append(f"run-timestamp: '{ts.isoformat(timespec='seconds')}'")
    lines.append(f"model: {args.model}")
    lines.append(f"input-dir: '{args.input_dir}'")
    if args.output_dir:
        lines.append(f"output-dir: '{args.output_dir}'")
    lines.append(f"scanned: {stats.scanned}")
    lines.append(f"enhanced: {stats.enhanced}")
    lines.append(f"cache-hits: {stats.cached}")
    lines.append(f"skipped-empty: {stats.skipped_empty}")
    lines.append(f"failed: {stats.failed}")
    lines.append(f"files-written: {stats.written}")
    lines.append("---")
    lines.append("")
    lines.append(f"# Enhancement Run — {ts.strftime('%Y-%m-%d %H:%M:%S')}")
    lines.append("")
    lines.append("## Summary")
    lines.append("")
    lines.append(f"- **Model:** `{args.model}`")
    lines.append(f"- **Input directory:** `{args.input_dir}`")
    if args.output_dir:
        lines.append(f"- **Output directory:** `{args.output_dir}`")
    else:
        lines.append("- **Output directory:** *(in-place)*")
    lines.append(f"- **Scanned:** {stats.scanned}")
    lines.append(f"- **Enhanced:** {stats.enhanced} "
                 f"(live: {len(live)}, cache-hits: {len(cached_only)})")
    lines.append(f"- **Skipped (empty LLM result):** {stats.skipped_empty}")
    lines.append(f"- **Failed:** {stats.failed}")
    lines.append(f"- **Files written:** {stats.written}")
    lines.append("")

    if enhanced:
        lines.append("## Enhanced Notes")
        lines.append("")
        lines.append("| # | Note | Cache | Additions |")
        lines.append("|---:|------|:-----:|-----------|")
        for i, r in enumerate(enhanced, start=1):
            stem = r.note.path.stem
            counts = _summarize_response(r.response)
            additions = (
                ", ".join(f"{k}: {v}" for k, v in counts.items())
                if counts else "_(no new material)_"
            )
            cache_marker = "✓" if r.cached else " "
            lines.append(f"| {i} | [[{stem}]] | {cache_marker} | {additions} |")
        lines.append("")

        lines.append("## Per-Note Detail")
        lines.append("")
        for r in enhanced:
            stem = r.note.path.stem
            lines.append(f"### [[{stem}]]")
            lines.append("")
            lines.append(f"- **Source path:** `{r.note.path}`")
            if r.written_path:
                lines.append(f"- **Written to:** `{r.written_path}`")
            lines.append(f"- **Cache hit:** {'yes' if r.cached else 'no'}")
            lines.append(f"- **Pass count after run:** "
                         f"{r.note.enhancement_passes + 1}")
            counts = _summarize_response(r.response)
            if counts:
                lines.append("- **Additions:**")
                for k, v in counts.items():
                    lines.append(f"  - {k}: **{v}**")
            else:
                lines.append("- **Additions:** _none — LLM returned an empty response._")
            lines.append("")

    if failed:
        lines.append("## Failed Notes")
        lines.append("")
        for r in failed:
            stem = r.note.path.stem
            lines.append(f"- [[{stem}]] — `{r.error}`")
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("*Generated by `enhance_notes.py` "
                 f"v{__version__}.*")
    lines.append("")

    text = "\n".join(lines)
    tmp = report_path.with_suffix(".md.tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(report_path)
    return report_path


def _print_summary(stats: RunStats, dry_run: bool) -> None:
    title = "DRY-RUN SUMMARY" if dry_run else "ENHANCEMENT SUMMARY"
    bar = "=" * 60
    lines = [
        "",
        bar,
        f"  {title}",
        bar,
        f"  Scanned:                    {stats.scanned}",
        f"  Enhanced:                   {stats.enhanced} (cache-hits: {stats.cached})",
        f"  Skipped (empty LLM result): {stats.skipped_empty}",
        f"  Failed:                     {stats.failed}",
        f"  Files written:              {stats.written}",
        bar,
    ]
    # Robust against Windows cp1252 stdout if any non-ASCII slips in.
    try:
        sys.stdout.write("\n".join(lines) + "\n")
    except UnicodeEncodeError:
        sys.stdout.write(
            ("\n".join(lines) + "\n").encode("ascii", "replace").decode("ascii")
        )


def main(argv: list[str] | None = None) -> int:
    """Main entry point.

    Returns:
        0 success, 1 uncaught, 2 input-dir not found, 4 no notes,
        5 strict + failures, 6 ollama unavailable, 130 interrupted.
    """
    parser = build_parser()
    args = parser.parse_args(argv)
    configure_logging(args.verbose, args.quiet)

    try:
        notes = scan_notes(
            args.input_dir,
            name_filter=args.note,
            max_passes=args.max_passes,
            re_enhance=args.re_enhance,
            limit=args.limit,
        )
    except FileNotFoundError as e:
        logger.error("%s", e)
        return 2

    if not notes:
        logger.error(
            "No notes selected (input=%s, filter=%s, max-passes=%d).",
            args.input_dir, args.note, args.max_passes,
        )
        return 4

    logger.info("Selected %d note(s) for enhancement.", len(notes))

    try:
        with OllamaClient(
            model=args.model,
            cache_dir=config_v3.LLM_CACHE_DIR,
        ) as client:
            try:
                results, stats = enhance_all(
                    notes, client,
                    model=args.model,
                    bypass_cache=args.bypass_cache,
                    dry_run=args.dry_run,
                    output_dir=args.output_dir,
                    input_dir=args.input_dir,
                )
            except OllamaUnavailableError as e:
                logger.error("Ollama unavailable: %s", e)
                return 6
    except OllamaUnavailableError as e:
        logger.error("Ollama unavailable on startup: %s", e)
        return 6
    except KeyboardInterrupt:
        logger.warning("Interrupted by user.")
        return 130

    _print_summary(stats, args.dry_run)

    # Write the run report (skip on dry-run, on --no-report, or if nothing changed).
    if not args.dry_run and not args.no_report and stats.enhanced > 0:
        try:
            report_path = write_run_report(
                results, stats, args, report_dir=args.report_dir,
            )
            logger.info("Run report written: %s", report_path)
        except OSError as e:
            logger.warning("Could not write run report: %s", e)

    if args.strict and stats.failed > 0:
        logger.error("Strict mode: %d failure(s).", stats.failed)
        return 5
    return 0


