#: Match an H2 header. Captures the heading text.
_H2_RE = re.compile(r"^##\s+(.+?)\s*$", re.MULTILINE)


def _split_sections(body: str) -> tuple[str, dict[str, str]]:
    """Split a markdown body into (preamble, {section_name: section_body}).

    The preamble is everything before the first ``##`` header (typically
    the H1 title and the ``[!definition]`` callout). Section bodies do
    NOT include their own ``## Header`` line — only the content underneath,
    up to the next H2 or end of file.
    """
    matches = list(_H2_RE.finditer(body))
    if not matches:
        return body, {}
    preamble = body[: matches[0].start()].rstrip() + "\n"
    sections: dict[str, str] = {}
    for i, m in enumerate(matches):
        name = m.group(1).strip()
        start = m.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(body)
        sections[name] = body[start:end].strip("\n")
    return preamble, sections


def _reassemble(preamble: str, sections: dict[str, str]) -> str:
    """Rebuild a body from preamble + sections in canonical order.

    Sections not present in CANONICAL_SECTIONS are appended at the end in
    insertion order (preserves any custom sections the user may have added).
    """
    parts: list[str] = [preamble.rstrip(), ""]
    seen: set[str] = set()
    for name in CANONICAL_SECTIONS:
        if name in sections:
            parts.append(f"## {name}")
            parts.append("")
            parts.append(sections[name].strip("\n"))
            parts.append("")
            seen.add(name)
    for name, content in sections.items():
        if name in seen:
            continue
        parts.append(f"## {name}")
        parts.append("")
        parts.append(content.strip("\n"))
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


