def _fix_bare_arrows(content: str) -> str:
    """Join split arrow lines where the LLM put the target node on the next line.

    Some models emit::

        A -->|Relies on|
          B[Node]

    which is invalid Mermaid syntax.  This joins such pairs into::

        A -->|Relies on| B[Node]

    The fix is applied line-by-line.  A line qualifies as a "bare arrow" when
    it ends with an edge operator (``-->``, ``-->|label|``, ``---``, etc.) and
    contains no closing shape bracket after the operator.  The following
    non-blank line must look like a node reference and must *not* itself
    contain an arrow operator (to avoid accidentally merging two real arrows).

    Args:
        content: Raw mermaid content string (no fences).

    Returns:
        Content with split arrow lines joined.
    """
    # Matches a line whose last non-whitespace is an arrow tail:
    #   optional leading whitespace, some non-newline, then arrow-style ending.
    _bare = re.compile(
        r"^([ \t]*\S[^\n]*?(?:--[>\-xo]+>?|\.\.\.|==>)(?:\|[^|\n]*\|)?)\s*$"
    )
    # Matches lines that contain an arrow (so we don't merge two real arrows).
    _has_arrow = re.compile(r"--[>\-xo]|\.\.\.>|==>")

    lines = content.splitlines()
    result: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        m = _bare.match(line)
        if m:
            # Peek ahead, skipping any blank lines in between.
            j = i + 1
            while j < len(lines) and not lines[j].strip():
                j += 1
            if j < len(lines):
                nxt = lines[j]
                if nxt.strip() and not _has_arrow.search(nxt):
                    # Merge: arrow line + target line.
                    result.append(line.rstrip() + " " + nxt.strip())
                    i = j + 1
                    continue
        result.append(line)
        i += 1
    return "\n".join(result)


def _fix_mermaid_content(content: str) -> str:
    """Best-effort fix for LLM-produced malformed Mermaid content.

    Applies several targeted fixups in order, then handles the rarer case of
    a completely one-liner output:

    1. **Bare-arrow join** — ``A -->|label|\\n  B`` → ``A -->|label| B``
       (some models emit the arrow and its target node on separate lines).
    2. **Participant bracket** — ``participant X[Label]`` →
       ``participant X as Label`` (sequence-diagram syntax error).
    3. **Single-quoted labels** — ``B['text']`` → ``B["text"]``
       (Mermaid only accepts double-quoted strings).
    4. **Paren-in-brackets quoting** — ``A[Node (detail)]`` →
       ``A["Node (detail)"]`` (parentheses inside ``[]`` break Mermaid's
       shape parser; applies to ALL content, not just one-liners).
    5. **One-liner re-split** — when the entire diagram is collapsed onto one
       line the diagram-type header and node boundaries are split out.

    Args:
        content: Raw mermaid content string (no fences, no callout ``> `` prefix).

    Returns:
        Content with each logical statement on its own line and known syntax
        issues resolved.
    """
    content = content.strip()

    # ── Fix 1: bare arrows (multi-line content — must run before early-return) ──
    # Only pay the line-splitting cost when the signature pattern is present.
    if re.search(r"--[>\-xo]+>?(?:\|[^|\n]*\|)?\s*$", content, re.MULTILINE):
        content = _fix_bare_arrows(content)

    # ── Fix 2: participant X[Y] → participant X as Y ──────────────────────────
    content = re.sub(
        r"participant\s+(\w+)\[([^\]]+)\]",
        r"participant \1 as \2",
        content,
    )

    # ── Fix 3: ['single-quoted labels'] → ["double-quoted labels"] ───────────
    content = re.sub(r"\['([^']+)'\]", r'["\1"]', content)

    # ── Fix 4: [label with (parens)] → ["label with (parens)"] ──────────────
    # e.g.  A[Scale Factor a(t)]  →  A["Scale Factor a(t)"]
    # Mermaid treats '(' inside '[]' as a shape operator — must run on ALL
    # content (multi-line and one-liner alike).
    content = re.sub(
        r"\[([^\]\"]*\([^)]*\)[^\]\"'.]*)\]",
        r'["\1"]',
        content,
    )

    # ── Early-return for well-formed multi-line content ───────────────────────
    # Fix 5 only makes sense for degenerate one-liner LLM output.
    if content.count("\n") >= 2:
        return content

    # ── Fix 5: split one-liner — diagram-type header from first node ──────────
    content = re.sub(
        r"^((?:flowchart|graph|sequenceDiagram|classDiagram|stateDiagram-v2?|erDiagram)\s*\S*)\s+",
        r"\1\n",
        content,
    )
    # Insert newline before any bare node ID that starts a new statement:
    # pattern = closing bracket/paren/brace + whitespace + word-char followed
    # by either a shape opener OR an edge operator.
    content = re.sub(
        r"([\]\)\}])\s+(?=[A-Za-z_]\w*(?:\s*[\[\(\{]|\s+-->|\s+---|\.\.\.>))",
        r"\1\n",
        content,
    )

    return content


def _render_diagram_block(diagram: Diagram, index: int) -> str:
    """Render a single :class:`Diagram` into Obsidian-ready markdown.

    Mermaid diagrams are placed inside a ``[!abstract]`` callout block that
    wraps the fenced code block — this is the most compatible layout for
    Obsidian ≥1.5.  ASCII diagrams use a plain code block (triple backticks)
    with a preceding caption line to keep them readable.

    Args:
        diagram: The diagram to render.
        index: 1-based position counter (used for heading label).

    Returns:
        A self-contained markdown string for this diagram.
    """
    label = f"Diagram {index} — {diagram.caption}"
    hint_line = f"> *{diagram.view_hint.strip()}*\n>\n" if diagram.view_hint.strip() else ""

    if diagram.diagram_type == "mermaid":
        # Obsidian renders Mermaid inside callout bodies as of v1.5+.
        # The nested code fence uses 4 backticks so the 3-backtick mermaid
        # fence does not close the outer callout prematurely.
        # _fix_mermaid_content handles rare LLM one-liner outputs.
        mermaid_content = _fix_mermaid_content(diagram.content)
        return (
            f"> [!abstract] **{label}**\n"
            f"{hint_line}"
            f"> ```mermaid\n"
            + "\n".join(f"> {line}" for line in mermaid_content.splitlines())
            + "\n> ```\n"
        )
    else:
        # ASCII: plain fenced block with caption above.
        return (
            f"**{label}**\n\n"
            f"{ASCII_FONT_NOTE}\n\n"
            + (f"*{diagram.view_hint.strip()}*\n\n" if diagram.view_hint.strip() else "")
            + "```\n"
            + diagram.content
            + "\n```\n"
        )


def build_diagram_section(
    response: DiagramResponse,
    *,
    pass_n: int,
    today: str,
) -> str:
    """Assemble the complete ``## 📊 Visual Overview`` section string.

    Args:
        response: Validated :class:`DiagramResponse` from the LLM.
        pass_n: Pass number stamped into the HTML marker comment.
        today: ISO-8601 date string for the marker.

    Returns:
        A markdown string starting with the section header, ready to prepend
        to the note body.
    """
    marker = f"<!-- diagram-pass:{pass_n} ({today}) -->"
    parts: list[str] = [DIAGRAM_SECTION_HEADER, "", marker, ""]
    for i, diagram in enumerate(response.diagrams, start=1):
        parts.append(_render_diagram_block(diagram, i))
        parts.append("")
    return "\n".join(parts)


