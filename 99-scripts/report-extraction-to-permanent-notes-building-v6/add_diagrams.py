def _body_hash(body: str) -> str:
    """Stable 16-char content fingerprint used in the cache key."""
    return hashlib.sha1(body.encode("utf-8")).hexdigest()[:16]


def diagram_one(
    note: V6Note,
    client: OllamaClient,
    *,
    model: str,
    bypass_cache: bool,
) -> DiagramResult:
    """Run a single LLM diagram pass for ``note``.

    Args:
        note: The parsed V6 note to diagram.
        client: An active :class:`OllamaClient` instance.
        model: Ollama model name override.
        bypass_cache: When True, skip the LLM response cache.

    Returns:
        :class:`DiagramResult` with ``ok=True`` when diagrams were generated.
    """
    user_prompt = _build_user_prompt(note)
    cache_key_inputs = (
        PROMPT_CONTRACT_VERSION,
        model,
        note.title,
        _body_hash(note.body),
    )
    try:
        rsp = client.chat_json(
            system=_SYSTEM_PROMPT,
            user=user_prompt,
            schema=DiagramResponse,
            cache_key_inputs=cache_key_inputs,
            model=model,
            bypass_cache=bypass_cache,
        )
    except StructuredOutputError as e:
        return DiagramResult(
            note=note, ok=False, cached=False, response=None,
            error=f"Schema validation failed: {e}",
        )
    except OllamaUnavailableError:
        raise   # bubble up — pipeline-level failure
    except LLMError as e:
        return DiagramResult(
            note=note, ok=False, cached=False, response=None,
            error=f"LLM error: {e}",
        )

    response: DiagramResponse = rsp.parsed  # type: ignore[assignment]
    if response.is_empty():
        return DiagramResult(
            note=note, ok=False, cached=rsp.cached, response=response,
            error="LLM returned no usable diagrams",
        )
    return DiagramResult(
        note=note, ok=True, cached=rsp.cached, response=response, error=None,
    )


