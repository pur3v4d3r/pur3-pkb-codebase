class Diagram(BaseModel):
    """A single diagram: one Mermaid or one ASCII block."""

    diagram_type: Literal["mermaid", "ascii"] = Field(
        ...,
        description="'mermaid' for Mermaid.js syntax, 'ascii' for plain-text art.",
    )
    caption: str = Field(
        ...,
        min_length=4,
        max_length=120,
        description="Short title / label for the diagram (3–12 words).",
    )
    view_hint: str = Field(
        default="",
        max_length=200,
        description=(
            "One sentence on how to interpret this diagram — what the reader "
            "should look for, or how it connects to the concept."
        ),
    )
    content: str = Field(
        ...,
        min_length=10,
        description=(
            "The raw diagram text.  For 'mermaid': valid Mermaid.js syntax "
            "(no surrounding fences).  For 'ascii': plain-text art using "
            "box-drawing chars or standard ASCII."
        ),
    )

    @field_validator("content")
    @classmethod
    def _strip_code_fences(cls, v: str) -> str:
        """Remove accidental ``` fences the model may have added."""
        v = v.strip()
        # Strip opening fence (```mermaid, ```ascii, ``` etc.)
        v = re.sub(r"^```[a-zA-Z]*\n?", "", v)
        # Strip closing fence
        v = re.sub(r"\n?```$", "", v)
        return v.strip()

    @field_validator("caption", "view_hint")
    @classmethod
    def _clean_text(cls, v: str) -> str:
        return v.strip()


class DiagramResponse(BaseModel):
    """Structured diagram payload returned by the LLM."""

    diagrams: list[Diagram] = Field(
        default_factory=list,
        description="2–4 diagrams for this note.",
    )

    @field_validator("diagrams", mode="before")
    @classmethod
    def _coerce_null(cls, v: object) -> object:
        return [] if v is None else v

    def has_mermaid(self) -> bool:
        return any(d.diagram_type == "mermaid" for d in self.diagrams)

    def is_empty(self) -> bool:
        return len(self.diagrams) == 0 or all(
            not d.content.strip() for d in self.diagrams
        )


