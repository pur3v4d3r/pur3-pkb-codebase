# Orchestration
# ════════════════════════════════════════════════════════════════════════════

@dataclass
class RunStats:
    """Aggregate counters for a batch run."""

    scanned: int = 0
    diagrammed: int = 0
    cached: int = 0
    skipped_empty: int = 0
    failed: int = 0
    written: int = 0


def diagram_all(
    notes: list[V6Note],
    client: OllamaClient,
    *,
    model: str,
    bypass_cache: bool,
    dry_run: bool,
    output_dir: Path | None,
    input_dir: Path,
) -> tuple[list[DiagramResult], RunStats]:
    """Run diagram generation across all ``notes``.

    Args:
        notes: Pre-scanned candidates (from :func:`scan_notes`).
        client: Active :class:`OllamaClient`.
        model: Ollama model name.
        bypass_cache: When True, ignore the LLM response cache.
        dry_run: When True, compute but do not write anything to disk.
        output_dir: Optional mirror directory for output files.  When
            ``None``, notes are overwritten in place.
        input_dir: Original input directory (used to compute relative paths
            when ``output_dir`` is set).

    Returns:
        ``(results, stats)`` — the list of per-note outcomes and aggregate
        counters.
    """
    stats = RunStats(scanned=len(notes))
    results: list[DiagramResult] = []
    today = dt.date.today().isoformat()
    progress_ctx, advance = _make_progress(len(notes))

    with progress_ctx as progress:
        task_id = (
            progress.add_task("Diagramming", total=len(notes))
            if progress else None
        )
        for note in notes:
            try:
                result = diagram_one(
                    note, client, model=model, bypass_cache=bypass_cache,
                )
            except OllamaUnavailableError:
                logger.error("Ollama unavailable — aborting run")
                raise
            except Exception as e:  # defensive catch for unexpected errors
                logger.exception("Unexpected error diagramming %s", note.path.name)
                result = DiagramResult(
                    note=note, ok=False, cached=False, response=None,
                    error=f"unexpected: {e}",
                )

            if not result.ok or result.response is None:
                if result.error == "LLM returned no usable diagrams":
                    stats.skipped_empty += 1
                    logger.warning("No diagrams for %s: %s", note.path.name, result.error)
                else:
                    stats.failed += 1
                    logger.error("Failed %s: %s", note.path.name, result.error)
                results.append(result)
                advance(progress, task_id)
                continue

            if result.cached:
                stats.cached += 1
            stats.diagrammed += 1

            pass_n = note.diagram_passes + 1
            diagram_section = build_diagram_section(
                result.response, pass_n=pass_n, today=today,
            )
            # Strip any pre-existing diagram section before inserting the new
            # one — ensures re-diagram runs (pass ≥ 2) don't double-up blocks.
            clean_body = re.sub(
                r"## 📊 Visual Overview[\s\S]*?(?=\n# |\Z)", "", note.body,
            )
            new_body = insert_diagram_section(clean_body, diagram_section)
            new_fm = update_frontmatter(
                note.frontmatter, pass_n=pass_n, model=model, today=today,
            )
            new_content = render_frontmatter(new_fm) + "\n" + new_body

            dest = _resolve_output_path(note.path, input_dir, output_dir)
            if not dry_run:
                try:
                    write_note_atomic(dest, new_content)
                    stats.written += 1
                    logger.info(
                        "Diagrammed %s (pass %d, %s)",
                        note.path.name, pass_n,
                        "cache-hit" if result.cached else "live",
                    )
                except OSError as e:
                    logger.error("Write failed for %s: %s", dest, e)
                    stats.failed += 1
                    results.append(DiagramResult(
                        note=note, ok=False, cached=result.cached,
                        response=result.response, error=f"write failed: {e}",
                    ))
                    advance(progress, task_id)
                    continue
            else:
                logger.info(
                    "Would diagram %s (pass %d, %s)",
                    note.path.name, pass_n,
                    "cache-hit" if result.cached else "live",
                )

            results.append(DiagramResult(
                note=note, ok=True, cached=result.cached,
                response=result.response, error=None, written_path=dest,
            ))
            advance(progress, task_id)

    return results, stats


def _resolve_output_path(
    src: Path,
    input_dir: Path,
    output_dir: Path | None,
) -> Path:
    """Compute the destination path for a note.

    Args:
        src: Source note path.
        input_dir: Root of the input scan.
        output_dir: Optional override destination root.

    Returns:
        ``src`` when ``output_dir`` is ``None`` (in-place overwrite),
        otherwise ``output_dir / relative_path``.
    """
    if output_dir is None:
        return src
    try:
        rel = src.relative_to(input_dir)
    except ValueError:
        rel = Path(src.name)
    return output_dir / rel


def _make_progress(total: int):
    """Return ``(context_manager, advance_fn)``.  No-op when rich is absent."""
    if not _RICH_AVAILABLE or total == 0:
        from contextlib import nullcontext

        def _noop(_p, _t) -> None:  # noqa: ANN001
            return None

        return nullcontext(None), _noop

    progress = Progress(
        SpinnerColumn(),
        TextColumn("[progress.description]{task.description}"),
        BarColumn(),
        MofNCompleteColumn(),
        TimeElapsedColumn(),
    )

    def _advance(p, t) -> None:
        if p is not None and t is not None:
            p.advance(t)

    return progress, _advance


