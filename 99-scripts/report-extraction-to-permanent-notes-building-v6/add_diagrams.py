# Body insertion
# ════════════════════════════════════════════════════════════════════════════

#: Matches the YAML frontmatter closing fence at the very start of the body.
_LEADING_WHITESPACE_RE = re.compile(r"^\s+")


def insert_diagram_section(body: str, diagram_section: str) -> str:
    """Insert ``diagram_section`` between the frontmatter and the ``# Title``.

    ``body`` is the text *after* ``parse_frontmatter()`` strips the YAML
    block, so it starts with optional whitespace then the ``# Title`` heading.
    The diagram section is prepended before the title heading.

    Args:
        body: The note body without YAML frontmatter.
        diagram_section: The rendered diagram section string.

    Returns:
        The updated body with the diagram section inserted at the top.

    Example:
        >>> insert_diagram_section("\\n# My Title\\n...", "## Diagrams\\n...")
        '## Diagrams\\n...\\n\\n# My Title\\n...'
    """
    stripped = body.lstrip("\n")
    return diagram_section.rstrip("\n") + "\n\n" + stripped


# ════════════════════════════════════════════════════════════════════════════
# Frontmatter update
# ════════════════════════════════════════════════════════════════════════════

def update_frontmatter(
    fm: dict[str, Any],
    *,
    pass_n: int,
    model: str,
    today: str,
) -> dict[str, Any]:
    """Return a new frontmatter dict with diagram provenance fields applied.

    Only writes/updates provenance sub-fields and ``updated``; all
    user-editable fields (``status``, ``tags``, ``aliases``, ``importance``,
    etc.) are left untouched.

    Args:
        fm: Existing parsed frontmatter dict.
        pass_n: Current diagram pass number (usually 1).
        model: Ollama model name used for the diagrams.
        today: ISO-8601 date string.

    Returns:
        A shallow copy of ``fm`` with diagram provenance applied.
    """
    out = dict(fm)
    out["updated"] = today
    provenance = dict(out.get("provenance") or {})
    provenance["diagram-passes"] = pass_n
    provenance["diagram-model"] = model
    provenance["last-diagrammed"] = today
    out["provenance"] = provenance
    return out


# ════════════════════════════════════════════════════════════════════════════
# File write
# ════════════════════════════════════════════════════════════════════════════

def write_note_atomic(path: Path, content: str) -> None:
    """Atomic write via ``.tmp → replace`` to avoid partial file states.

    Args:
        path: Destination file path.
        content: Full UTF-8 content to write.

    Raises:
        OSError: When the write or rename fails.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(content, encoding="utf-8")
    tmp.replace(path)


