def configure_logging(verbosity: int, quiet: bool) -> None:
    """Set root logger level based on CLI verbosity flags.

    Args:
        verbosity: Count of ``-v`` flags (0 = WARNING, 1 = INFO, 2+ = DEBUG).
        quiet: When True, suppress output below ERROR.
    """
    if quiet:
        level = logging.ERROR
    elif verbosity >= 2:
        level = logging.DEBUG
    elif verbosity == 1:
        level = logging.INFO
    else:
        level = logging.WARNING
    logging.basicConfig(
        level=level,
        format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
    )


def main(argv: list[str] | None = None) -> int:
    """Main entry point for the diagram-generation pipeline.

    Args:
        argv: Argument vector (defaults to ``sys.argv[1:]``).

    Returns:
        Exit code: 0 = success, 1 = unexpected error, 2 = input dir not found,
        4 = no notes found, 5 = strict mode with failures, 6 = Ollama unavailable,
        130 = interrupted.
    """
    parser = build_parser()
    args = parser.parse_args(argv)
    configure_logging(args.verbose, args.quiet)

    # ── Discover notes ────────────────────────────────────────────────────
    try:
        notes = scan_notes(
            args.input_dir,
            name_filter=args.note,
            re_diagram=args.re_diagram,
            limit=args.limit,
        )
    except FileNotFoundError as e:
        logger.error("%s", e)
        return 2

    if not notes:
        logger.warning(
            "No eligible notes found in %s (filter=%r, re_diagram=%s).",
            args.input_dir, args.note, args.re_diagram,
        )
        return 4

    logger.info(
        "Found %d note(s) to diagram%s.",
        len(notes),
        " (dry-run — no files will be written)" if args.dry_run else "",
    )

    # ── Connect to Ollama ─────────────────────────────────────────────────
    try:
        client = OllamaClient(
            url=config_v3.OLLAMA_URL,
            model=args.model,
            cache_dir=config_v3.LLM_CACHE_DIR,
        )
    except Exception as e:
        logger.error("Failed to initialise Ollama client: %s", e)
        return 6

    # ── Run diagram pipeline ──────────────────────────────────────────────
    try:
        results, stats = diagram_all(
            notes,
            client,
            model=args.model,
            bypass_cache=args.bypass_cache,
            dry_run=args.dry_run,
            output_dir=args.output_dir,
            input_dir=args.input_dir,
        )
    except OllamaUnavailableError:
        logger.error(
            "Ollama is unreachable at %s. Start Ollama and retry.",
            config_v3.OLLAMA_URL,
        )
        return 6
    except KeyboardInterrupt:
        logger.warning("Interrupted by user.")
        return 130
    except Exception:
        logger.exception("Unexpected pipeline error.")
        return 1

    # ── Summary ───────────────────────────────────────────────────────────
    action = "Would diagram" if args.dry_run else "Diagrammed"
    logger.warning(
        "%s %d/%d notes (%d cached, %d written, %d failed, %d empty).",
        action,
        stats.diagrammed,
        stats.scanned,
        stats.cached,
        stats.written,
        stats.failed,
        stats.skipped_empty,
    )

    if args.strict and stats.failed > 0:
        return 5
    return 0


