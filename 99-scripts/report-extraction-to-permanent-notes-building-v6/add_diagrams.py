def _safe_str(v: Any, default: str = "") -> str:
    if v is None:
        return default
    if isinstance(v, list):
        return ", ".join(str(x) for x in v if x)
    return str(v)


def load_note(path: Path) -> V6Note:
    """Parse a V6 markdown note into a :class:`V6Note`.

    Raises:
        NoteParseError: On I/O error, empty file, or missing frontmatter.
    """
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as e:
        raise NoteParseError(f"Cannot read {path}: {e}") from e
    if not text.strip():
        raise NoteParseError(f"Empty file: {path}")
    try:
        fm, body = parse_frontmatter(text)
    except Exception as e:
        raise NoteParseError(f"Frontmatter parse failed for {path}: {e}") from e
    if not isinstance(fm, dict) or not fm:
        raise NoteParseError(f"Missing or non-mapping frontmatter: {path}")

    title = _safe_str(fm.get("title")) or path.stem.replace("-", " ").title()
    domain = _safe_str(fm.get("domain"), "general")
    parent = _safe_str(fm.get("parent-concept"), "")

    provenance = fm.get("provenance") or {}
    diagram_passes = 0
    if isinstance(provenance, dict):
        try:
            diagram_passes = int(provenance.get("diagram-passes", 0) or 0)
        except (TypeError, ValueError):
            diagram_passes = 0

    return V6Note(
        path=path,
        title=title,
        domain=domain,
        parent_concept=parent,
        frontmatter=dict(fm),
        body=body,
        diagram_passes=diagram_passes,
    )


def scan_notes(
    input_dir: Path,
    *,
    name_filter: str | None,
    re_diagram: bool,
    limit: int | None,
) -> list[V6Note]:
    """Discover candidate notes for diagram generation under ``input_dir``.

    Skips notes that already have ``provenance.diagram-passes >= 1`` unless
    ``re_diagram`` is True.

    Args:
        input_dir: Root directory to scan for ``*.md`` files.
        name_filter: Case-insensitive substring filter on filename stems.
        re_diagram: When True, include notes already processed.
        limit: Cap on the number of notes returned (for batch sizing).

    Returns:
        Sorted list of :class:`V6Note` candidates.

    Raises:
        FileNotFoundError: When ``input_dir`` does not exist.
    """
    if not input_dir.is_dir():
        raise FileNotFoundError(f"Input directory not found: {input_dir}")
    notes: list[V6Note] = []
    for path in sorted(input_dir.glob("*.md")):
        if name_filter and name_filter.lower() not in path.stem.lower():
            continue
        try:
            note = load_note(path)
        except NoteParseError as e:
            logger.warning("Skipping unparseable note %s: %s", path.name, e)
            continue
        if not re_diagram and note.diagram_passes >= 1:
            logger.debug("Skipping %s — already diagrammed", path.name)
            continue
        notes.append(note)
        if limit is not None and len(notes) >= limit:
            break
    return notes


