def configure_logging(verbosity: int, quiet: bool) -> None:
    """Configure root logger from CLI verbosity flags."""
    level = (
        logging.ERROR if quiet
        else logging.DEBUG if verbosity >= 2
        else logging.INFO if verbosity == 1
        else logging.WARNING
    )
    logging.basicConfig(
        level=level,
        format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
        stream=sys.stderr,
    )


def _auto_detect_vault_root(folder: Path) -> Path:
    """Walk upward from folder to find a .obsidian marker directory."""
    for candidate in [folder.resolve(), *folder.resolve().parents]:
        if (candidate / ".obsidian").is_dir():
            logger.info("Auto-detected vault root: %s", candidate)
            return candidate
    fallback = Path.cwd()
    logger.info("No .obsidian directory found; using CWD as vault root: %s", fallback)
    return fallback


def main(argv: list[str] | None = None) -> int:
    """Main entry point.

    Returns:
        0=success, 1=unexpected error, 2=path not found, 3=permission denied, 130=interrupted.
    """
    parser = build_parser()
    args = parser.parse_args(argv)
    configure_logging(args.verbose, args.quiet)

    folder: Path = args.folder.resolve()
    vault_root: Path = args.vault.resolve() if args.vault else _auto_detect_vault_root(folder)

    if args.dry_run:
        glob_fn = folder.rglob if args.recursive else folder.glob
        try:
            file_count = sum(1 for _ in glob_fn("*.md")) if folder.is_dir() else 0
        except PermissionError as exc:
            logger.error("Cannot access folder: %s", exc)
            return 3
        print(f"# Dry Run — wiki_orphan_scanner v{__version__}\n")
        print(f"**Scan folder:** `{folder}`  ")
        print(f"**Vault root:** `{vault_root}`  ")
        print(f"**Recursive:** {'yes' if args.recursive else 'no'}  ")
        print(f"**Files that would be scanned:** {file_count}")
        return 0

    try:
        vault_index = build_vault_index(vault_root)
        result = scan_folder(folder, vault_index, recursive=args.recursive)
    except (FolderNotFoundError, VaultNotFoundError) as exc:
        logger.error("%s", exc)
        return 2
    except PermissionError as exc:
        logger.error("Permission denied: %s", exc)
        return 3
    except KeyboardInterrupt:
        logger.warning("Interrupted by user.")
        return 130
    except Exception:
        logger.exception("Unexpected error during scan.")
        return 1

    report = generate_report(result, folder, vault_root, recursive=args.recursive)

    if args.output:
        try:
            args.output.write_text(report, encoding="utf-8")
            if not args.quiet:
                print(f"Report written to: {args.output}", file=sys.stderr)
        except OSError as exc:
            logger.error("Cannot write output file: %s", exc)
            return 3
    else:
        print(report)

    if args.seed:
        exclude = not args.include_synthetic
        seed_report = generate_seed_report(result, exclude_synthetic=exclude)
        try:
            args.seed.parent.mkdir(parents=True, exist_ok=True)
            args.seed.write_text(seed_report, encoding="utf-8")
            if not args.quiet:
                unique_count = seed_report.count("\n| ") - 1  # subtract header row
                print(
                    f"Seed list written to: {args.seed}  ({unique_count} links, sorted by frequency)",
                    file=sys.stderr,
                )
        except OSError as exc:
            logger.error("Cannot write seed file: %s", exc)
            return 3

    return 0


if __name__ == "__main__":
    sys.exit(main())
