# Matches [[Note]], [[Note|Alias]], [[Note#Heading]], [[Note#Heading|Alias]].
# Negative lookbehind on '!' excludes embedded files: ![[image.png]].
WIKI_LINK_RE = re.compile(
    r"(?<!!)\[\[([^\[\]|#\n]+)(?:[#|][^\[\]]*)?\]\]",
    re.IGNORECASE,
)

CODE_FENCE_RE = re.compile(r"```.*?```", re.DOTALL)
INLINE_CODE_RE = re.compile(r"`[^`\n]+`")

logger = logging.getLogger(__name__)


class WikiOrphanScannerError(Exception):
    """Base exception for wiki_orphan_scanner errors."""


class FolderNotFoundError(WikiOrphanScannerError):
    """Raised when the specified scan folder does not exist or is not a directory."""


class VaultNotFoundError(WikiOrphanScannerError):
    """Raised when the specified vault root does not exist or is not a directory."""


@dataclass(frozen=True)
class BrokenLink:
    """A [[wiki-link]] whose target note was not found in the vault index.

    Attributes:
        source_file: Absolute path to the file containing this link.
        link_target: Raw link target text as written (pre-normalisation).
        line_number: 1-based line number of the link in source_file.
    """

    source_file: Path
    link_target: str
    line_number: int


@dataclass
class ScanResult:
    """Aggregated results of a single folder scan run.

    Attributes:
        scanned_files: Number of .md files examined.
        total_links: Total wiki-links encountered across all files.
        broken_links: BrokenLink instances for every unresolvable link.
        vault_note_count: Size of the vault index used for resolution.
    """

    scanned_files: int = 0
    total_links: int = 0
    broken_links: list[BrokenLink] = field(default_factory=list)
    vault_note_count: int = 0


def build_vault_index(vault_root: Path) -> set[str]:
    """Build a case-insensitive set of all note stems in the vault.

    Obsidian resolves [[Wiki Links]] by matching the link target
    case-insensitively against the stem (filename without extension) of
    every .md file anywhere in the vault. This function replicates that.

    Args:
        vault_root: Root directory of the Obsidian vault.

    Returns:
        Lowercase set of .md stems across the entire vault tree.

    Raises:
        VaultNotFoundError: If vault_root does not exist or is not a directory.
    """
    if not vault_root.exists():
        raise VaultNotFoundError(f"Vault root does not exist: {vault_root}")
    if not vault_root.is_dir():
        raise VaultNotFoundError(f"Vault root is not a directory: {vault_root}")

    index: set[str] = {md.stem.lower() for md in vault_root.rglob("*.md")}
    logger.info("Vault index: %d notes indexed from %s", len(index), vault_root)
    return index


def strip_code_spans(text: str) -> str:
    """Remove fenced code blocks and inline code spans from Markdown text.

    Fenced blocks are replaced with equivalent newlines so line numbers of
    surrounding content are preserved. Inline code spans are zeroed out.

    Args:
        text: Raw Markdown content.

    Returns:
        Text safe to run wiki-link extraction against.
    """
    def _preserve_newlines(m: re.Match) -> str:
        return "\n" * m.group(0).count("\n")

    text = CODE_FENCE_RE.sub(_preserve_newlines, text)
    return INLINE_CODE_RE.sub("", text)


def extract_wiki_links(content: str) -> list[tuple[str, int]]:
    """Extract all wiki-link targets and their 1-based line numbers.

    Handles:
      [[Note Name]]
      [[Note Name|Display Alias]]
      [[Note Name#Heading]]
      [[Note Name#Heading|Alias]]
      [[folder/Note Name]]  — resolved to stem only

    Args:
        content: Markdown text with code spans already stripped.

    Returns:
        List of (note_name, line_number) tuples.

    Example:
        >>> extract_wiki_links("See [[PKM]] and [[Zettelkasten#Origins|ZK]].")
        [('PKM', 1), ('Zettelkasten', 1)]
    """
    results: list[tuple[str, int]] = []
    for line_num, line in enumerate(content.splitlines(), start=1):
        for m in WIKI_LINK_RE.finditer(line):
            raw = m.group(1).strip()
            # For path-based links ([[folder/Note]]), keep only the final segment stem.
            # NOTE: stem-only is a conservative approximation of Obsidian's shortest-path
            # resolution; two notes with the same stem in different folders may produce
            # false positives (known limitation, v1.0.0).
            if "/" in raw or "\\" in raw:
                note_name = Path(raw).stem
            else:
                note_name = raw
            results.append((note_name, line_num))
    return results


def resolve_link(link_target: str, vault_index: set[str]) -> bool:
    """Check whether a wiki-link target maps to an existing vault note.

    Args:
        link_target: The raw note name from the wiki-link (e.g. "My Note").
        vault_index: Lowercase set of note stems from build_vault_index().

    Returns:
        True if the link resolves to a known note, False otherwise.
    """
    stem = Path(link_target).stem if link_target.lower().endswith(".md") else link_target
    return stem.lower() in vault_index


def scan_folder(
    folder: Path,
    vault_index: set[str],
    *,
    recursive: bool = False,
) -> ScanResult:
    """Scan Markdown files in a folder for wiki-links with missing targets.

    Args:
        folder: Directory whose .md files are scanned for source links.
        vault_index: Set of lowercase note stems from build_vault_index().
        recursive: If True, descend into subdirectories of folder.

    Returns:
        ScanResult with all broken links found.

    Raises:
        FolderNotFoundError: If folder does not exist or is not a directory.
    """
    if not folder.exists():
        raise FolderNotFoundError(f"Scan folder does not exist: {folder}")
    if not folder.is_dir():
        raise FolderNotFoundError(f"Scan folder is not a directory: {folder}")

    result = ScanResult(vault_note_count=len(vault_index))
    glob_fn = folder.rglob if recursive else folder.glob

    for md_file in sorted(glob_fn("*.md")):
        logger.debug("Scanning: %s", md_file)
        result.scanned_files += 1

        try:
            raw = md_file.read_text(encoding="utf-8", errors="replace")
        except OSError as exc:
            logger.warning("Cannot read %s — skipping: %s", md_file, exc)
            continue

        clean = strip_code_spans(raw)
        links = extract_wiki_links(clean)
        result.total_links += len(links)

        for target, line_num in links:
            if not resolve_link(target, vault_index):
                result.broken_links.append(
                    BrokenLink(source_file=md_file, link_target=target, line_number=line_num)
                )
                logger.debug("Broken: %s:%d → [[%s]]", md_file.name, line_num, target)

    logger.info(
        "Scan complete — files: %d  links: %d  broken: %d",
        result.scanned_files,
        result.total_links,
        len(result.broken_links),
    )
    return result


def generate_report(
    result: ScanResult,
    scanned_folder: Path,
    vault_root: Path,
    *,
    recursive: bool,
) -> str:
    """Render a ScanResult as a Markdown orphan report.

    Args:
        result: Populated ScanResult from scan_folder().
        scanned_folder: Folder that was scanned (display only).
        vault_root: Vault root used for resolution (display only).
        recursive: Whether the scan was recursive (display only).

    Returns:
        Complete Markdown string suitable for direct use in Obsidian.
    """
    out: list[str] = []
    broken_count = len(result.broken_links)
    pct = (broken_count / result.total_links * 100) if result.total_links else 0.0

    out += [
        "# Wiki-Link Orphan Report",
        "",
        f"> **Scan folder:** `{scanned_folder}`  ",
        f"> **Vault root:** `{vault_root}`  ",
        f"> **Recursive:** {'yes' if recursive else 'no'}",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|--------|-------|",
        f"| Files scanned | {result.scanned_files} |",
        f"| Notes in vault index | {result.vault_note_count:,} |",
        f"| Total wiki-links found | {result.total_links:,} |",
        f"| **Broken links (no target note)** | **{broken_count:,}** |",
        f"| Broken link rate | {pct:.1f}% |",
        "",
    ]

    if broken_count == 0:
        out += [
            "> [!success] All Clear",
            "> No broken wiki-links detected — every link resolves to an existing note.",
            "",
        ]
        return "\n".join(out)

    out += [
        "> [!warning] Broken Links Detected",
        f"> {broken_count} wiki-link(s) point to notes that do not exist in the vault.",
        "",
    ]

    grouped: dict[Path, list[BrokenLink]] = defaultdict(list)
    for bl in sorted(result.broken_links, key=lambda b: (str(b.source_file), b.line_number)):
        grouped[bl.source_file].append(bl)

    out += ["## Broken Links by File", ""]

    for src in sorted(grouped):
        file_links = grouped[src]
        out += [
            f"### `{src.name}`",
            "",
            f"**Path:** `{src}`  ",
            f"**Missing links:** {len(file_links)}",
            "",
            "| Line | Missing Target |",
            "|-----:|----------------|",
        ]
        for bl in file_links:
            out.append(f"| {bl.line_number} | `[[{bl.link_target}]]` |")
        out.append("")

    counts: Counter[str] = Counter(bl.link_target for bl in result.broken_links)
    sorted_targets = sorted(counts.items(), key=lambda x: (-x[1], x[0].casefold()))

    out += [
        "## Unique Missing Note Targets (by Reference Count)",
        "",
        f"*{len(sorted_targets)} distinct note name(s) referenced but absent from the vault — sorted by frequency:*",
        "",
        "| Count | Wiki-Link |",
        "|------:|-----------|",
    ]
    for target, count in sorted_targets:
        out.append(f"| {count} | `[[{target}]]` |")
    out.append("")

    return "\n".join(out)


def generate_seed_report(
    result: ScanResult,
    *,
    exclude_synthetic: bool = True,
) -> str:
    """Render a frequency-ranked seed list of orphan wiki-links.

    Produces a Markdown file listing every unique missing link target sorted
    by how many times it is referenced — highest first — so the user can
    prioritise which permanent notes to create first.

    Args:
        result: Populated ScanResult from scan_folder().
        exclude_synthetic: If True, omit entries containing '-synthetic-seed-'.

    Returns:
        Markdown string suitable for use as a note-creation seed list.
    """
    sources: dict[str, list[BrokenLink]] = defaultdict(list)
    for bl in result.broken_links:
        if exclude_synthetic and "-synthetic-seed-" in bl.link_target.lower():
            continue
        sources[bl.link_target].append(bl)

    sorted_items = sorted(
        sources.items(), key=lambda x: (-len(x[1]), x[0].casefold())
    )

    lines: list[str] = [
        "# Seed Wiki-Links — Priority Ranked by Reference Count",
        "",
        f"**Total unique missing links:** {len(sorted_items)}  ",
        f"**Synthetic-seed entries excluded:** {'yes' if exclude_synthetic else 'no'}",
        "",
        "---",
        "",
    ]
    for target, occurrences in sorted_items:
        count = len(occurrences)
        lines += [
            f"## [[{target}]] — {count} reference(s)",
            "",
            "| Source File | Line |",
            "|-------------|-----:|",
        ]
        for bl in sorted(occurrences, key=lambda b: (b.source_file.name.casefold(), b.line_number)):
            lines.append(f"| `{bl.source_file.name}` | {bl.line_number} |")
        lines.append("")
    return "\n".join(lines)


