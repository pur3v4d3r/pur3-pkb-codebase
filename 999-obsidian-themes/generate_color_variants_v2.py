def _resolve_paths(cfg: dict) -> tuple[Path, Path, Path, Path]:
    """Resolve (vault_root, theme_source, snippets_source, output_root)."""
    vault = Path(cfg.get("vault_root", DEFAULT_VAULT_ROOT))
    theme_source = vault / cfg.get("theme_source", DEFAULT_THEME_SOURCE_REL)
    snippets_source = vault / cfg.get("snippets_source", DEFAULT_SNIPPETS_SOURCE_REL)
    output_root = vault / cfg.get("output_dir", DEFAULT_OUTPUT_REL)
    return vault, theme_source, snippets_source, output_root


def _validate_sources(theme_source: Path, snippets_source: Path) -> None:
    """Ensure source theme and snippets directories exist."""
    if not theme_source.exists():
        raise SourceNotFoundError(f"Theme source not found: {theme_source}")
    if not (theme_source / "theme.css").exists():
        raise SourceNotFoundError(
            f"theme.css missing in source theme: {theme_source}"
        )
    if not snippets_source.exists():
        # Snippets are optional — warn but don't fail.
        logger.warning("Snippets source missing: %s", snippets_source)


def generate_variant(
    scheme: ColorScheme,
    cfg: dict,
    *,
    dry_run: bool = False,
    write_preview: bool = True,
) -> VariantStats:
    """Generate a single color variant on disk.

    Args:
        scheme: The ``ColorScheme`` to generate.
        cfg: Parsed config dict (provides paths and global params).
        dry_run: If True, do all work but write no files.
        write_preview: If True, also write an SVG palette preview.

    Returns:
        ``VariantStats`` describing the work done.

    Raises:
        SourceNotFoundError: If the source theme is missing.
    """
    _, theme_source, snippets_source, output_root = _resolve_paths(cfg)
    _validate_sources(theme_source, snippets_source)

    base_theme = theme_source.name  # e.g. "V4D3R Crimson"
    base_prefix = base_theme.split()[0] if " " in base_theme else base_theme

    # Determine source hue (per-scheme override > config > auto-detect).
    source_hue = (
        scheme.source_hue
        if scheme.source_hue is not None
        else cfg.get("source_hue")
    )
    if source_hue is None:
        css_text = (theme_source / "theme.css").read_text(encoding="utf-8")
        detected = detect_source_hue(
            css_text, sat_min=cfg.get("sat_min", DEFAULT_SAT_MIN)
        )
        if detected is None:
            raise ColorVariantError(
                "Could not auto-detect source hue (no chromatic colors found). "
                "Set 'source_hue' in config or scheme."
            )
        source_hue = detected
        logger.info("Auto-detected source hue: %.1f°", source_hue)

    sat_min = float(cfg.get("sat_min", DEFAULT_SAT_MIN))
    tolerance = float(cfg.get("hue_tolerance", DEFAULT_HUE_TOLERANCE))
    preserve = tuple(scheme.preserve_patterns or cfg.get(
        "preserve_patterns", DEFAULT_PRESERVE_PATTERNS
    ))

    output_dir = output_root / f"{base_prefix}-{safe_slug(scheme.name).title()}"
    theme_dir = output_dir / f"{base_prefix} {scheme.name}"
    snippets_dir = output_dir / "snippets"

    files_written = 0
    transforms = 0
    errors: list[str] = []

    # ── theme.css ──────────────────────────────────────────────────────
    src_theme_css = (theme_source / "theme.css").read_text(encoding="utf-8")
    new_theme_css, n = transform_css(
        src_theme_css, scheme, source_hue, sat_min, tolerance, preserve
    )
    transforms += n
    if not dry_run:
        write_text_atomic(theme_dir / "theme.css", new_theme_css)
        files_written += 1

    # ── manifest.json ──────────────────────────────────────────────────
    manifest = generate_manifest(scheme, base_prefix)
    if not dry_run:
        write_text_atomic(theme_dir / "manifest.json", manifest)
        files_written += 1

    # ── README.md ──────────────────────────────────────────────────────
    readme = generate_readme(scheme, base_prefix, source_hue)
    if not dry_run:
        write_text_atomic(theme_dir / "README.md", readme)
        files_written += 1

    # ── snippets ───────────────────────────────────────────────────────
    if snippets_source.exists():
        for snippet_path in sorted(snippets_source.glob("*.css")):
            try:
                src = snippet_path.read_text(encoding="utf-8")
            except OSError as e:
                errors.append(f"Read failed: {snippet_path}: {e}")
                continue
            new_text, n = transform_css(
                src, scheme, source_hue, sat_min, tolerance, preserve
            )
            transforms += n
            if not dry_run:
                try:
                    write_text_atomic(snippets_dir / snippet_path.name, new_text)
                    files_written += 1
                except OSError as e:
                    errors.append(f"Write failed: {snippet_path.name}: {e}")

    # ── SVG preview ────────────────────────────────────────────────────
    if write_preview and not dry_run:
        svg = generate_swatch_svg(scheme, source_hue)
        write_text_atomic(output_dir / "preview.svg", svg)
        files_written += 1

    return VariantStats(
        scheme=scheme.name,
        output_dir=str(output_dir),
        files_written=files_written,
        colors_transformed=transforms,
        errors=tuple(errors),
    )


def _generate_one_for_pool(
    scheme_dict: dict, cfg: dict, dry_run: bool, write_preview: bool
) -> VariantStats:
    """Worker entry point for ProcessPoolExecutor (must be top-level)."""
    scheme = ColorScheme(
        name=scheme_dict["name"],
        slug=scheme_dict["slug"],
        target_hue=scheme_dict["target_hue"],
        description=scheme_dict.get("description", ""),
        secondary_hue=scheme_dict.get("secondary_hue"),
        chroma_mult=scheme_dict.get("chroma_mult", 1.0),
        lightness_offset=scheme_dict.get("lightness_offset", 0.0),
        source_hue=scheme_dict.get("source_hue"),
        preserve_patterns=tuple(scheme_dict.get("preserve_patterns", ())),
    )
    return generate_variant(
        scheme, cfg, dry_run=dry_run, write_preview=write_preview
    )


def generate_variants(
    schemes: list[ColorScheme],
    cfg: dict,
    *,
    dry_run: bool = False,
    write_preview: bool = True,
    jobs: int = 1,
) -> list[VariantStats]:
    """Generate multiple variants, optionally in parallel."""
    if jobs <= 1 or len(schemes) <= 1:
        results: list[VariantStats] = []
        for s in schemes:
            logger.info("Generating: %s", s.name)
            results.append(
                generate_variant(s, cfg, dry_run=dry_run, write_preview=write_preview)
            )
        return results

    # Multiprocessing path: ColorScheme is dataclass-frozen but we serialize
    # via dicts to keep worker contract simple and pickle-safe.
    payloads = [asdict(s) for s in schemes]
    results = []
    with ProcessPoolExecutor(max_workers=jobs) as pool:
        futures = {
            pool.submit(_generate_one_for_pool, p, cfg, dry_run, write_preview): p["name"]
            for p in payloads
        }
        for fut in as_completed(futures):
            name = futures[fut]
            try:
                stats = fut.result()
                logger.info("Done: %s (%d transforms)",
                            stats.scheme, stats.colors_transformed)
                results.append(stats)
            except Exception as e:
                logger.error("Variant '%s' failed: %s", name, e)
                results.append(VariantStats(
                    scheme=name, output_dir="", errors=(str(e),)
                ))
    return results


