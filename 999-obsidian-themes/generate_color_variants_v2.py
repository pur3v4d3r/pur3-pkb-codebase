def generate_swatch_svg(
    scheme: ColorScheme, source_hue: float, sample_lightnesses: tuple[float, ...] = (
        0.25, 0.40, 0.55, 0.70, 0.85,
    )
) -> str:
    """Render an SVG palette preview of the scheme.

    Produces a strip of swatches at varying lightnesses for both the
    primary and (if set) secondary hue, with hex labels.
    """
    swatch_w, swatch_h, pad = 120, 80, 12
    rows = 2 if scheme.secondary_hue is not None else 1
    cols = len(sample_lightnesses)
    width = pad + cols * (swatch_w + pad)
    height = pad + rows * (swatch_h + pad) + 30

    parts: list[str] = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" '
        f'height="{height}" viewBox="0 0 {width} {height}">',
        '<style>text{font-family:monospace;font-size:11px;fill:#fff;'
        'text-anchor:middle;}</style>',
        f'<rect width="100%" height="100%" fill="#111"/>',
        f'<text x="{width/2}" y="20" font-size="14">{scheme.name} '
        f'(hue {scheme.target_hue}°, source {source_hue:.0f}°)</text>',
    ]
    hues_to_render = [(scheme.target_hue, "primary")]
    if scheme.secondary_hue is not None:
        hues_to_render.append((scheme.secondary_hue, "secondary"))

    for row, (hue, _label) in enumerate(hues_to_render):
        for col, L in enumerate(sample_lightnesses):
            r, g, b = oklch_to_rgb(L, 0.18 * scheme.chroma_mult, hue)
            x = pad + col * (swatch_w + pad)
            y = 30 + pad + row * (swatch_h + pad)
            hex_str = rgb_to_hex(r, g, b)
            parts.append(
                f'<rect x="{x}" y="{y}" width="{swatch_w}" '
                f'height="{swatch_h}" fill="{hex_str}"/>'
            )
            parts.append(
                f'<text x="{x + swatch_w/2}" y="{y + swatch_h - 6}">'
                f'{hex_str}</text>'
            )

    parts.append('</svg>')
    return "\n".join(parts)


