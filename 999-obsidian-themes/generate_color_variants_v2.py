# ═════════════════════════════════════════════════════════════════════════
# Color math — sRGB ⇄ Linear ⇄ OKLab ⇄ OKLCH
# ═════════════════════════════════════════════════════════════════════════
#
# OKLab/OKLCH is a perceptually uniform color space designed by Björn
# Ottosson (2020). Hue rotations in OKLCH preserve apparent lightness
# and chroma, eliminating the "muddy yellow / washed-out cyan" failure
# mode of HSL rotations.
# Reference: https://bottosson.github.io/posts/oklab/
#
# DESIGN: Pure-Python implementation (no numpy/colour-science deps) —
# this keeps the script stdlib-only and trivially deployable.

def _srgb_to_linear(c: float) -> float:
    """Inverse sRGB gamma. Input/output in [0, 1]."""
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def _linear_to_srgb(c: float) -> float:
    """Apply sRGB gamma. Input/output in [0, 1]."""
    if c <= 0.0:
        return 0.0
    if c >= 1.0:
        return 1.0
    return 12.92 * c if c <= 0.0031308 else 1.055 * (c ** (1 / 2.4)) - 0.055


def rgb_to_oklab(r: int, g: int, b: int) -> tuple[float, float, float]:
    """Convert sRGB (0–255) to OKLab (L, a, b)."""
    rl = _srgb_to_linear(r / 255.0)
    gl = _srgb_to_linear(g / 255.0)
    bl = _srgb_to_linear(b / 255.0)

    # Linear sRGB → LMS (Ottosson matrices)
    l = 0.4122214708 * rl + 0.5363325363 * gl + 0.0514459929 * bl
    m = 0.2119034982 * rl + 0.6806995451 * gl + 0.1073969566 * bl
    s = 0.0883024619 * rl + 0.2817188376 * gl + 0.6299787005 * bl

    l_, m_, s_ = (
        math.copysign(abs(l) ** (1 / 3), l),
        math.copysign(abs(m) ** (1 / 3), m),
        math.copysign(abs(s) ** (1 / 3), s),
    )

    L = 0.2104542553 * l_ + 0.7936177850 * m_ - 0.0040720468 * s_
    a = 1.9779984951 * l_ - 2.4285922050 * m_ + 0.4505937099 * s_
    b_ = 0.0259040371 * l_ + 0.7827717662 * m_ - 0.8086757660 * s_
    return L, a, b_


def _oklab_to_linear_rgb(L: float, a: float, b: float) -> tuple[float, float, float]:
    """OKLab → linear sRGB (no clipping, no gamma). May return out-of-gamut values."""
    l_ = L + 0.3963377774 * a + 0.2158037573 * b
    m_ = L - 0.1055613458 * a - 0.0638541728 * b
    s_ = L - 0.0894841775 * a - 1.2914855480 * b

    l = l_ ** 3
    m = m_ ** 3
    s = s_ ** 3

    rl = +4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
    gl = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
    bl = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s
    return rl, gl, bl


def _in_linear_gamut(rl: float, gl: float, bl: float, eps: float = 1e-4) -> bool:
    """True iff a linear-sRGB triple sits inside the displayable cube."""
    return (-eps <= rl <= 1.0 + eps
            and -eps <= gl <= 1.0 + eps
            and -eps <= bl <= 1.0 + eps)


def oklab_to_rgb(L: float, a: float, b: float) -> tuple[int, int, int]:
    """Convert OKLab to sRGB (0–255).

    Uses **hue-preserving gamut mapping**: when the requested OKLab is
    outside the sRGB gamut, chroma is reduced via binary search while
    holding L and hue constant. This avoids the hue shifts that simple
    per-channel clipping produces for highly saturated colors.
    """
    rl, gl, bl = _oklab_to_linear_rgb(L, a, b)
    if not _in_linear_gamut(rl, gl, bl):
        # Hold L and hue (atan2(b,a)); shrink chroma (||a,b||) until in-gamut.
        lo, hi = 0.0, 1.0
        for _ in range(20):  # ~6 decimal places of precision is plenty
            mid = (lo + hi) / 2.0
            tr, tg, tb = _oklab_to_linear_rgb(L, a * mid, b * mid)
            if _in_linear_gamut(tr, tg, tb):
                lo = mid
            else:
                hi = mid
        rl, gl, bl = _oklab_to_linear_rgb(L, a * lo, b * lo)

    r = _linear_to_srgb(max(0.0, min(1.0, rl)))
    g = _linear_to_srgb(max(0.0, min(1.0, gl)))
    b_out = _linear_to_srgb(max(0.0, min(1.0, bl)))

    return (
        max(0, min(255, round(r * 255))),
        max(0, min(255, round(g * 255))),
        max(0, min(255, round(b_out * 255))),
    )


def oklab_to_oklch(L: float, a: float, b: float) -> tuple[float, float, float]:
    """Convert OKLab to OKLCH (L, C, h°)."""
    C = math.hypot(a, b)
    h = math.degrees(math.atan2(b, a)) % 360.0
    return L, C, h


def oklch_to_oklab(L: float, C: float, h: float) -> tuple[float, float, float]:
    """Convert OKLCH (h in degrees) back to OKLab."""
    rad = math.radians(h)
    return L, C * math.cos(rad), C * math.sin(rad)


def rgb_to_oklch(r: int, g: int, b: int) -> tuple[float, float, float]:
    """Convenience: sRGB → OKLCH (L, C, h°)."""
    return oklab_to_oklch(*rgb_to_oklab(r, g, b))


def oklch_to_rgb(L: float, C: float, h: float) -> tuple[int, int, int]:
    """Convenience: OKLCH (h in degrees) → sRGB (0–255)."""
    return oklab_to_rgb(*oklch_to_oklab(L, C, h))


# ═════════════════════════════════════════════════════════════════════════
# Color rotation logic
# ═════════════════════════════════════════════════════════════════════════

def hue_distance(h1: float, h2: float) -> float:
    """Shortest angular distance between two hues in degrees (0–180)."""
    diff = abs((h1 - h2 + 180.0) % 360.0 - 180.0)
    return diff


def lerp_hue(h1: float, h2: float, t: float) -> float:
    """Interpolate between two hues along the shortest arc."""
    diff = ((h2 - h1 + 180.0) % 360.0) - 180.0
    return (h1 + t * diff) % 360.0


def in_source_band(
    h: float, source_hue: float, tolerance: float
) -> bool:
    """True iff hue ``h`` is within ``tolerance`` degrees of ``source_hue``."""
    return hue_distance(h, source_hue) <= tolerance


def transform_color_oklch(
    r: int,
    g: int,
    b: int,
    scheme: ColorScheme,
    source_hue: float,
    sat_min: float,
    tolerance: float,
) -> Optional[tuple[int, int, int]]:
    """Rotate a color into the scheme's hue.

    Returns ``None`` if the color is greyscale (low chroma) or outside
    the source-hue band — caller should leave such colors untouched.
    """
    if (r, g, b) == (0, 0, 0):
        return None
    L, C, h = rgb_to_oklch(r, g, b)

    # Normalize chroma to a 0..1-ish scale for the saturation check.
    # OKLCH chroma typically ranges 0..0.4 for sRGB-displayable colors.
    if (C / 0.4) < sat_min:
        return None
    if not in_source_band(h, source_hue, tolerance):
        return None

    # Compute hue offset from source center, preserving relative variation
    # within the source band (so a darker accent stays darker after rotation).
    hue_offset = ((h - source_hue + 180.0) % 360.0) - 180.0

    if scheme.secondary_hue is not None:
        # Dual-tone: bright tones → primary; dark tones → secondary.
        # Lightness range in OKLab is roughly 0..1.
        t = max(0.0, min(1.0, (L - 0.15) / 0.55))
        base = lerp_hue(scheme.secondary_hue, scheme.target_hue, t)
    else:
        base = scheme.target_hue

    new_h = (base + hue_offset) % 360.0
    new_C = max(0.0, C * scheme.chroma_mult)
    new_L = max(0.0, min(1.0, L + scheme.lightness_offset))
    return oklch_to_rgb(new_L, new_C, new_h)


