def install_variant(scheme: ColorScheme, cfg: dict) -> None:
    """Copy a generated variant into the active vault's `.obsidian/`."""
    vault, theme_source, _, output_root = _resolve_paths(cfg)
    base_theme = theme_source.name
    base_prefix = base_theme.split()[0] if " " in base_theme else base_theme

    src_dir = output_root / f"{base_prefix}-{safe_slug(scheme.name).title()}"
    src_theme = src_dir / f"{base_prefix} {scheme.name}"
    src_snippets = src_dir / "snippets"

    if not src_theme.exists():
        raise SourceNotFoundError(
            f"Variant not generated yet: {src_theme}. "
            "Run `generate` first."
        )

    # Theme
    dest_theme = vault / ".obsidian" / "themes" / f"{base_prefix} {scheme.name}"
    dest_theme.mkdir(parents=True, exist_ok=True)
    for f in src_theme.iterdir():
        shutil.copy2(f, dest_theme / f.name)
    logger.info("Installed theme to: %s", dest_theme)

    # Snippets
    if src_snippets.exists():
        dest_snip = vault / ".obsidian" / "snippets"
        dest_snip.mkdir(parents=True, exist_ok=True)
        n = 0
        for f in src_snippets.glob("*.css"):
            shutil.copy2(f, dest_snip / f.name)
            n += 1
        logger.info("Installed %d snippet(s) to: %s", n, dest_snip)


def validate_variant(variant_dir: Path) -> dict:
    """Run WCAG contrast checks on a variant's `theme.css`.

    Pairs background-like variables (containing 'background', 'bg') against
    foreground-like ones (containing 'text', 'foreground', 'fg', 'accent').
    """
    theme_css_path = variant_dir / "theme.css"
    if not theme_css_path.exists():
        # Try nested layout: <variant_dir>/<theme name>/theme.css
        candidates = list(variant_dir.glob("*/theme.css"))
        if not candidates:
            raise SourceNotFoundError(f"theme.css not found in {variant_dir}")
        theme_css_path = candidates[0]

    css = theme_css_path.read_text(encoding="utf-8")
    var_colors: dict[str, tuple[int, int, int]] = {}

    for line in css.splitlines():
        m_def = RE_VAR_DEF_LINE.search(line)
        if not m_def:
            continue
        name = m_def.group(1)
        m_hex = RE_HEX.search(line)
        if m_hex:
            parsed = parse_hex(m_hex.group(0))
            if parsed:
                var_colors[name] = parsed[:3]
                continue
        m_rgba = RE_RGBA.search(line)
        if m_rgba:
            var_colors[name] = (
                int(m_rgba.group(1)), int(m_rgba.group(2)), int(m_rgba.group(3))
            )

    backgrounds = {n: c for n, c in var_colors.items()
                   if re.search(r"(background|^bg-|-bg-|-bg$)", n)}
    foregrounds = {n: c for n, c in var_colors.items()
                   if re.search(r"(text|foreground|^fg-|-fg-|-fg$|accent)", n)}

    pairs: list[tuple[str, str, float, str]] = []
    for fn, fc in foregrounds.items():
        for bn, bc in backgrounds.items():
            r = contrast_ratio(fc, bc)
            pairs.append((fn, bn, r, wcag_grade(r)))

    pairs.sort(key=lambda p: p[2])

    fails = [p for p in pairs if p[3] == "FAIL"]
    return {
        "theme_css": str(theme_css_path),
        "total_pairs": len(pairs),
        "fail_count": len(fails),
        "worst": pairs[:10],
        "best": pairs[-5:] if pairs else [],
    }


