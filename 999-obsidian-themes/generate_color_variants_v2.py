# Hex / rgba parsing
# ═════════════════════════════════════════════════════════════════════════

def parse_hex(hex_str: str) -> Optional[tuple[int, int, int, Optional[int]]]:
    """Parse ``#RGB`` / ``#RGBA`` / ``#RRGGBB`` / ``#RRGGBBAA``."""
    h = hex_str.lstrip("#")
    try:
        if len(h) == 3:
            return int(h[0] * 2, 16), int(h[1] * 2, 16), int(h[2] * 2, 16), None
        if len(h) == 4:
            return (
                int(h[0] * 2, 16), int(h[1] * 2, 16),
                int(h[2] * 2, 16), int(h[3] * 2, 16),
            )
        if len(h) == 6:
            return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), None
        if len(h) == 8:
            return (
                int(h[0:2], 16), int(h[2:4], 16),
                int(h[4:6], 16), int(h[6:8], 16),
            )
    except ValueError:
        return None
    return None


def rgb_to_hex(
    r: int, g: int, b: int, alpha: Optional[int] = None, lowercase: bool = True
) -> str:
    """Format an (R, G, B[, A]) tuple as a hex string."""
    s = f"#{r:02x}{g:02x}{b:02x}" + (f"{alpha:02x}" if alpha is not None else "")
    return s if lowercase else s.upper()


