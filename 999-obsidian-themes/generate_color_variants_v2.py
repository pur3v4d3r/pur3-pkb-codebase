# DESIGN: We tokenize CSS roughly line-by-line so we can correlate a color
# token with the variable name on the same line and apply preserve rules.

RE_HEX = re.compile(r"#([0-9A-Fa-f]{3,4}|[0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})\b")
RE_RGBA = re.compile(
    r"rgba?\(\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})\s*"
    r"(?:,\s*([0-9.]+)\s*)?\)"
)
RE_BARE_RGB = re.compile(
    r"(--[\w-]+\s*:\s*(?:/\*[^*]*\*/\s*)?)"
    r"(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})(?=\s*[;}\n])"
)
RE_VAR_DEF_LINE = re.compile(r"--([\w-]+)\s*:")


def _is_preserved_line(line: str, preserve_res: list[re.Pattern[str]]) -> bool:
    """True if any preserve regex matches a CSS variable on this line."""
    return any(p.search(line) for p in preserve_res)


def transform_css(
    css: str,
    scheme: ColorScheme,
    source_hue: float,
    sat_min: float,
    tolerance: float,
    preserve_patterns: Iterable[str],
) -> tuple[str, int]:
    """Transform every in-band color in a CSS source.

    Returns ``(new_css, transform_count)``.
    """
    preserve_res = [re.compile(p) for p in preserve_patterns]
    counter = 0

    def _maybe_rotate(r: int, g: int, b: int) -> Optional[tuple[int, int, int]]:
        return transform_color_oklch(r, g, b, scheme, source_hue, sat_min, tolerance)

    out_lines: list[str] = []
    for line in css.splitlines(keepends=True):
        if _is_preserved_line(line, preserve_res):
            out_lines.append(line)
            continue

        def _hex_sub(m: re.Match) -> str:
            nonlocal counter
            parsed = parse_hex(m.group(0))
            if parsed is None:
                return m.group(0)
            r, g, b, a = parsed
            new = _maybe_rotate(r, g, b)
            if new is None:
                return m.group(0)
            counter += 1
            was_upper = any(c.isupper() for c in m.group(1) if c.isalpha())
            return rgb_to_hex(*new, alpha=a, lowercase=not was_upper)

        def _rgba_sub(m: re.Match) -> str:
            nonlocal counter
            r, g, b = int(m.group(1)), int(m.group(2)), int(m.group(3))
            alpha = m.group(4)
            new = _maybe_rotate(r, g, b)
            if new is None:
                return m.group(0)
            counter += 1
            nr, ng, nb = new
            return (
                f"rgba({nr}, {ng}, {nb}, {alpha})" if alpha is not None
                else f"rgb({nr}, {ng}, {nb})"
            )

        def _bare_sub(m: re.Match) -> str:
            nonlocal counter
            prefix = m.group(1)
            r, g, b = int(m.group(2)), int(m.group(3)), int(m.group(4))
            new = _maybe_rotate(r, g, b)
            if new is None:
                return m.group(0)
            counter += 1
            nr, ng, nb = new
            return f"{prefix}{nr}, {ng}, {nb}"

        line = RE_HEX.sub(_hex_sub, line)
        line = RE_RGBA.sub(_rgba_sub, line)
        line = RE_BARE_RGB.sub(_bare_sub, line)
        out_lines.append(line)

    return "".join(out_lines), counter


# ═════════════════════════════════════════════════════════════════════════
# Source-hue auto-detection
# ═════════════════════════════════════════════════════════════════════════

def detect_source_hue(
    css_text: str, sat_min: float = DEFAULT_SAT_MIN
) -> Optional[float]:
    """Estimate the dominant accent hue in a CSS source.

    Strategy: collect all sufficiently-chromatic colors, weight each by its
    chroma, and return the chroma-weighted circular mean of their hues.
    Returns ``None`` if no chromatic colors found.
    """
    samples: list[tuple[float, float]] = []  # (hue, chroma_weight)

    for m in RE_HEX.finditer(css_text):
        parsed = parse_hex(m.group(0))
        if parsed is None:
            continue
        r, g, b, _ = parsed
        _, C, h = rgb_to_oklch(r, g, b)
        if (C / 0.4) >= sat_min:
            samples.append((h, C))

    for m in RE_RGBA.finditer(css_text):
        r, g, b = int(m.group(1)), int(m.group(2)), int(m.group(3))
        _, C, h = rgb_to_oklch(r, g, b)
        if (C / 0.4) >= sat_min:
            samples.append((h, C))

    if not samples:
        return None

    # Chroma-weighted circular mean.
    sin_sum = sum(w * math.sin(math.radians(h)) for h, w in samples)
    cos_sum = sum(w * math.cos(math.radians(h)) for h, w in samples)
    if sin_sum == 0 and cos_sum == 0:
        return None
    return math.degrees(math.atan2(sin_sum, cos_sum)) % 360.0


# ═════════════════════════════════════════════════════════════════════════
# WCAG contrast
# ═════════════════════════════════════════════════════════════════════════

def relative_luminance(r: int, g: int, b: int) -> float:
    """WCAG relative luminance for sRGB."""
    rl = _srgb_to_linear(r / 255.0)
    gl = _srgb_to_linear(g / 255.0)
    bl = _srgb_to_linear(b / 255.0)
    return 0.2126 * rl + 0.7152 * gl + 0.0722 * bl


def contrast_ratio(c1: tuple[int, int, int], c2: tuple[int, int, int]) -> float:
    """WCAG contrast ratio between two sRGB colors (1.0–21.0)."""
    L1 = relative_luminance(*c1)
    L2 = relative_luminance(*c2)
    lo, hi = sorted((L1, L2))
    return (hi + 0.05) / (lo + 0.05)


def wcag_grade(ratio: float) -> str:
    """Map a contrast ratio to a human-readable grade."""
    if ratio >= WCAG_AAA_NORMAL:
        return "AAA"
    if ratio >= WCAG_AA_NORMAL:
        return "AA"
    if ratio >= WCAG_AA_LARGE:
        return "AA-large"
    return "FAIL"


