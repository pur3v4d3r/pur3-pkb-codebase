def configure_logging(verbosity: int, quiet: bool) -> None:
    """Configure root logger from CLI verbosity flags."""
    if quiet:
        level = logging.ERROR
    elif verbosity >= 2:
        level = logging.DEBUG
    elif verbosity == 1:
        level = logging.INFO
    else:
        level = logging.WARNING
    logging.basicConfig(
        level=level,
        format="%(asctime)s [%(levelname)s] %(message)s",
        datefmt="%H:%M:%S",
    )


def _resolve_schemes(
    cfg: dict, requested_slugs: list[str] | None, all_flag: bool
) -> list[ColorScheme]:
    """Resolve which schemes to operate on from CLI flags."""
    available = schemes_from_config(cfg)
    if all_flag or not requested_slugs:
        return available if all_flag else available
    by_slug = {s.slug: s for s in available}
    missing = [s for s in requested_slugs if s not in by_slug]
    if missing:
        raise SchemeNotFoundError(
            f"Unknown scheme(s): {', '.join(missing)}. "
            f"Run `list` to see available."
        )
    return [by_slug[s] for s in requested_slugs]


