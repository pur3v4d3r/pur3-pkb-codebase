def load_config(path: Optional[Path]) -> dict:
    """Load JSON config from disk, or return defaults if path is None.

    Raises:
        ConfigError: If the file exists but is malformed.
    """
    if path is None:
        return default_config_dict()
    if not path.exists():
        raise ConfigError(f"Config file not found: {path}")
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        raise ConfigError(f"Invalid JSON in {path}: {e}") from e


def schemes_from_config(cfg: dict) -> list[ColorScheme]:
    """Extract a list of ``ColorScheme`` from a parsed config dict."""
    raw = cfg.get("schemes", [])
    if not isinstance(raw, list):
        raise ConfigError("Config 'schemes' must be a list.")
    out: list[ColorScheme] = []
    for i, s in enumerate(raw):
        try:
            out.append(
                ColorScheme(
                    name=s["name"],
                    slug=s["slug"],
                    target_hue=float(s["target_hue"]),
                    description=s.get("description", ""),
                    secondary_hue=(
                        float(s["secondary_hue"])
                        if s.get("secondary_hue") is not None else None
                    ),
                    chroma_mult=float(s.get("chroma_mult", 1.0)),
                    lightness_offset=float(s.get("lightness_offset", 0.0)),
                    source_hue=(
                        float(s["source_hue"])
                        if s.get("source_hue") is not None else None
                    ),
                    preserve_patterns=tuple(s.get("preserve_patterns", ())),
                )
            )
        except (KeyError, TypeError, ValueError) as e:
            raise ConfigError(
                f"Invalid scheme at index {i}: {e}"
            ) from e
    return out


